def part_label(p) -> str:
    return p.partName or (p.id if isinstance(p.id, str) else "Part")


def name_unnamed_parts(score) -> list[str]:
    """Give a part that arrived with no name one a reader would use.

    An ABC tune's melody, and any notation file whose parts carry no
    <part-name>, came in named nothing and was shown as "Part" -- beside its
    fader level on the mixer knob that read "Part 7". One part is the
    "Melody"; several are "Part 1", "Part 2" by position. A grand staff's
    staves are left alone: they are named through their group. Run once, at
    import (workspace.create_score); a name already given is never touched.
    """
    from music21 import stream
    parts = list(score.parts)
    given = []
    for index, part in enumerate(parts):
        if (part.partName or "").strip() or isinstance(part, stream.PartStaff):
            continue
        part.partName = "Melody" if len(parts) == 1 else f"Part {index + 1}"
        given.append(part.partName)
    return given


def list_part_labels(score) -> list[str]:
    return [part_label(p) for p in score.parts]


def bar_label(n) -> str:
    """How a REPORT names the bar a note stands in.

    music21 numbers a pickup 0, and that number is a real address here -- an
    element address may say `m0` and `--from-measure 0` reaches it. But no page
    prints a bar 0: an engraver leaves the pickup unnumbered and calls the
    first full bar 1, which is also where `_measures_in_range` starts when no
    range is given. So a report that says "bar 0" names a bar the reader cannot
    find, and one did: a whistle range report read "3 notes (B3 in bars 0, 3,
    and 11)" for a tune whose bar 0 was its two-note upbeat.

    The pickup is NAMED rather than numbered, and the number is left out of the
    report entirely rather than carried beside the name -- a report is prose
    the chat agent writes from, and a `0` anywhere in it is a `0` that can be
    printed. Op ARGUMENTS are the other surface and keep their integers.

    **BAR 0 IS NOT THE SAME THING AS A PICKUP**, and the first version of this
    said it was. music21's ABC reader numbers EVERY tune from 0, pickup or no
    pickup, so `number == 0` called the ordinary first bar of every jig and
    reel in the library "the pickup". What distinguishes them is
    `paddingLeft` -- the beats missing from the head of the bar -- which is 0
    on a full bar and positive on a real anacrusis:

        Morrison's Jig (no pickup)   bar 0, paddingLeft 0.0, a full 6/8 bar
        Star of the County Down      bar 0, paddingLeft 2.0, two eighths

    A bar 0 that is a whole bar is REPORTED AS 0, which is also what the
    transport and the play head call it, so at least the app agrees with
    itself. That every ABC import is numbered from zero while every MusicXML
    one is numbered from one is a wider oddity, and it is in BACKLOG.
    """
    number = n.measureNumber
    if number != 0:
        return str(number)
    measure = n.getContextByClass(stream.Measure)
    if measure is not None and (measure.paddingLeft or 0) > 0:
        return "pickup"
    return str(number)


def find_parts(score, names: list[str]):
    """Match parts by name (case-insensitive, exact then substring) or by index ('#0', '#1', ...)."""
    matched = []
    all_parts = list(score.parts)
    for name in names:
        want = name.strip().lower()
        if want.startswith("#"):
            try:
                idx = int(want[1:])
                hits = [all_parts[idx]]
            except (ValueError, IndexError):
                raise ValueError(f"Bad part index '{name}'. Score has {len(all_parts)} parts (#0..#{len(all_parts) - 1})")
            for p in hits:
                if p not in matched:
                    matched.append(p)
            continue
        # `part_label` too: it is what the refusal below LISTS, and a part
        # with no name is listed as "Part" -- which the chat then sent back
        # and was refused ("No part matches 'Part'. Available parts:
        # ['Part']"). A name the error offers has to be a name it accepts.
        exact = [p for p in score.parts
                 if (p.partName or "").lower() == want
                 or (p.partAbbreviation or "").lower() == want
                 or (isinstance(p.id, str) and p.id.lower() == want)
                 or part_label(p).lower() == want]
        hits = exact or [p for p in score.parts if want in (p.partName or "").lower()]
        if not hits:
            raise ValueError(f"No part matches '{name}'. Available parts: {list_part_labels(score)}")
        for p in hits:
            if p not in matched:
                matched.append(p)
    return matched


def rename_part(part, new_name: str, abbreviation: str | None = None) -> dict:
    old = part_label(part)
    part.partName = new_name
    if abbreviation:
        part.partAbbreviation = abbreviation
    return {"from": old, "to": new_name}


def keep_parts(score, names: list[str]) -> list[str]:
    matched = find_parts(score, names)
    removed = []
    for p in list(score.parts):
        if p not in matched:
            removed.append(part_label(p))
            score.remove(p, recurse=True)
    return removed


def remove_parts(score, names: list[str]) -> list[str]:
    matched = find_parts(score, names)
    if len(matched) == len(list(score.parts)):
        raise ValueError("Refusing to remove every part in the score.")
    removed = []
    for p in matched:
        removed.append(part_label(p))
        score.remove(p, recurse=True)
    return removed


def merge_parts(score, names: list[str], new_name: str, clef_name: str = "treble") -> dict:
    """Merge several parts into one staff, each source part becoming its own voice.

    Lossless: every note, rest, and duration of every source part is preserved
    (measure by measure, as independent voices on the shared staff). The merged
    part takes the place of the first source part in score order.
    """
    if clef_name not in CLEFS:
        raise ValueError(f"Unknown clef '{clef_name}'. Choose from: {sorted(CLEFS)}")
    sources = find_parts(score, names)
    if len(sources) < 2:
        raise ValueError("merge-parts needs at least two distinct parts")

    note_total = sum(1 for p in sources for n in p.recurse().notes for _ in n.pitches)
    measures_by_part = [list(p.getElementsByClass(stream.Measure)) for p in sources]
    n_measures = max(len(ms) for ms in measures_by_part)

    merged = stream.Part()
    merged.partName = new_name
    merged.partAbbreviation = new_name

    for idx in range(n_measures):
        ref = next((ms[idx] for ms in measures_by_part if idx < len(ms)), None)
        m_new = stream.Measure(number=ref.number if ref is not None else idx + 1)
        if idx == 0:
            m_new.insert(0.0, CLEFS[clef_name]())
        for kind in ("TimeSignature", "KeySignature"):
            for el in ref.getElementsByClass(kind):
                m_new.insert(el.offset, copy.deepcopy(el))
        for vi, ms in enumerate(measures_by_part):
            if idx >= len(ms):
                continue
            voice = stream.Voice(id=str(vi + 1))
            for el in ms[idx].notesAndRests:
                voice.insert(el.offset, copy.deepcopy(el))
            m_new.insert(0.0, voice)
        merged.append(m_new)

    labels = [part_label(p) for p in sources]
    order = [p for p in score.parts if p not in sources[1:]]
    order[order.index(sources[0])] = merged
    _set_part_order(score, order)

    merged_total = sum(1 for n in merged.recurse().notes for _ in n.pitches)
    if merged_total != note_total:
        raise RuntimeError(f"Note-count mismatch after merge: sources had {note_total}, merged has {merged_total}")
    cleaned = _normalize_part(merged)
    return {"merged": labels, "into": new_name, "clef": clef_name,
            "voices": len(sources), "notes_before": note_total, "notes_after": merged_total,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0)}


def split_bass(score, name: str, bass_name: str, chords_name: str,
               instrument_name: str | None = None) -> dict:
    """Split one part into a bass staff and a chords staff.

    The source part is chordified into time slices. At every slice the lowest
    sounding pitch goes to the bass staff (bass clef); all remaining pitches
    become a chord on the chords staff (treble clef). The chords staff replaces
    the source part in score order; the bass staff is appended below it.
    """
    src = find_parts(score, [name])[0]
    sliced = src.chordify(addTies=True)

    bass_part = stream.Part()
    bass_part.partName = bass_name
    bass_part.partAbbreviation = bass_name
    chords_part = stream.Part()
    chords_part.partName = chords_name
    chords_part.partAbbreviation = chords_name

    slice_pitches = 0
    bass_notes = 0
    chord_notes = 0

    for m in sliced.getElementsByClass(stream.Measure):
        mb = stream.Measure(number=m.number)
        mc = stream.Measure(number=m.number)
        if m.number <= 1 and m is sliced.getElementsByClass(stream.Measure).first():
            mb.insert(0.0, m21clef.BassClef())
            mc.insert(0.0, m21clef.TrebleClef())
        for kind in ("TimeSignature", "KeySignature"):
            for el in m.getElementsByClass(kind):
                mb.insert(el.offset, copy.deepcopy(el))
                mc.insert(el.offset, copy.deepcopy(el))
        for el in m.notesAndRests:
            off, dur = el.offset, el.quarterLength
            if el.isRest or not el.pitches:
                mb.insert(off, m21note.Rest(quarterLength=dur))
                mc.insert(off, m21note.Rest(quarterLength=dur))
                continue
            pitches = sorted(el.pitches, key=lambda p: p.ps)
            slice_pitches += len(pitches)

            b = m21note.Note(pitches[0])
            b.quarterLength = dur
            if el.tie is not None:
                b.tie = copy.deepcopy(el.tie)
            mb.insert(off, b)
            bass_notes += 1

            upper = pitches[1:]
            if upper:
                c = m21note.Note(upper[0]) if len(upper) == 1 else m21chord.Chord(upper)
                c.quarterLength = dur
                if el.tie is not None:
                    c.tie = copy.deepcopy(el.tie)
                mc.insert(off, c)
                chord_notes += len(upper)
            else:
                mc.insert(off, m21note.Rest(quarterLength=dur))
        bass_part.append(mb)
        chords_part.append(mc)

    if bass_notes + chord_notes != slice_pitches:
        raise RuntimeError(f"Split lost pitches: {slice_pitches} sliced vs {bass_notes + chord_notes} placed")

    if instrument_name:
        for p in (bass_part, chords_part):
            p.insert(0.0, m21instrument.fromString(instrument_name))

    old_label = part_label(src)
    order = list(score.parts)
    idx = order.index(src)
    order[idx] = chords_part
    order.insert(idx + 1, bass_part)
    _set_part_order(score, order)

    hidden = sum(_normalize_part(p).get("hidden", 0) for p in (bass_part, chords_part))
    return {"split": old_label, "chords_staff": chords_name, "bass_staff": bass_name,
            "redundant_accidentals_hidden": hidden,
            "slices": bass_notes, "bass_notes": bass_notes, "chord_notes": chord_notes,
            "note": "sustained notes are sliced at each attack (tied where the source was tied)"}


def rhythm_faults(score_or_part) -> list[tuple[int, int, str]]:
    """Everything wrong with a score's rhythm, as (part index, bar, description).

    Structured because the write guard compares one score's faults against
    another's, and it has to know WHICH bar went wrong: an edit is refused for
    breaking a bar that was sound before, not for carrying along a bar that was
    already broken when the music was imported.

    One definition, used by the write guard, by the ops that risk breaking it,
    and by engine/scripts/check_rhythm.py — three copies of "sound rhythm"
    would drift apart.

    Two faults:

    - a bar holding more music than it is long. Measured on each voice's END
      TIME, never the sum of its durations: notes sounding together sum to more
      than they occupy, and summing made a collapsed measure look correct.
      Under-fill is fine (a pickup, a partial bar before a repeat, a last bar).
    - two things sounding at once inside ONE voice. A voice is a single line;
      simultaneous pitches are a chord, which is one object. `stripTies` leaves
      such pairs behind, and while they look harmless in memory the writer lays
      them end to end, which is how a bar silently grows.
    """
    from music21 import harmony

    faults: list[tuple[int, int, str]] = []
    for index, part in enumerate(getattr(score_or_part, "parts", None) or [score_or_part]):
        for measure in part.getElementsByClass(stream.Measure):
            limit = measure.barDuration.quarterLength
            for container in (list(measure.voices) or [measure]):
                events = sorted((el.offset, el.quarterLength)
                                for el in container.notesAndRests
                                if not isinstance(el, harmony.Harmony))
                if not events:
                    continue
                end = max(off + dur for off, dur in events)
                if end > limit + 1e-6:
                    faults.append((index + 1, measure.number,
                                   f"{float(end):g} beats of music in a "
                                   f"{float(limit):g}-beat bar"))
                for (o1, d1), (o2, _) in zip(events, events[1:]):
                    if o1 + d1 > o2 + 1e-6:
                        faults.append((index + 1, measure.number,
                                       f"two notes sound at once in one voice "
                                       f"({float(o1):g}+{float(d1):g} runs into "
                                       f"{float(o2):g})"))
                        break
    return faults


def rhythm_problems(score_or_part) -> list[str]:
    """The same faults, phrased for a person to read."""
    return [f"part {part} bar {bar}: {what}"
            for part, bar, what in rhythm_faults(score_or_part)]


def _strip_ties_safely(part) -> str | None:
    """`stripTies`, but only when the result survives inspection.

    music21's `stripTies` is the right tool and usually correct, but on some
    material it leaves two notes sounding at once in one voice, which becomes a
    longer bar the moment the score is written. Rather than corrupt the part,
    rehearse the whole thing on a copy — strip, re-tie at the barlines, check —
    and only touch the real part if it came out sound.

    Returns None when applied, or the reason it was left alone.
    """
    trial = copy.deepcopy(part)
    try:
        trial.stripTies(inPlace=True, matchByPitch=True)
        trial.makeTies(inPlace=True)
    except Exception as e:  # noqa: BLE001 — any failure means "do not touch it"
        return f"{type(e).__name__}: {e}"
    problems = rhythm_problems(trial)
    if problems:
        return problems[0]
    part.stripTies(inPlace=True, matchByPitch=True)
    return None


def consolidate_ties(score, names: list[str]) -> list[dict]:
    """Merge runs of tied same-pitch notes into single notes of combined duration.

    A quarter tied to a half becomes a dotted half; notes genuinely spanning a
    barline get re-tied at the barline on export. Pitch content and total
    durations are unchanged — this is purely notational cleanup.

    A part whose ties music21 cannot merge cleanly is reported and left as it
    was, rather than rewritten into something that no longer plays the same.
    """
    report = []
    for p in find_parts(score, names):
        before = len(list(p.recurse().notes))
        skipped = _strip_ties_safely(p)
        after = len(list(p.recurse().notes))
        entry = {"part": part_label(p), "events_before": before,
                 "events_after": after, "merged": before - after}
        if skipped:
            entry["skipped"] = ("left unchanged: consolidating would have changed "
                                f"the rhythm ({skipped})")
        report.append(entry)
    return report


def limit_part(score, name: str, max_pitch: str | None = None, monophonic: bool = False) -> dict:
    """Enforce playability constraints on a part, always sacrificing higher notes.

    --monophonic: chords are reduced to their lowest note; where two notes
    overlap in time, the higher one is removed.
    --max-pitch: notes strictly above this pitch are removed (replaced by
    rests); chords keep only their pitches at or below it.
    """
    part = find_parts(score, [name])[0]
    maxp = m21pitch.Pitch(max_pitch) if max_pitch else None
    stats = {"part": part_label(part), "chords_reduced": 0, "overlaps_removed": 0, "high_removed": 0}

    for m in part.getElementsByClass(stream.Measure):
        containers = list(m.voices) or [m]
        for cont in containers:
            if monophonic:
                for el in list(cont.notes):
                    if el.isChord:
                        lo = min(el.pitches, key=lambda x: x.ps)
                        n = m21note.Note(lo)
                        n.quarterLength = el.quarterLength
                        if el.tie is not None:
                            n.tie = copy.deepcopy(el.tie)
                        cont.replace(el, n)
                        stats["chords_reduced"] += 1
                kept = []
                for el in sorted(cont.notes, key=lambda e: e.offset):
                    dropped = False
                    while kept and el.offset < kept[-1].offset + kept[-1].quarterLength - 1e-6:
                        prev = kept[-1]
                        if min(p.ps for p in el.pitches) < min(p.ps for p in prev.pitches):
                            cont.remove(prev)
                            kept.pop()
                            stats["overlaps_removed"] += 1
                        else:
                            cont.remove(el)
                            stats["overlaps_removed"] += 1
                            dropped = True
                            break
                    if not dropped:
                        kept.append(el)
            if maxp is not None:
                for el in list(cont.notes):
                    keep = [x for x in el.pitches if x.ps <= maxp.ps]
                    if len(keep) == len(el.pitches):
                        continue
                    stats["high_removed"] += len(el.pitches) - len(keep)
                    if keep:
                        n = m21note.Note(keep[0]) if len(keep) == 1 else m21chord.Chord(keep)
                        n.quarterLength = el.quarterLength
                        if el.tie is not None:
                            n.tie = copy.deepcopy(el.tie)
                        cont.replace(el, n)
                    else:
                        cont.replace(el, m21note.Rest(quarterLength=el.quarterLength))
    if maxp is not None:
        stats["max_pitch"] = maxp.nameWithOctave
    stats["redundant_accidentals_hidden"] = _normalize_part(part).get("hidden", 0)
    return stats


def _measures_in_range(part, from_measure: int | None, to_measure: int | None) -> list:
    """The part's Measure objects whose numbers fall in the inclusive range
    (None = open end)."""
    lo = from_measure if from_measure is not None else 1
    out = []
    for m in part.recurse().getElementsByClass(stream.Measure):
        if m.number < lo:
            continue
        if to_measure is not None and m.number > to_measure:
            continue
        out.append(m)
    return out


def _will_print(part) -> int:
    """How many accidentals this part would ENGRAVE as it stands."""
    total = 0
    for n in part.recurse().notes:
        # .pitches, which both a Note and a Chord have -- a `getattr` default
        # of (n.pitch,) is evaluated eagerly and a Chord has no `.pitch`
        for pitch in n.pitches:
            acc = pitch.accidental
            if acc is not None and acc.displayStatus is not False:
                total += 1
    return total


def _normalize_part(part) -> dict:
    """`normalize_accidentals` for one part, for the ops that hold the part
    itself rather than its name."""
    label = part_label(part)
    if not part.getElementsByClass(stream.Measure):
        # nothing to scope an accidental to; say so rather than pretend
        return {"part": label, "skipped": "no measures"}
    before = _will_print(part)
    part.makeAccidentals(inPlace=True, overrideStatus=True,
                         cautionaryNotImmediateRepeat=False)
    after = _will_print(part)
    return {"part": label, "printed_before": before, "printed_now": after,
            "hidden": before - after}


def normalize_accidentals(score, names: list[str] | None = None) -> dict:
    """Recompute which accidentals PRINT, from each part's own written key.

    Display only. No pitch, no spelling, no octave and no key signature is
    touched -- only `displayStatus`, which decides whether the glyph is drawn.

    Every op that changes pitches or spelling runs this on the parts it
    touched, because the alternative is what a user actually reported: "you've
    put a lot of accidental sharps in the alto saxophone part that are in the
    key signature so it's just making it hard to read". Two music21 behaviours
    combine to produce that.

    First, an op that assigns a new `Accidental` (respell does, note by note)
    gets one whose `displayStatus` is None, and the MusicXML writer prints an
    accidental whose status is None.

    Second, and the reason a fresh fixture cannot show the bug: music21 runs
    `makeAccidentals` at most ONCE per stream and records it in `streamStatus`.
    A score built in memory is normalised by the exporter on its way out; a
    score that has been written and read back -- which is every version in the
    workspace -- never is. So the redundant accidentals survive every
    subsequent write. `overrideStatus=True` is what makes this recompute rather
    than respect the stale answer.

    Each part is judged by the key signature ON ITS OWN STAFF, which for a
    transposing instrument is the WRITTEN key: an E-flat alto's part in A major
    must not have its sharps printed just because concert pitch has none.

    `cautionaryNotImmediateRepeat=False` because the ask was to REMOVE
    redundant accidentals; the default adds cautionary ones and would make the
    page busier than it started.
    """
    targets = find_parts(score, names) if names else list(score.parts)
    report = [_normalize_part(part) for part in targets]
    return {"parts": report,
            "hidden": sum(r.get("hidden", 0) for r in report)}


def transpose(score, interval_str: str, names: list[str] | None = None,
              from_measure: int | None = None, to_measure: int | None = None) -> dict:
    """Transpose by a named interval ('M2', 'm-3') or a semitone count ('-3', '5').

    With from_measure/to_measure set, only measures in that inclusive range are
    transposed (in the named parts, or in every part).
    """
    s = str(interval_str).strip()
    itv = m21interval.Interval(int(s)) if re.fullmatch(r"-?\d+", s) else m21interval.Interval(s)
    ranged = from_measure is not None or to_measure is not None
    if ranged:
        targets = find_parts(score, names) if names else list(score.parts)
        touched = 0
        for p in targets:
            for m in _measures_in_range(p, from_measure, to_measure):
                m.transpose(itv, inPlace=True)
                touched += 1
        scope = [part_label(p) for p in targets] if names else "all parts"
        # the pitches moved, so what prints is recomputed against the key they
        # moved INTO -- see normalize_accidentals
        cleaned = normalize_accidentals(score, names)
        return {"interval": itv.niceName, "direction": itv.direction.name.lower(),
                "scope": scope,
                "measures": f"{from_measure or 1}-{to_measure if to_measure is not None else 'end'}",
                "measures_transposed": touched,
                "chord_diagrams_cleared": clear_stale_diagrams(score, names),
                "redundant_accidentals_hidden": cleaned["hidden"]}
    if names:
        targets = find_parts(score, names)
        for p in targets:
            p.transpose(itv, inPlace=True)
        scope = [part_label(p) for p in targets]
    else:
        score.transpose(itv, inPlace=True)
        scope = "all parts"
    cleaned = normalize_accidentals(score, names)
    return {"interval": itv.niceName, "direction": itv.direction.name.lower(),
            "scope": scope,
            "chord_diagrams_cleared": clear_stale_diagrams(score, names),
            "redundant_accidentals_hidden": cleaned["hidden"]}


# ------------------------------------------------------- diatonic transposition
#
# The chromatic `transpose` above moves every pitch by a fixed number of
# semitones, which moves the KEY with it: a G major tune shifted down eight
# semitones is a B major tune, and its key signature changes to say so. That is
# the right answer for "put this in a singable key" and the wrong one for
# "write me a harmony line a sixth below".
#
# A diatonic transposition moves by SCALE DEGREES and stays in the key. Down a
# sixth in G major sends G to B, A to C, B to D, D to F# -- so some of those
# sixths are major and some are minor, the key signature never changes, and
# nothing accidental appears on the page. Asked for the same thing chromatically
# the arrangement agent had to answer that it could not be done, which is what
# this exists to fix.
#
# music21 has the primitive (`GenericInterval.transposePitchKeyAware`), and the
# work here is the three things around it:
#
#   - **Which key.** Read per part from the key signature ON ITS OWN STAFF, so a
#     transposing instrument is judged by its WRITTEN key, exactly as
#     `normalize_accidentals` judges it. Tracked measure by measure, because a
#     key change mid-piece changes the answer from that bar on. A signature
#     carries no mode, and asking for the major is safe: a natural minor holds
#     the same seven pitches as its relative major, so both give the same
#     degrees. Where there is NO signature at all (optical recognition often
#     drops it) the op refuses and names `--key`, rather than guessing C and
#     silently writing a wrong line.
#
#   - **Notes outside the key.** A chromatic note has no scale degree, so it has
#     to be handled by a rule rather than by the primitive. music21's rule is
#     to carry the alteration along -- in G major a D# down a sixth becomes
#     F##, which is theoretically exact and unwritable. So a result needing a
#     double accidental is respelled to its single-accidental enharmonic, and
#     every note that was outside the key is REPORTED with its bar, because the
#     op made a choice there and the reader is the one who can judge it.
#
#   - **What prints.** Pitches moved, so `normalize_accidentals` recomputes the
#     accidentals against the key they landed in -- the key they started in,
#     here, which is the point.

# 'sixth' and 'third' as the reader says them, because the agent is handed the
# reader's own words and an ordinal is cheaper to accept than to get wrong.
GENERIC_DEGREE_WORDS = {
    "unison": 1, "second": 2, "third": 3, "fourth": 4, "fifth": 5, "sixth": 6,
    "seventh": 7, "octave": 8, "eighth": 8, "ninth": 9, "tenth": 10,
    "eleventh": 11, "twelfth": 12, "thirteenth": 13, "fourteenth": 14,
    "fifteenth": 15, "double octave": 15,
}


def parse_generic_degrees(text) -> int:
    """A signed generic interval number: 6 is up a sixth, -6 down a sixth.

    Accepts what the reader says as well as what the machine wants: '-6',
    'down a sixth', '3rd up', 'octave'. There is no zeroth interval -- a unison
    is 1 -- so 0 is an error and not a no-op.
    """
    s = str(text).strip().lower()
    if not s:
        raise ValueError("no interval given: -6 is down a sixth, 3 is up a third")
    sign = -1 if re.search(r"\bdown\b|\bbelow\b|^-", s) else 1
    body = re.sub(r"\b(up|down|above|below|a|an|the|by)\b", " ", s).strip(" +-")
    number = None
    if m := re.search(r"\d+", body):
        number = int(m.group())
    else:
        for word, value in GENERIC_DEGREE_WORDS.items():
            if word in body:
                number = value
                break
    if number is None:
        raise ValueError(
            f"cannot read {text!r} as a diatonic interval. Give a signed number "
            "of scale steps (-6 is down a sixth, 3 is up a third) or a name "
            "('down a sixth').")
    if number == 0:
        raise ValueError("there is no zeroth interval; a unison is 1")
    return sign * number


def _key_signatures_of(container) -> list:
    """The key signatures in this container, voices included."""
    return list(container.recurse().getElementsByClass(m21key.KeySignature))


def _as_key(signature):
    """A KeySignature read as a Key.

    A signature does not say whether it is major or minor, and for this purpose
    it does not have to: a natural minor holds the same seven pitch classes as
    its relative major, so the scale degrees come out the same either way. A
    Key already knows its own mode and is passed through.
    """
    if isinstance(signature, m21key.Key):
        return signature
    return signature.asKey("major")


def _part_key_at_start(part, override: str | None):
    """The key the part begins in, or None if nothing says.

    `override` wins over the notation, because a score whose signature optical
    recognition dropped is exactly the case the flag is for.
    """
    if override:
        return _named_key(override)
    found = _key_signatures_of(part)
    return _as_key(found[0]) if found else None


def _named_key(text):
    """A key from what a person typed: 'G', 'e', 'Bb', 'E- minor'.

    music21 wants 'B-' where readers write 'Bb', and lower case for minor.
    Tried as given first, so anything music21 already understands is untouched.
    """
    raw = str(text).strip()
    for candidate in (raw, re.sub(r"(?<=[A-Ga-g])b", "-", raw)):
        try:
            return m21key.Key(candidate)
        except Exception:
            continue
    raise ValueError(f"cannot read {text!r} as a key. Try 'G', 'e' for e minor, "
                     "'B-' or 'Bb', 'f#'.")


def _diatonic_pitch(p, generic, key_obj):
    """One pitch moved by scale degrees, and what had to be decided about it.

    Returns (new pitch, outside_the_key, respelled).
    """
    in_key = p.pitchClass in {q.pitchClass for q in key_obj.pitches}
    moved = generic.transposePitchKeyAware(p, key_obj)
    respelled = False
    # F## in G major is the exact answer and not a writable one. Its
    # single-accidental enharmonic says the same thing on a page a player can
    # read; anything still needing two accidentals after the swap is left as it
    # is, because a wrong note is worse than an ugly one.
    if moved.accidental is not None and abs(moved.accidental.alter) >= 2:
        alternative = moved.getEnharmonic()
        if alternative.accidental is None or abs(alternative.accidental.alter) < 2:
            moved, respelled = alternative, True
    return moved, not in_key, respelled


def _move_note_diatonically(n, generic, key_obj, chromatic: list) -> int:
    """Move every pitch of one note or chord. Returns how many pitches moved."""
    pitches = list(n.pitches)
    if not pitches:
        return 0
    out = []
    for p in pitches:
        moved, outside, respelled = _diatonic_pitch(p, generic, key_obj)
        if outside:
            chromatic.append({"bar": bar_label(n),
                              "pitch": p.nameWithOctave,
                              "became": moved.nameWithOctave,
                              "respelled": respelled})
        out.append(moved)
    if isinstance(n, m21chord.Chord):
        n.pitches = tuple(out)
    else:
        n.pitch = out[0]
    return len(out)


def _diatonic_over_measures(part, generic, override, from_measure, to_measure,
                            chromatic: list) -> tuple[int, str]:
    """Transpose a part's notes, tracking the key measure by measure.

    The running key is what makes a key change mid-piece come out right: from
    that bar on, the degrees are counted in the new key.
    """
    from music21 import harmony as m21harmony

    running = _part_key_at_start(part, override)
    lo = from_measure if from_measure is not None else 1
    moved = 0
    for measure in part.recurse().getElementsByClass(stream.Measure):
        for signature in _key_signatures_of(measure):
            running = _as_key(signature) if not override else running
        if measure.number < lo:
            continue
        if to_measure is not None and measure.number > to_measure:
            continue
        if running is None:
            raise ValueError(
                f"{part_label(part)} has no key signature, so it has no scale "
                "degrees to move by. Give one with --key (e.g. --key G, --key e), "
                "or use chromatic `transpose` if a semitone shift is what you want.")
        for n in measure.recurse().notes:
            if isinstance(n, m21harmony.Harmony):
                continue  # a chord SYMBOL is a Chord in music21; it is not on the staff
            moved += _move_note_diatonically(n, generic, running, chromatic)
    return moved, (running.name if running is not None else "")


def transpose_diatonic(score, degrees, names: list[str] | None = None,
                       from_measure: int | None = None, to_measure: int | None = None,
                       key_name: str | None = None) -> dict:
    """Move parts by SCALE DEGREES, staying in the key.

    `degrees` is signed and generic: -6 is down a sixth, 3 is up a third. The
    key signature is not touched, and the sixths come out major or minor as the
    key requires -- which is what makes this a harmony line and not a
    modulation. See the note above this function for the three decisions it
    makes.
    """
    steps = parse_generic_degrees(degrees)
    generic = m21interval.GenericInterval(steps)
    targets = find_parts(score, names) if names else list(score.parts)
    chromatic: list[dict] = []
    moved = 0
    keys = []
    for part in targets:
        count, key_used = _diatonic_over_measures(
            part, generic, key_name, from_measure, to_measure, chromatic)
        moved += count
        if key_used and key_used not in keys:
            keys.append(key_used)
    cleaned = normalize_accidentals(score, names)
    out = {"degrees": steps,
           "interval": generic.niceName,
           "direction": "down" if steps < 0 else "up",
           "key": keys[0] if len(keys) == 1 else keys,
           "key_signature_changed": False,
           "scope": [part_label(p) for p in targets] if names else "all parts",
           "notes_moved": moved,
           "outside_the_key": chromatic[:20],
           "outside_the_key_count": len(chromatic),
           "chord_diagrams_cleared": clear_stale_diagrams(score, names),
           "redundant_accidentals_hidden": cleaned["hidden"]}
    if from_measure is not None or to_measure is not None:
        out["measures"] = f"{from_measure or 1}-{to_measure if to_measure is not None else 'end'}"
    return out


def transpose_diatonic_elements(score, degrees, addresses: list,
                                key_name: str | None = None) -> dict:
    """The same move, applied ONLY to the named elements.

    Exists for the same reason `transpose_elements` does: a selection degraded
    to a measure range moves every note in the bar, and a harmony line written
    over a lassoed phrase is exactly when that would be noticed.
    """
    steps = parse_generic_degrees(degrees)
    generic = m21interval.GenericInterval(steps)
    found = resolve_elements(score, addresses)
    if not found["resolved"]:
        raise AddressError(
            "none of those elements are in this score: "
            + "; ".join(m["why"] for m in found["missing"][:3]))
    chromatic: list[dict] = []
    moved = 0
    touched_parts = []
    keys = []
    for _text, owner, pitch_index, _kind in found["resolved"]:
        if isinstance(owner, m21note.Rest):
            continue
        holder = owner.getContextByClass(stream.Part)
        if holder is not None and not any(holder is p for p in touched_parts):
            touched_parts.append(holder)
        if key_name:
            key_obj = _named_key(key_name)
        else:
            signature = owner.getContextByClass(m21key.KeySignature)
            if signature is None:
                raise ValueError(
                    "those notes are on a staff with no key signature, so they "
                    "have no scale degrees to move by. Give one with --key, or "
                    "use chromatic `transpose-elements` for a semitone shift.")
            key_obj = _as_key(signature)
        if key_obj.name not in keys:
            keys.append(key_obj.name)
        pitches = list(owner.pitches)
        if pitch_index is None:
            moved += _move_note_diatonically(owner, generic, key_obj, chromatic)
        else:
            p = pitches[pitch_index]
            new, outside, respelled = _diatonic_pitch(p, generic, key_obj)
            if outside:
                chromatic.append({"bar": bar_label(owner),
                                  "pitch": p.nameWithOctave,
                                  "became": new.nameWithOctave,
                                  "respelled": respelled})
            pitches[pitch_index] = new
            owner.pitches = tuple(pitches)
            moved += 1
    hidden = sum(_normalize_part(p).get("hidden", 0) for p in touched_parts)
    return {"degrees": steps,
            "interval": generic.niceName,
            "direction": "down" if steps < 0 else "up",
            "key": keys[0] if len(keys) == 1 else keys,
            "key_signature_changed": False,
            "elements_transposed": moved,
            "elements_requested": len(addresses),
            "outside_the_key": chromatic[:20],
            "outside_the_key_count": len(chromatic),
            "redundant_accidentals_hidden": hidden,
            "missing": found["missing"]}


def respell(score, prefer: str = "flats", names: list[str] | None = None,
            from_measure: int | None = None, to_measure: int | None = None) -> dict:
    """Respell accidentals enharmonically: prefer 'flats' (G#->Ab) or 'sharps' (Ab->G#).

    Pitch-by-pitch enharmonic swap; leaves naturals alone and skips swaps that
    would produce a double accidental. Key signatures are untouched (OMR/MIDI
    imports usually carry the right signature but wrong accidental spellings).
    With from_measure/to_measure set, only measures in that inclusive range are
    respelled.
    """
    if prefer not in ("flats", "sharps"):
        raise ValueError("prefer must be 'flats' or 'sharps'")
    targets = find_parts(score, names) if names else list(score.parts)
    ranged = from_measure is not None or to_measure is not None
    changed = 0
    for part in targets:
        if ranged:
            pitches = [p for m in _measures_in_range(part, from_measure, to_measure)
                       for p in m.recurse().stream().pitches]
        else:
            pitches = part.recurse().stream().pitches
        for p in pitches:
            acc = p.accidental
            if acc is None or acc.alter == 0:
                continue
            if (prefer == "flats" and acc.alter > 0) or (prefer == "sharps" and acc.alter < 0):
                e = p.getEnharmonic()
                if e.accidental is not None and abs(e.accidental.alter) > 1:
                    continue  # would need a double accidental; keep original
                p.step = e.step
                p.octave = e.octave
                p.accidental = e.accidental
                changed += 1
    # A respelled pitch carries a BRAND NEW accidental, whose displayStatus is
    # None, and None prints. Respelling A-flat to G-sharp inside A major put a
    # sharp on every one of them -- the reported bug.
    cleaned = normalize_accidentals(score, names)
    out = {"prefer": prefer, "changed_notes": changed,
           "redundant_accidentals_hidden": cleaned["hidden"],
           "scope": [part_label(p) for p in targets] if names else "all parts"}
    if ranged:
        out["measures"] = (f"{from_measure or 1}-"
                           f"{to_measure if to_measure is not None else 'end'}")
    return out


def change_clef(part, clef_name: str, from_measure: int = 1) -> dict:
    if clef_name not in CLEFS:
        raise ValueError(f"Unknown clef '{clef_name}'. Choose from: {sorted(CLEFS)}")
    measures = list(part.getElementsByClass(stream.Measure))
    if not measures:
        raise ValueError("Part has no measures")
    target = next((m for m in measures if m.number == from_measure), None)
    if target is None:
        if from_measure <= 1:
            target = measures[0]
        else:
            raise ValueError(f"No measure {from_measure} (part has {len(measures)} measures)")
    for old in list(target.getElementsByClass(m21clef.Clef)):
        target.remove(old)
    target.insert(0.0, CLEFS[clef_name]())
    return {"part": part_label(part), "clef": clef_name, "from_measure": target.number}


def range_violations(part, class_name: str) -> list[dict]:
    lo, hi = (m21pitch.Pitch(x) for x in RANGES[class_name])
    out = []
    for n in part.recurse().notes:
        for p in n.pitches:
            if p < lo or p > hi:
                out.append({"bar": bar_label(n), "pitch": p.nameWithOctave})
    return out


def change_instrument(part, target_name: str) -> dict:
    """Swap a part's instrument idiomatically.

    Works in sounding pitch, octave-shifts the whole line to best fit the new
    instrument's range, sets the idiomatic clef, then converts to written pitch
    for transposing instruments. Reports what it did and what still needs a
    human ear (remaining out-of-range notes).
    """
    new_instr = m21instrument.fromString(target_name)
    cls = type(new_instr).__name__
    if cls == "Instrument":
        raise ValueError(f"Unrecognized instrument '{target_name}'")

    try:
        part.toSoundingPitch(inPlace=True)
    except Exception:
        pass
    part.atSoundingPitch = True

    old_label = part_label(part)
    for old in list(part.recurse().getElementsByClass(m21instrument.Instrument)):
        part.remove(old, recurse=True)
    part.insert(0.0, new_instr)
    part.partName = new_instr.instrumentName or target_name
    part.partAbbreviation = new_instr.instrumentAbbreviation or part.partName

    report = {"from": old_label, "to": part.partName, "octave_shift": 0, "out_of_range": []}

    if cls in RANGES:
        lo, hi = (m21pitch.Pitch(x).ps for x in RANGES[cls])
        ps_vals = [p.ps for n in part.recurse().notes for p in n.pitches]
        if ps_vals:
            def violations_at(shift: int) -> int:
                return sum(1 for v in ps_vals if not (lo <= v + 12 * shift <= hi))
            best = min((0, -1, 1, -2, 2), key=lambda s: (violations_at(s), abs(s)))
            if best != 0 and violations_at(best) < violations_at(0):
                part.transpose(m21interval.Interval(12 * best), inPlace=True)
                report["octave_shift"] = best
            report["out_of_range"] = range_violations(part, cls)

    clef_name = DEFAULT_CLEF.get(cls, "treble")
    change_clef(part, clef_name, 1)
    report["clef"] = clef_name

    if new_instr.transposition is not None:
        try:
            part.toWrittenPitch(inPlace=True)
            report["written_transposition"] = new_instr.transposition.niceName
        except Exception:
            report["written_transposition"] = "FAILED — part left at concert pitch"
    # last, so it reads the key the part ENDS in -- for a transposing
    # instrument that is the written key, which is the whole point
    report["redundant_accidentals_hidden"] = _normalize_part(part).get("hidden", 0)
    return report


def _sounding(container):
    """Notes/chords in a container, excluding ChordSymbol/Harmony objects
    (which subclass Chord but are annotations, not sounding notes)."""
    return [el for el in container.notesAndRests if "Harmony" not in el.classes]


ABSORB_DEFAULT_RULES = {
    "below_melody": True,   # absorbed tones stay strictly below the concurrent melody note
    "drop_doubling": True,  # drop tones the melody is already sounding
    "min_pitch": "G3",      # register floor: fold up anything under this
    "max_span": 12,         # max semitone span of the absorbed chord (drop lowest beyond it)
}


def absorb_part(score, source_name: str, target_name: str, rules: dict | None = None) -> dict:
    """Fold a chordal part into a melodic part as a second voice, rule-governed.

    The target keeps its existing line as voice 1 (the melody); the source's
    notes become voice 2 underneath it, adjusted per the declarative rule set.
    The source part itself is left untouched (strip or remove it separately).
    """
    rules = {**ABSORB_DEFAULT_RULES, **(rules or {})}
    src = find_parts(score, [source_name])[0]
    tgt = find_parts(score, [target_name])[0]
    if src is tgt:
        raise ValueError("source and target must differ")
    floor_ps = m21pitch.Pitch(rules["min_pitch"]).ps
    stats = {"added": 0, "folded_up": 0, "folded_down": 0,
             "dropped_doubling": 0, "dropped_no_room": 0, "dropped_span": 0}

    src_measures = {m.number: m for m in src.getElementsByClass(stream.Measure)}
    for tm in tgt.getElementsByClass(stream.Measure):
        sm = src_measures.get(tm.number)
        if sm is None or not any(getattr(el, "pitches", None) for el in _sounding(sm)):
            continue
        # the melody may sit directly in the measure or inside voices; look in
        # both, or the below-melody and doubling rules see nothing to work
        # against on a staff that already has voices
        melody_containers = list(tm.voices) or [tm]
        melody = [(el.offset, el.offset + el.quarterLength, el)
                  for c in melody_containers for el in _sounding(c)
                  if getattr(el, "pitches", None)]

        v2 = stream.Voice(id="2")
        for el in _sounding(sm):
            off, dur = el.offset, el.quarterLength
            if el.isRest or not el.pitches:
                v2.insert(off, m21note.Rest(quarterLength=dur))
                continue
            concurrent = [p.ps for (mo, me, mel) in melody if mo < off + dur and me > off
                          for p in mel.pitches]
            ceiling = min(concurrent) if (concurrent and rules["below_melody"]) else None
            kept: list = []  # Pitch objects, spelling preserved through octave folds
            for p in sorted(el.pitches, key=lambda x: x.ps):
                shift = 0
                while p.ps + 12 * shift < floor_ps:
                    shift += 1
                    stats["folded_up"] += 1
                if ceiling is not None:
                    while p.ps + 12 * shift >= ceiling:
                        shift -= 1
                        stats["folded_down"] += 1
                    if p.ps + 12 * shift < floor_ps:
                        stats["dropped_no_room"] += 1
                        continue
                np = copy.deepcopy(p)
                if shift:
                    np.octave += shift
                if rules["drop_doubling"] and any(abs(np.ps - c) < 0.5 for c in concurrent):
                    stats["dropped_doubling"] += 1
                    continue
                if all(abs(np.ps - k.ps) > 0.5 for k in kept):
                    kept.append(np)
            while kept and max(k.ps for k in kept) - min(k.ps for k in kept) > rules["max_span"]:
                kept.remove(min(kept, key=lambda k: k.ps))
                stats["dropped_span"] += 1
            if kept:
                if len(kept) == 1:
                    n = m21note.Note(kept[0])
                else:
                    n = m21chord.Chord(sorted(kept, key=lambda k: k.ps))
                n.quarterLength = dur
                v2.insert(off, n)
                stats["added"] += len(kept)
            else:
                v2.insert(off, m21note.Rest(quarterLength=dur))

        existing = list(tm.voices)
        if existing:
            # The staff already sings in voices -- an OMR'd piano or accordion
            # part usually does. Leave them be and give the absorbed line an id
            # of its own: inserting another "1" and "2" alongside them left two
            # voices sharing each id, and the writer folds same-id voices
            # together, so their notes came back sounding on top of each other.
            used = {str(v.id) for v in existing}
            spare = 1
            while str(spare) in used:
                spare += 1
            v2.id = str(spare)
            tm.insert(0.0, v2)
        else:
            v1 = stream.Voice(id="1")
            for el in list(tm.notesAndRests):
                if "Harmony" in el.classes:
                    continue
                # read the offset BEFORE detaching: music21's .offset is relative
                # to the element's active site, so a removed element reports 0 and
                # the whole melody collapsed onto the downbeat -- which the writer
                # then laid out end to end, making every bar as long as its notes
                off = el.offset
                tm.remove(el)
                v1.insert(off, el)
            tm.insert(0.0, v1)
            tm.insert(0.0, v2)

    cleaned = _normalize_part(tgt)
    return {"source": part_label(src), "target": part_label(tgt), "rules": rules,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0), **stats}


def strip_notes(score, name: str) -> dict:
    """Empty a part of sounding notes, keeping chord symbols (a names-only staff)."""
    part = find_parts(score, [name])[0]
    removed = 0
    for m in part.getElementsByClass(stream.Measure):
        for v in list(m.voices):
            m.remove(v, recurse=True)
            removed += sum(len(el.pitches) for el in _sounding(v) if not el.isRest)
        for el in list(m.notesAndRests):
            if "Harmony" in el.classes:
                continue
            if not el.isRest:
                removed += len(el.pitches)
            m.remove(el)
        m.insert(0.0, m21note.Rest(quarterLength=m.barDuration.quarterLength))
    return {"part": part_label(part), "notes_removed": removed}


def octave_shift(score, name: str, octaves: int, from_measure: int, to_measure: int) -> dict:
    """Shift a part's notes by whole octaves within a measure range (inclusive)."""
    part = find_parts(score, [name])[0]
    itv = m21interval.Interval(12 * octaves)
    shifted = 0
    for m in part.getElementsByClass(stream.Measure):
        if from_measure <= m.number <= to_measure:
            m.transpose(itv, inPlace=True)
            shifted += 1
    if shifted == 0:
        raise ValueError(f"No measures in range {from_measure}-{to_measure}")
    cleaned = _normalize_part(part)
    return {"part": part_label(part), "octaves": octaves,
            "measures": f"{from_measure}-{to_measure}", "measures_shifted": shifted,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0)}


REBUILD_DEFAULT_RULES = {
    "hold_min": 2.0,    # a base note at least this long (quarterLengths) is a "held note"
    "move_max": 1.0,    # overlay notes at most this long count as "moving"
    "min_run": 2,       # a phrase needs at least this many consecutive moving notes
    "min_pitch": "G3",  # fold overlay material up to this register floor
}


def rebuild_part(score, target_name: str, src_score, base_name: str,
                 overlay_name: str | None = None, rules: dict | None = None) -> dict:
    """Replace a part's content with a base part from another version, plus
    rule-selected moving lines from an overlay part.

    Overlay runs (consecutive short notes) are kept only where they overlap a
    held note in the base — "when the 2nd violin holds, the viola's moving
    phrase continues in the right hand."
    """
    rules = {**REBUILD_DEFAULT_RULES, **(rules or {})}
    target = find_parts(score, [target_name])[0]
    base = find_parts(src_score, [base_name])[0]
    overlay = find_parts(src_score, [overlay_name])[0] if overlay_name else None
    floor_ps = m21pitch.Pitch(rules["min_pitch"]).ps

    new_part = stream.Part()
    new_part.partName = target.partName
    new_part.partAbbreviation = target.partAbbreviation
    instr = target.getInstrument(returnDefault=False)
    if instr is not None:
        new_part.insert(0.0, copy.deepcopy(instr))
    old_clef = target.recurse().getElementsByClass(m21clef.Clef).first()

    ov_measures = {m.number: m for m in overlay.getElementsByClass(stream.Measure)} if overlay else {}
    runs_kept = overlay_notes = 0

    for i, bm in enumerate(base.getElementsByClass(stream.Measure)):
        nm = stream.Measure(number=bm.number)
        if i == 0:
            nm.insert(0.0, copy.deepcopy(old_clef) if old_clef else m21clef.TrebleClef())
        for kind in ("TimeSignature", "KeySignature"):
            for el in bm.getElementsByClass(kind):
                nm.insert(el.offset, copy.deepcopy(el))
        bar_len = bm.barDuration.quarterLength
        base_events = [el for el in _sounding(bm) if el.offset < bar_len - 1e-6]
        holds = [(el.offset, el.offset + el.quarterLength) for el in base_events
                 if not el.isRest and el.quarterLength >= rules["hold_min"]]

        chosen = []
        om = ov_measures.get(bm.number)
        if om is not None and holds:
            moving = [el for el in _sounding(om)
                      if not el.isRest and el.quarterLength <= rules["move_max"]
                      and el.offset < bar_len - 1e-6]
            runs, cur = [], []
            for el in moving:
                if cur and abs(cur[-1].offset + cur[-1].quarterLength - el.offset) > 1e-3:
                    runs.append(cur)
                    cur = []
                cur.append(el)
            if cur:
                runs.append(cur)
            for run in runs:
                if len(run) < rules["min_run"]:
                    continue
                r0, r1 = run[0].offset, run[-1].offset + run[-1].quarterLength
                if any(h0 < r1 and h1 > r0 for h0, h1 in holds):
                    chosen.extend(run)
                    runs_kept += 1

        if chosen:
            v1 = stream.Voice(id="1")
            v2 = stream.Voice(id="2")
            for el in base_events:
                v1.insert(el.offset, copy.deepcopy(el))
            for el in chosen:
                ne = copy.deepcopy(el)
                for p in ne.pitches:
                    while p.ps < floor_ps:
                        p.octave += 1
                v2.insert(el.offset, ne)
                overlay_notes += len(ne.pitches)
            nm.insert(0.0, v1)
            nm.insert(0.0, v2)
        else:
            for el in base_events:
                nm.insert(el.offset, copy.deepcopy(el))
        new_part.append(nm)

    flat = _flatten_copy(new_part) if runs_kept else new_part
    flat.partName = target.partName
    flat.partAbbreviation = target.partAbbreviation
    order = list(score.parts)
    order[order.index(target)] = flat
    _set_part_order(score, order)
    cleaned = _normalize_part(flat)
    return {"target": part_label(flat), "base": base_name, "overlay": overlay_name,
            "rules": rules, "overlay_runs_kept": runs_kept, "overlay_notes": overlay_notes,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0)}


def _measure_count(part) -> int:
    """How many bars this staff actually holds."""
    return len(part.getElementsByClass(stream.Measure))


def _length_report(score) -> dict:
    """How long each staff is, and a sentence when they are not all the same.

    A score assembled out of two others -- which is what `pull_part` is for --
    can end up with staves of different lengths, and nothing said so. Ali's
    four-part arrangement was built by pulling from a one-part score and a
    three-part one: the first system carried all four staves, the accordion
    staves stopped, and the rest of the page was single-staff systems with a
    blank region where the others had been. The op returned `pulled`,
    `added_as`, `position` and an accidental count, so neither the reader nor
    the chat agent had anything to notice it by; it was found by looking at
    the page.

    It REPORTS and does not pad. Adding bars a part does not have, to make a
    page look tidy, is changing someone's music -- and the shortfall is
    sometimes exactly right (a tacet second half, a coda one instrument sits
    out). The reader is who can judge it, and they can only judge what they
    are told.
    """
    lengths = [{"part": part_label(p), "measures": _measure_count(p)}
               for p in score.parts]
    if not lengths:
        return {}
    longest = max(row["measures"] for row in lengths)
    short = [row for row in lengths if row["measures"] < longest]
    out: dict = {"score_measures": longest, "parts_measures": lengths}
    if short:
        named = ", ".join(f"{row['part']} ({row['measures']})" for row in short)
        out["uneven_parts"] = short
        out["length_warning"] = (
            f"The staves are not the same length. The score runs to {longest} bars; "
            f"{named} stop before that, so those staves end early and the page "
            f"shows a gap where they ran out. Nothing was padded: adding bars to "
            f"tidy the page would change the music. Extend them deliberately if "
            f"the shortfall is wrong.")
    return out


def pull_part(score, src_score, part_name: str, as_name: str | None = None,
              replace: str | None = None, measures: tuple[int, int] | None = None) -> dict:
    """Bring a part (or a measure range of it) from another document into this score.

    - Whole part: added as a new staff, or swapped in for --replace.
    - Measure range: requires --replace; only those measures of the target part
      are overwritten with the source's content (clefs/keys/meters kept).

    Every form reports the bars it brought (`measures_pulled`), how long every
    staff in the score now is (`parts_measures`, `score_measures`) and, when
    they differ, `uneven_parts` and a `length_warning` sentence. See
    `_length_report`: assembling a score out of two others is what this op is
    for, and parts of unequal length used to assemble silently.
    """
    src_part = find_parts(src_score, [part_name])[0]

    if measures is not None:
        if not replace:
            raise ValueError("A measure-range pull needs --replace (which part to pull into)")
        m0, m1 = measures
        target = find_parts(score, [replace])[0]
        tgt = {m.number: m for m in target.getElementsByClass(stream.Measure)}
        src = {m.number: m for m in src_part.getElementsByClass(stream.Measure)}
        for n in range(m0, m1 + 1):
            if n not in tgt or n not in src:
                raise ValueError(f"Measure {n} missing in {'target' if n not in tgt else 'source'}")
        replaced = 0
        for n in range(m0, m1 + 1):
            tm, sm = tgt[n], src[n]
            for v in list(tm.voices):
                tm.remove(v, recurse=True)
            for el in list(tm.notesAndRests):
                if "Harmony" not in el.classes:
                    tm.remove(el)
            bar_len = tm.barDuration.quarterLength
            for v in sm.voices:
                nv = stream.Voice(id=v.id)
                for el in v.notesAndRests:
                    if el.offset < bar_len - 1e-6:
                        nv.insert(el.offset, copy.deepcopy(el))
                tm.insert(0.0, nv)
            for el in sm.notesAndRests:
                if "Harmony" in el.classes or el.offset >= bar_len - 1e-6:
                    continue
                tm.insert(el.offset, copy.deepcopy(el))
            replaced += 1
        cleaned = _normalize_part(target)
        return {"pulled": part_name, "into": part_label(target),
                "measures": f"{m0}-{m1}", "measures_replaced": replaced,
                "redundant_accidentals_hidden": cleaned.get("hidden", 0),
                **_length_report(score)}

    new_part = copy.deepcopy(src_part)
    if as_name:
        new_part.partName = as_name
        new_part.partAbbreviation = as_name
    if replace:
        target = find_parts(score, [replace])[0]
        order = list(score.parts)
        order[order.index(target)] = new_part
        _set_part_order(score, order)
        cleaned = _normalize_part(new_part)
        return {"pulled": part_name, "replaced": replace, "as": part_label(new_part),
                "measures_pulled": _measure_count(new_part),
                "redundant_accidentals_hidden": cleaned.get("hidden", 0),
                **_length_report(score)}
    order = list(score.parts) + [new_part]
    _set_part_order(score, order)
    cleaned = _normalize_part(new_part)
    return {"pulled": part_name, "added_as": part_label(new_part),
            "position": len(order) - 1,
            "measures_pulled": _measure_count(new_part),
            "redundant_accidentals_hidden": cleaned.get("hidden", 0),
            **_length_report(score)}


def simplify_repeats(score, name: str, note_length: float = 1.0) -> dict:
    """Collapse measures that only restate one pitch class (octave jumps,
    repeated notes, ties) into a single downbeat note plus rests.

    The kept note is the lowest pitch in the measure (bass function). Measures
    with more than one pitch class — an actual line — are left alone, as are
    measures already holding a single note.
    """
    part = find_parts(score, [name])[0]
    simplified = []
    for m in part.getElementsByClass(stream.Measure):
        events = [el for el in _sounding(m) if not el.isRest]
        if len(events) < 2:
            continue
        pcs = {p.pitchClass for el in events for p in el.pitches}
        if len(pcs) != 1:
            continue
        lowest = min((p for el in events for p in el.pitches), key=lambda p: p.ps)
        bar_len = m.barDuration.quarterLength
        for cont in list(m.voices) or [m]:
            for el in list(_sounding(cont)):
                cont.remove(el)
        for v in list(m.voices):
            m.remove(v)
        n = m21note.Note(copy.deepcopy(lowest))
        n.quarterLength = min(note_length, bar_len)
        m.insert(0.0, n)
        pos = n.quarterLength
        while pos < bar_len - 1e-6:
            r = m21note.Rest(quarterLength=min(1.0, bar_len - pos))
            m.insert(pos, r)
            pos += r.quarterLength
        simplified.append(m.number)
    cleaned = _normalize_part(part)
    return {"part": part_label(part), "measures_simplified": len(simplified),
            "measures": simplified,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0)}



# -- rhythmic simplification --------------------------------------------------
#
# "Make this easier to play by reducing the 16th notes down to reasonable
# eighth notes I can't play this fast." The agent answered, correctly, that it
# had no tool for it and offered a transposition instead.
#
# The ask is ambiguous and the readings are not variations on each other, they
# are different pieces of music. So the op does not choose: `--mode` does, and
# the report says what the choice cost.
#
#   AUGMENT doubles every value and halves the meter's denominator, so 4/4
#   becomes 4/2 and every sixteenth becomes an eighth. Not one note is lost and
#   not one bar is added -- bar numbers, repeats, voltas and rehearsal marks all
#   stay where they were. What it costs is TIME: the passage now lasts twice as
#   long, which is the same thing as playing it half as fast. That is the point
#   for a soloist reading off the page, and it is ruinous for a part playing
#   with others, so a named part in a score that has more than one is refused.
#
#   THIN keeps the passage exactly where it sits in the bar and drops notes
#   until nothing attacks faster than the unit. The part still fits the
#   ensemble and still lasts the same number of beats. What it costs is NOTES,
#   which is someone's music, so `notes_removed` is in the report with the bar
#   each one came out of.
#
# And the third answer, which needs no notation at all: play it slower. Nothing
# here writes a tempo mark -- this repo has no tempo family to hang one off
# (see "Adding to the toolset") -- but augmenting IS that answer written down,
# and the report says so, because a reader who would rather just take it slower
# should not be handed a rewritten score.
#
# WHICH NOTES THIN KEEPS is the judgement, and it is the metrical one: an
# attack survives if it lands ON the unit grid, counted from the bar's metrical
# start (a pickup's `paddingLeft` is in the sum, so a pickup is counted from
# where it really sits in the bar). Each survivor is stretched to the next
# survivor. That is what a player does simplifying at sight, and it falls out
# right on the figures that actually defeat people: four sixteenths keep the
# first and third; a dotted eighth plus a sixteenth keeps the dotted eighth as
# a quarter and loses the pickup sixteenth; an eighth-note syncopation is on the
# grid and survives untouched. Nothing is ever MOVED -- a dropped note is honest
# and a displaced one is a lie about when the music sounds.

NOTE_UNITS = {
    "whole": 4.0, "half": 2.0, "quarter": 1.0,
    "eighth": 0.5, "8th": 0.5,
    "sixteenth": 0.25, "16th": 0.25,
    "thirtysecond": 0.125, "32nd": 0.125,
}

# Denominators a reader can be handed. Halving 4/4 gives 4/2, which is
# uncommon but read at sight; halving 4/2 would give 4/1, which is not.
WRITABLE_DENOMINATORS = {2, 4, 8, 16, 32}


def parse_note_unit(text) -> float:
    """A note value, by name ('eighth', '16th') or as a quarterLength ('0.5')."""
    if isinstance(text, (int, float)):
        return float(text)
    want = str(text).strip().lower()
    if want in NOTE_UNITS:
        return NOTE_UNITS[want]
    try:
        value = float(want)
    except ValueError:
        raise ValueError(
            f"'{text}' is not a note value. Use one of {sorted(NOTE_UNITS)}, "
            f"or a quarterLength like 0.5")
    if value <= 0:
        raise ValueError(f"A note value must be longer than nothing (got {text})")
    return value


def note_value_name(ql: float) -> str:
    """What a musician calls a duration -- for the report, never for a decision."""
    from music21 import duration as m21duration
    try:
        d = m21duration.Duration(float(ql))
    except Exception:  # noqa: BLE001 -- a report may not raise
        return f"{float(ql):g} quarters"
    name = d.type
    if name in ("complex", "inexpressible", "zero"):
        return f"{float(ql):g} quarters"
    if d.tuplets:
        name = f"{name} triplet" if d.tuplets[0].tupletActual[0] == 3 else f"{name} tuplet"
    return f"{'dotted ' * d.dots}{name}"


def _shortest_attack(measures) -> float | None:
    """The shortest sounding value in these bars, ignoring grace notes (which
    have no duration to shorten and are ornaments, not the tempo of the line)."""
    values = [float(el.quarterLength)
              for m in measures
              for cont in (list(m.voices) or [m])
              for el in _sounding(cont)
              if not el.isRest and float(el.quarterLength) > 0
              and not el.duration.isGrace]
    return min(values) if values else None


def _measure_grid(measure, step: float) -> float:
    """How far the bar's first offset sits past a grid line.

    A pickup's notes start at offset 0 but stand somewhere else in the bar;
    `paddingLeft` is that distance, so the grid is counted from it.
    """
    return float(measure.paddingLeft or 0.0) % step


def _repair_tie(el, forward_ok: bool, backward_ok: bool) -> None:
    """A tie is a claim about the note next to it. When thinning removes that
    note the claim is false, and an unresolved tie is how a sustained note
    swallows the rest of a bar in a renderer."""
    from music21 import tie as m21tie
    existing = getattr(el, "tie", None)
    if existing is None:
        return
    kind = existing.type
    forward = kind in ("start", "continue") and forward_ok
    backward = kind in ("stop", "continue") and backward_ok
    if forward and backward:
        el.tie = m21tie.Tie("continue")
    elif forward:
        el.tie = m21tie.Tie("start")
    elif backward:
        el.tie = m21tie.Tie("stop")
    else:
        el.tie = None


def _same_sound(a, b) -> bool:
    if a is None or b is None or a.isRest or b.isRest:
        return False
    return tuple(p.nameWithOctave for p in a.pitches) == tuple(
        p.nameWithOctave for p in b.pitches)


def _absorb_spanners(dropped, into) -> None:
    """Hand a removed note's slurs and hairpins to the note that swallowed it.

    A Spanner does not live on the staff; it POINTS at notes. Delete a note a
    slur ends on and the slur is left reaching for something that is not there,
    which Verovio resolves by drawing the arc to wherever it can -- a page of
    thinned bars came back with one slur spanning a whole system.
    """
    for sp in list(dropped.getSpannerSites()):
        try:
            if into is not None and all(el is not into
                                        for el in sp.getSpannedElements()):
                sp.replaceSpannedElement(dropped, into)
            else:
                sp.spannerStorage.remove(dropped)
        except Exception:  # noqa: BLE001 -- a stale reference is what we are clearing
            pass


def _prune_lone_spanners(container) -> int:
    """A slur with one end left is not a slur."""
    from music21 import spanner as m21spanner

    gone = 0
    for sp in list(container.recurse().getElementsByClass(m21spanner.Spanner)):
        if len(sp.getSpannedElements()) >= 2:
            continue
        try:
            container.remove(sp, recurse=True)
            gone += 1
        except Exception:  # noqa: BLE001
            pass
    return gone


def _thin_container(container, step: float, phase: float) -> dict | None:
    """Quantize one voice's attacks onto the `step` grid.

    Returns the tally, or None when thinning would leave the bar with no notes
    at all -- a passage attacked entirely off the grid is left exactly as it
    was and reported, because emptying someone's bar is not a simplification.
    """
    from music21 import beam as m21beam
    from music21 import duration as m21duration

    events = sorted((el for el in _sounding(container)),
                    key=lambda el: (float(el.offset), 0 if el.isRest else 1))
    if not events:
        return {"removed": 0, "rests_absorbed": 0, "lengthened": 0, "graces": 0}

    content_end = max(float(el.offset) + float(el.quarterLength) for el in events)

    def on_grid(offset: float) -> bool:
        if abs(offset) < 1e-6:
            return True  # the bar's own start is always a grid line
        pos = offset + phase
        return abs(pos - round(pos / step) * step) < 1e-6

    kept, dropped = [], []
    for el in events:
        # a note already as long as the unit is not one of the fast ones and is
        # kept wherever it starts. Without this, three quarter-note TRIPLETS --
        # each longer than an eighth, and not what anyone means by "too fast" --
        # are two-thirds deleted for landing between the eighth lines.
        long_enough = float(el.quarterLength) >= step - 1e-6
        if el.duration.isGrace or not (long_enough or on_grid(float(el.offset))):
            dropped.append(el)
        elif kept and abs(float(el.offset) - float(kept[-1].offset)) < 1e-6:
            dropped.append(el)  # a second attack on the same grid line
        else:
            kept.append(el)

    if not dropped:
        return {"removed": 0, "rests_absorbed": 0, "lengthened": 0, "graces": 0}
    if not any(not el.isRest for el in kept) and any(not el.isRest for el in events):
        return None

    lengthened = 0
    for index, el in enumerate(kept):
        end = float(kept[index + 1].offset) if index + 1 < len(kept) else content_end
        new_ql = end - float(el.offset)
        if new_ql <= 0:
            continue
        if abs(new_ql - float(el.quarterLength)) > 1e-6:
            # a fresh Duration rather than a quarterLength assignment: the old
            # one may carry a tuplet, and 3 sixteenths of a triplet becoming one
            # eighth is not "the same tuplet, longer"
            el.duration = m21duration.Duration(new_ql)
            lengthened += 1
        if not el.isRest:
            _repair_tie(el,
                        forward_ok=(index + 1 >= len(kept)
                                    or _same_sound(el, kept[index + 1])),
                        backward_ok=(index == 0 or _same_sound(kept[index - 1], el)))

    for el in dropped:
        absorbed_into = next((k for k in reversed(kept)
                              if float(k.offset) <= float(el.offset) + 1e-6), None)
        _absorb_spanners(el, absorbed_into or (kept[0] if kept else None))
        container.remove(el)

    # beams describe a group that no longer exists; makeBeams re-derives them
    # from the meter once the durations are settled
    for el in kept:
        if not el.isRest:
            el.beams = m21beam.Beams()

    return {"removed": sum(1 for el in dropped if not el.isRest and not el.duration.isGrace),
            "rests_absorbed": sum(1 for el in dropped if el.isRest),
            "graces": sum(1 for el in dropped if el.duration.isGrace),
            "lengthened": lengthened}


def _relayout_measures(part) -> None:
    """Re-seat every measure at the offset its predecessors' lengths give it.

    A Part holds measures at absolute offsets, so a bar that grew leaves every
    bar after it sitting inside the one before.
    """
    measures = list(part.getElementsByClass(stream.Measure))
    for m in measures:
        part.remove(m)
    at = 0.0
    for m in measures:
        part.insert(at, m)
        at += float(m.barDuration.quarterLength) - float(m.paddingLeft or 0.0) \
            - float(m.paddingRight or 0.0)


def _augment_part(part, from_measure, to_measure, factor: int = 2) -> dict:
    """Double every value in range and halve the meter's denominator to match.

    The bar count does not change, so nothing is renumbered and every mark
    hanging off a bar number stays true. What changes is how long a bar lasts.

    Read first, then write. The meter in force at bar N has to be read off the
    score as it was WRITTEN: doubling bar 1 from 4/4 to 4/2 and then carrying
    that forward as bar 2's meter reports, wrongly, that bar 2 is already as
    slow as doubling goes.
    """
    from music21 import meter as m21meter

    measures = list(part.getElementsByClass(stream.Measure))
    targets = _measures_in_range(part, from_measure, to_measure)
    if not targets:
        raise ValueError(f"No measures in range {from_measure or 1}-"
                         f"{to_measure if to_measure is not None else 'end'}")
    wanted = {m.number for m in targets}

    # pass one: the meter in force at each bar, and whether the bar states it
    in_force, states_it = {}, {}
    current = None
    for m in measures:
        here = m.getElementsByClass(m21meter.TimeSignature).first()
        if here is not None:
            current = here
        in_force[m.number] = current
        states_it[m.number] = here is not None

    first_in_range = targets[0].number
    for m in targets:
        signature = in_force[m.number]
        if signature is None:
            raise ValueError(
                f"Bar {m.number} has no time signature to halve. Import the "
                f"score with its meter, or use --mode thin, which needs none.")
        if (signature.denominator % factor
                or (signature.denominator // factor) not in WRITABLE_DENOMINATORS):
            raise ValueError(
                f"Doubling the values in bar {m.number} would put it in "
                f"{signature.numerator}/{signature.denominator // factor}, which "
                f"is not a meter to hand a reader. {signature.ratioString} is "
                f"already as slow as doubling goes; use --mode thin instead.")

    # pass two: the rewrite
    meters, changed = [], []
    for m in targets:
        signature = in_force[m.number]
        doubled = m21meter.TimeSignature(
            f"{signature.numerator}/{signature.denominator // factor}")
        m.augmentOrDiminish(float(factor), inPlace=True)
        m.paddingLeft = float(m.paddingLeft or 0.0) * factor
        m.paddingRight = float(m.paddingRight or 0.0) * factor
        for ts in list(m.getElementsByClass(m21meter.TimeSignature)):
            m.remove(ts)
        # only where the reader needs to be told: where the score stated a
        # meter, and at the head of the passage. A signature on every bar is
        # printed on every bar.
        if states_it[m.number] or m.number == first_in_range:
            m.timeSignature = doubled
            meters.append({"measure": m.number, "from": signature.ratioString,
                           "to": doubled.ratioString})
        changed.append(m.number)

    # the bar after the passage goes back to the meter it was written in, or
    # the rest of the piece silently inherits half-speed
    after = [m for m in measures if m.number not in wanted
             and m.number > targets[-1].number]
    if after and not states_it[after[0].number]:
        restored = in_force[targets[-1].number]
        after[0].timeSignature = m21meter.TimeSignature(restored.ratioString)
        meters.append({"measure": after[0].number,
                       "from": f"{restored.numerator}/{restored.denominator // factor}",
                       "to": restored.ratioString,
                       "note": "the meter the passage came out of, put back"})
    _relayout_measures(part)
    return {"measures_changed": changed, "meters": meters}


def _meters_in_range(part, from_measure, to_measure) -> set[str]:
    """Every meter in force across the range, as written."""
    from music21 import meter as m21meter

    wanted = {m.number for m in _measures_in_range(part, from_measure, to_measure)}
    seen, current = set(), None
    for m in part.getElementsByClass(stream.Measure):
        here = m.getElementsByClass(m21meter.TimeSignature).first()
        if here is not None:
            current = here
        if m.number in wanted and current is not None:
            seen.add(current.ratioString)
    return seen


def _can_double_again(parts, from_measure, to_measure) -> bool:
    """Whether a second pass would be accepted, rather than refused for the
    meter it would produce -- so the report does not send a reader back into
    a refusal it could have predicted."""
    for part in parts:
        for ratio in _meters_in_range(part, from_measure, to_measure):
            denominator = int(ratio.split("/")[1])
            if denominator % 2 or (denominator // 2) not in WRITABLE_DENOMINATORS:
                return False
    return True


def simplify_rhythm(score, mode: str, names: list[str] | None = None,
                    unit: str = "eighth", from_measure: int | None = None,
                    to_measure: int | None = None) -> dict:
    """Make a passage slower to read, by one of two openly different means.

    mode='augment': every value doubles and the meter's denominator halves.
    Every note survives; the passage takes twice as long to play. Applies to
    the WHOLE score -- the length of a bar is not a property of one staff --
    so naming a part of a multi-part score is refused.

    mode='thin': attacks are quantized onto the `unit` grid and the notes
    between them are dropped. The passage keeps its place and its length, so it
    still fits the other parts; it is no longer the same tune, and the report
    says how many notes that cost and which bars they came from.
    """
    mode = str(mode).strip().lower()
    if mode not in ("augment", "thin"):
        raise ValueError(f"mode is 'augment' or 'thin', not '{mode}'")
    step = parse_note_unit(unit)
    all_parts = list(score.parts)
    span = (f"{from_measure or 1}-{to_measure}" if to_measure is not None
            else (f"{from_measure}-end" if from_measure else "all"))

    if mode == "augment":
        if names and len(all_parts) > 1:
            chosen = find_parts(score, names)
            if len(chosen) != len(all_parts):
                raise ValueError(
                    f"Doubling the note values makes every bar last twice as "
                    f"long, so it is a change to the whole score, not to "
                    f"{part_label(chosen[0])} alone -- that part would drift a "
                    f"bar further from the other {len(all_parts) - len(chosen)} "
                    f"with every bar. Run it with no --part to double them all, "
                    f"or use --mode thin, which keeps this part in step.")
        targets = all_parts or [score]
    else:
        if not names:
            raise ValueError(
                "Thinning drops notes, so it needs to be told whose. Name the "
                "part with --part.")
        targets = find_parts(score, names)

    before = {}
    for part in targets:
        in_range = _measures_in_range(part, from_measure, to_measure)
        before[id(part)] = _shortest_attack(in_range)
    shortest_before = min([v for v in before.values() if v], default=None)

    report = {"mode": mode, "unit": note_value_name(step),
              "parts": [part_label(p) for p in targets], "measures": span,
              "shortest_before": (note_value_name(shortest_before)
                                  if shortest_before else None)}

    if mode == "augment":
        per_part, hidden = [], 0
        for part in targets:
            done = _augment_part(part, from_measure, to_measure)
            per_part.append({"part": part_label(part), **done})
            hidden += _normalize_part(part).get("hidden", 0)
        report["notes_removed"] = 0
        report["measures_changed"] = per_part[0]["measures_changed"]
        report["meters"] = per_part[0]["meters"]
        report["beats_before"] = round(
            sum(float(m.barDuration.quarterLength)
                for m in _measures_in_range(targets[0], from_measure, to_measure)) / 2, 4)
        report["beats_now"] = round(report["beats_before"] * 2, 4)
        report["cost"] = (
            "Every note survived and no bar was added or renumbered, so every "
            "repeat, volta and rehearsal mark still points where it did. The "
            "passage now takes "
            f"{report['beats_now']:g} quarter-note beats where it took "
            f"{report['beats_before']:g}, which is to say it sounds at half "
            "speed: this IS 'play it slower', written into the notation. "
            "Doubling the tempo mark as well would undo the whole thing.")
    else:
        removed_by_measure: dict[str, int] = {}
        totals = {"removed": 0, "rests_absorbed": 0, "graces": 0, "lengthened": 0}
        untouched: list[int] = []
        changed: list[int] = []
        hidden = 0
        for part in targets:
            for m in _measures_in_range(part, from_measure, to_measure):
                phase = _measure_grid(m, step)
                bar_removed = 0
                declined = False
                for cont in (list(m.voices) or [m]):
                    tally = _thin_container(cont, step, phase)
                    if tally is None:
                        declined = True
                        continue
                    for k in totals:
                        totals[k] += tally[k]
                    bar_removed += tally["removed"] + tally["graces"]
                if declined:
                    untouched.append(m.number)
                elif bar_removed:
                    removed_by_measure[str(m.number)] = bar_removed
                    changed.append(m.number)
                    try:
                        m.makeBeams(inPlace=True)
                    except Exception:  # noqa: BLE001 -- unbeamed reads; wrong beams do not
                        pass
            hidden += _normalize_part(part).get("hidden", 0)
        report["notes_removed"] = totals["removed"] + totals["graces"]
        report["grace_notes_removed"] = totals["graces"]
        report["rests_absorbed"] = totals["rests_absorbed"]
        report["notes_lengthened"] = totals["lengthened"]
        report["removed_by_measure"] = removed_by_measure
        report["measures_changed"] = changed
        if untouched:
            report["measures_left_alone"] = untouched
        kept = sum(1 for p in targets
                   for m in _measures_in_range(p, from_measure, to_measure)
                   for c in (list(m.voices) or [m])
                   for el in _sounding(c) if not el.isRest)
        report["notes_now"] = kept
        report["slurs_dropped"] = _prune_lone_spanners(score)
        report["cost"] = (
            f"{report['notes_removed']} note"
            f"{'' if report['notes_removed'] == 1 else 's'} of the "
            f"{report['notes_removed'] + kept} that were there are gone; "
            f"{kept} remain. The passage keeps its place in the bar and its "
            "length, so it still fits whatever else is playing -- but it is no "
            "longer the same tune, and only the reader can say whether what is "
            "left is still the melody.")
        if untouched:
            report["cost"] += (
                f" Bar{'s' if len(untouched) > 1 else ''} "
                f"{', '.join(str(n) for n in untouched)} "
                f"{'were' if len(untouched) > 1 else 'was'} left exactly as "
                "written: every attack there falls between the grid lines, and "
                "thinning would have emptied the bar rather than simplified it.")

    after = min([v for v in
                 (_shortest_attack(_measures_in_range(p, from_measure, to_measure))
                  for p in targets) if v], default=None)
    report["shortest_now"] = note_value_name(after) if after else None
    report["reached_unit"] = bool(after is not None and after >= step - 1e-6)
    if not report["reached_unit"] and after is not None:
        short = (f"the shortest value in the passage is now a "
                 f"{note_value_name(after)}, still faster than the "
                 f"{note_value_name(step)} you asked for")
        if mode == "thin":
            # name the bars, not a guess at why. Two different things leave a
            # fast note behind: a bar left alone whole, and a grid note pinned
            # short by an off-grid note too long to drop -- and lengthening
            # that one would mean moving the note after it.
            where = sorted({m.number for part in targets
                            for m in _measures_in_range(part, from_measure,
                                                        to_measure)
                            for cont in (list(m.voices) or [m])
                            for el in _sounding(cont)
                            if not el.isRest and not el.duration.isGrace
                            and 0 < float(el.quarterLength) < step - 1e-6})
            report["measures_still_fast"] = where
            report["still_faster_than_unit"] = (
                short + f" -- in bar{'s' if len(where) > 1 else ''} "
                f"{', '.join(str(n) for n in where)}. Lengthening those would "
                f"mean moving the note after them, which this op will not do.")
        elif _can_double_again(targets, from_measure, to_measure):
            report["still_faster_than_unit"] = (
                short + " -- run it again to double once more")
        else:
            stuck = _meters_in_range(targets[0], from_measure, to_measure)
            report["still_faster_than_unit"] = (
                short + f" -- and doubling has gone as far as the meter allows "
                f"({'/'.join(sorted(stuck))} cannot be halved again without "
                f"writing a whole-note beat). What is left would have to be "
                f"thinned, which drops notes.")
    report["redundant_accidentals_hidden"] = hidden
    return report


def _set_part_order(score, ordered_parts) -> None:
    """Rebuild the score's part list in the given order (music21's replace()
    appends same-offset inserts, losing position)."""
    for p in list(score.parts):
        score.remove(p, recurse=True)
    for p in ordered_parts:
        score.insert(0.0, p)


def _flatten_copy(part) -> stream.Part:
    """A single-voice copy of a part: voices chordified into one layer,
    tied runs consolidated, voice-padding artifacts trimmed."""
    work = copy.deepcopy(part)
    for h in list(work.recurse().getElementsByClass("Harmony")):
        work.remove(h, recurse=True)
    sliced = work.chordify(addTies=True)
    # the same rehearsal consolidate_ties uses: strip only if the result holds
    # up, since a flattened part that no longer plays the same is worse than an
    # unflattened one
    _strip_ties_safely(sliced)

    new_part = stream.Part()
    new_part.partName = part.partName
    new_part.partAbbreviation = part.partAbbreviation
    instr = part.getInstrument(returnDefault=False)
    if instr is not None:
        new_part.insert(0.0, copy.deepcopy(instr))
    old_clef = part.recurse().getElementsByClass(m21clef.Clef).first()
    for i, m in enumerate(sliced.getElementsByClass(stream.Measure)):
        nm = stream.Measure(number=m.number)
        if i == 0:
            nm.insert(0.0, copy.deepcopy(old_clef) if old_clef else m21clef.TrebleClef())
        for kind in ("TimeSignature", "KeySignature"):
            for el in m.getElementsByClass(kind):
                nm.insert(el.offset, copy.deepcopy(el))
        bar_len = m.barDuration.quarterLength
        for el in m.notesAndRests:
            if el.offset >= bar_len - 1e-6:
                continue  # voice-padding artifacts from MusicXML round-trips
            nm.insert(el.offset, copy.deepcopy(el))
        new_part.append(nm)
    return new_part


def flatten_voices(score, name: str) -> dict:
    """Collapse a multi-voice staff into a single voice of chords (piano-RH style).

    Simultaneous notes across voices merge into chords; sustained tones are
    tied through the other layer's attacks, then identical runs consolidated.
    Stemming is left to normal engraving rules (single voice = no forced stems).
    """
    part = find_parts(score, [name])[0]
    new_part = _flatten_copy(part)

    before = sum(len(e.pitches) for e in part.recurse().notes if "Harmony" not in e.classes)
    after = sum(len(e.pitches) for e in new_part.recurse().notes)
    order = list(score.parts)
    order[order.index(part)] = new_part
    _set_part_order(score, order)
    cleaned = _normalize_part(new_part)
    return {"part": new_part.partName, "voices": "flattened to 1",
            "pitch_events_before": before, "pitch_events_after": after,
            "redundant_accidentals_hidden": cleaned.get("hidden", 0)}


def chart_style(score, name: str, symbol_y: float = -25.0) -> dict:
    """Real Book chart styling for a chord-symbol staff.

    Hides all rests (print-object="no") and drops the chord names onto the
    staff itself (default-y in tenths; -20 is the middle line).
    """
    part = find_parts(score, [name])[0]
    rests_hidden = symbols_moved = 0
    for m in part.getElementsByClass(stream.Measure):
        for r in m.recurse().getElementsByClass(m21note.Rest):
            r.style.hideObjectOnPrint = True
            rests_hidden += 1
        for cs in m.recurse().getElementsByClass("ChordSymbol"):
            # placement="below" makes OSMD position deterministically at
            # StaffHeight + ChordSymbolYOffset (the viewer sets a negative
            # offset to land the name ON the staff); Verovio gets place="within"
            # stamped at render time.
            cs.placement = "below"
            cs.style.absoluteY = symbol_y
            symbols_moved += 1
    return {"part": part_label(part), "rests_hidden": rests_hidden,
            "symbols_placed": symbols_moved, "symbol_y": symbol_y}


FLAT_NAMES = ["C", "Db", "D", "Eb", "E", "F", "Gb", "G", "Ab", "A", "Bb", "B"]

CHORD_TEMPLATES = [
    ("", {0, 4, 7}),          # major
    ("m", {0, 3, 7}),         # minor
    ("7", {0, 4, 7, 10}),     # dominant 7th
    ("m7", {0, 3, 7, 10}),
    ("maj7", {0, 4, 7, 11}),
    ("m7b5", {0, 3, 6, 10}),
    ("6", {0, 4, 7, 9}),
    ("m6", {0, 3, 7, 9}),
    ("dim", {0, 3, 6}),
    ("dim7", {0, 3, 6, 9}),
    ("aug", {0, 4, 8}),
]

QUALITY_KINDS = {
    "": "major", "m": "minor", "7": "dominant-seventh", "m7": "minor-seventh",
    "maj7": "major-seventh", "m7b5": "half-diminished-seventh",
    "6": "major-sixth", "m6": "minor-sixth",
    "dim": "diminished", "dim7": "diminished-seventh", "aug": "augmented",
}


def analyze_harmony(score, names: list[str] | None = None) -> dict:
    """Per-measure harmony extraction (read-only).

    For each measure, every sounding pitch class is weighted by duration and
    matched against chord templates over all 12 roots; the bass note at the
    downbeat weighs in favor of root-position readings. Returns ranked
    candidates per bar — the *judgment* of which label is musically right
    stays with the caller (the agent), by design.
    """
    parts = find_parts(score, names) if names else list(score.parts)
    measures_by_part = [list(p.getElementsByClass(stream.Measure)) for p in parts]
    n_measures = max(len(ms) for ms in measures_by_part)
    try:
        global_key = str(score.analyze("key"))
    except Exception:
        global_key = None

    out = []
    for i in range(n_measures):
        weights: dict[int, float] = {}
        bass_pc, bass_ps = None, None
        for ms in measures_by_part:
            if i >= len(ms):
                continue
            for el in ms[i].recurse().notes:
                w = float(el.quarterLength) or 0.25
                for pt in el.pitches:
                    weights[pt.pitchClass] = weights.get(pt.pitchClass, 0.0) + w
                    if el.offset < 0.75 and (bass_ps is None or pt.ps < bass_ps):
                        bass_ps, bass_pc = pt.ps, pt.pitchClass
        number = next((ms[i].number for ms in measures_by_part if i < len(ms)), i + 1)
        if not weights:
            out.append({"measure": number, "bass": None, "top": []})
            continue
        total = sum(weights.values())
        cands = []
        for root in range(12):
            for suffix, tpl in CHORD_TEMPLATES:
                tpl_pcs = {(root + iv) % 12 for iv in tpl}
                in_w = sum(w for pc, w in weights.items() if pc in tpl_pcs)
                coverage = sum(1 for pc in tpl_pcs if weights.get(pc, 0) > 0) / len(tpl_pcs)
                third = (root + (3 if suffix.startswith("m") or "dim" in suffix else 4)) % 12
                sc = in_w - 0.9 * (total - in_w) + 1.2 * coverage
                if weights.get(root, 0) == 0:
                    sc -= 1.0
                if weights.get(third, 0) == 0:
                    sc -= 0.8
                if bass_pc is not None and bass_pc == root:
                    sc += 1.0
                cands.append((sc, FLAT_NAMES[root] + suffix))
        cands.sort(key=lambda c: -c[0])
        out.append({"measure": number,
                    "bass": FLAT_NAMES[bass_pc] if bass_pc is not None else None,
                    "top": [{"symbol": s, "score": round(sc, 2)} for sc, s in cands[:3]]})
    return {"key": global_key, "parts_analyzed": [part_label(p) for p in parts], "measures": out}



# ------------------------------------------------- penny whistle fingerings
#
# A six-hole whistle has one fingering per pitch class and no keys, so the
# chart is small, published and unambiguous — which is exactly why this belongs
# in the engine as a table rather than in a model's head. Holes are numbered
# from the mouthpiece down: 1-3 under the upper hand, 4-6 under the lower.
#
# Both octaves use the same fingering; the second is overblown, which the chart
# marks with a "+" rather than by inventing a different pattern.

# X / O / half-slash, the way whistle fingerings have always been written in
# text ("xxx ooo"). Filled circles read better but are not in the font the PDF
# rasterizer falls back to, and a chart that engraves as a column of empty
# boxes is worse than no chart at all.
COVERED, OPEN, HALF = "X", "O", "/"

# What the renderer looks for when it replaces these with drawn circles. The
# letters stay in the notation as the meaning (and as what a plain MusicXML
# export carries); the diagram is how they are drawn.
WHISTLE_LYRIC_TAG = "wf"
# Six holes and the overblown mark: the verses a fingering occupies.
WHISTLE_VERSES = 7

# pitch class (as a sounding name) -> the six holes, top to bottom.
# The cross-fingerings for C natural and F natural are the standard ones;
# half-holed notes are marked HALF on the hole that is half covered.
WHISTLE_D_FINGERINGS = {
    "D":  "xxxxxx",
    "E-": "xxxxxh",      # half-hole the bottom
    "E":  "xxxxxo",
    "F":  "xxxoxx",      # cross-fingering
    "F#": "xxxxoo",
    "G":  "xxxooo",
    "G#": "xxxhoo",      # half-hole
    "A":  "xxoooo",
    "B-": "xoxxxo",      # cross-fingering
    "B":  "xooooo",
    "C":  "oxxooo",      # cross-fingering
    "C#": "oooooo",
}

WHISTLE_KEYS = {"D": "D4", "C": "C4", "E-": "E-4", "F": "F4", "G": "G4", "A": "A4"}

# The same chart, keyed by SEMITONES above the whistle's own tonic, which is
# how it is looked up.
#
# Ali's screenshot: diagrams under most notes and none under three of them,
# circled, "missing tablature". Keying the chart by the pitch's NAME is why. A
# fingering is a fact about a sounding pitch -- one hole pattern per semitone,
# twelve of them -- and D# is the same six holes as E-flat, played with the same
# finger. Asked for a D# the chart had no entry, so the note was reported as
# having "no standard fingering" and left bare, and every enharmonic spelling
# failed the same way: G-, A-, A#, D-, B#, C-, E#, F-. Optical recognition and
# transposition both produce those spellings freely, which is how a run of
# ordinary notes ends up with holes in it.
#
# Derived from the chart above rather than typed out again: the published fact
# has one home, and a transcription error here could not be seen.
WHISTLE_D_BY_SEMITONE = {
    int(m21pitch.Pitch(f"{name}4").ps - m21pitch.Pitch("D4").ps) % 12: pattern
    for name, pattern in WHISTLE_D_FINGERINGS.items()
}
assert len(WHISTLE_D_BY_SEMITONE) == 12, "every semitone of the octave has a fingering"

# How far above its lowest note a whistle plays: two octaves, and then the
# tonic again at the top.
#
# The top D of a D whistle is all six holes covered and blown hard, and it is in
# every tutor book -- it is also the top note of a great many tunes, so leaving
# it out put a gap on a common note. Above it (the third-octave E and beyond)
# is possible on some instruments and not standard on any, so those stay
# reported rather than guessed at.
WHISTLE_TOP_SEMITONE = 24


def _whistle_symbols(pattern: str) -> list[str]:
    table = {"x": COVERED, "o": OPEN, "h": HALF}
    return [table[c] for c in pattern]


def whistle_fingerings(score, part, whistle_key: str = "D", clear: bool = False) -> dict:
    """Write penny-whistle fingerings under a part, as stacked lyric verses.

    Six verses, one per hole, so the notation itself carries the diagram: it
    engraves under the right notehead, exports with the score, prints, and
    survives every later op — none of which is true of anything drawn over the
    page. A seventh verse marks the overblown octave.

    Notes the whistle cannot play are left without a diagram and reported, the
    same way `check-range` reports what an instrument cannot reach.
    """
    from music21 import harmony as m21harmony

    def playable_notes(container):
        """The notes a whistle plays.

        `recurse().notes` includes the chord SYMBOLS: a ChordSymbol is a Chord
        in music21, so a part carrying a chart had six holes and an octave mark
        hung on every symbol on it -- a fingering for a chord, on an element
        that is not on the staff at all. `guitar_tab` was written knowing this;
        this was written before it was known.
        """
        return [n for n in container.recurse().notes
                if not isinstance(n, m21harmony.Harmony)]

    def without_fingerings(n):
        """The note's other verses. A whistle's are taken and everything else
        is left, or clearing the fingerings takes the guitar tab under the same
        notes with them -- two features on one part, one of them eating the
        other."""
        return [ly for ly in n.lyrics
                if str(ly.identifier or "") != WHISTLE_LYRIC_TAG]

    def make_room(n):
        """Everything on this note that is not about to be written over.

        A whistle's fingerings are verses 1-7 and the guitar tab's frets are
        verses 1-6, so one note cannot carry both -- and music21's `addLyric`
        writes the TEXT of the verse at that number and leaves its NAME alone,
        which put fret numbers under a `wf` label and drew "3" as a row of
        circles. Whichever op runs last takes those verses outright, and the
        report says how many notes it took them from.
        """
        return [ly for ly in n.lyrics if (ly.number or 0) > WHISTLE_VERSES]

    if clear:
        cleared = 0
        for n in playable_notes(part):
            kept = without_fingerings(n)
            if len(kept) != len(n.lyrics):
                n.lyrics = kept
                cleared += 1
        return {"part": part_label(part), "cleared": cleared}

    key = whistle_key.upper().replace("EB", "E-").replace("BB", "B-")
    if key not in WHISTLE_KEYS:
        raise ValueError(f"No fingering chart for a {whistle_key} whistle. "
                         f"Have: {sorted(WHISTLE_KEYS)}")
    lowest = m21pitch.Pitch(WHISTLE_KEYS[key])

    written = 0
    displaced = 0
    unplayable: list[dict] = []
    for n in playable_notes(part):
        pitches = n.pitches if isinstance(n, m21chord.Chord) else [n.pitch]
        # a whistle plays one note at a time; the top of a chord is the tune
        sounding = max(pitches)
        # How far above the instrument's own lowest note, in semitones. Measured
        # from the whistle's tonic and not from the staff: a D whistle's first
        # octave runs D4 to C#5, so C#5 is the top of the LOW octave and is not
        # overblown, while octave numbers change at C. And measured in
        # semitones rather than looked up by name, so a D# finds the E-flat
        # fingering it shares -- see WHISTLE_D_BY_SEMITONE.
        steps = int(round(sounding.ps - lowest.ps))
        if steps < 0 or steps > WHISTLE_TOP_SEMITONE:
            unplayable.append({
                "bar": bar_label(n),
                "pitch": sounding.nameWithOctave,
                "why": f"outside a {key} whistle's range "
                       f"({lowest.nameWithOctave} to "
                       f"{lowest.transpose(WHISTLE_TOP_SEMITONE).nameWithOctave})",
            })
            n.lyrics = make_room(n)
            continue
        pattern = WHISTLE_D_BY_SEMITONE[steps % 12]
        if any(parse_tab_label(str(ly.identifier or "")) is not None
               for ly in n.lyrics):
            displaced += 1
        n.lyrics = make_room(n)
        # WHISTLE_LYRIC_TAG marks these as fingerings rather than words. It
        # rides through MusicXML as <lyric name="wf"> and out the far side as a
        # title on Verovio's verse group, which is what lets the renderer swap
        # each one for a drawn circle without ever mistaking a sung "O" for an
        # open hole.
        for hole, symbol in enumerate(_whistle_symbols(pattern), start=1):
            n.addLyric(symbol, lyricNumber=hole, lyricIdentifier=WHISTLE_LYRIC_TAG)
        if steps >= 12:
            n.addLyric("+", lyricNumber=7, lyricIdentifier=WHISTLE_LYRIC_TAG)
        written += 1

    return {
        "part": part_label(part),
        "whistle": key,
        "notes_fingered": written,
        "guitar_tab_replaced": displaced,
        "unplayable": unplayable[:20],
        "unplayable_count": len(unplayable),
    }


# --------------------------------------------- guitar chord diagrams
#
# A chord diagram is a fact about the CHORD, so it hangs off the chord symbols
# the part already carries — `set-chords` writes them, `chart_style` places
# them — rather than off the notes underneath. A second notion of where a chord
# sits would fall out of step with the first one the moment either moved.
#
# What goes into the notation is the SHAPE, in the shorthand every guitarist
# reads: `[x,3,2,0,1,0]`, one entry per string from the low E up, `x` for a
# string that is not sounded, a number for the fret it is stopped at. Nothing
# else is stored, because nothing else has to be: the window of the neck to
# draw, whether the top line is the nut, where a barre lies and whether a
# "5 fr." label is needed all follow from those six values, by the rules below,
# which both renderers apply and neither invents.
#
# It rides as a <direction><words> at the chord symbol's own offset, and that
# is a deliberate second choice. MusicXML's own element for this is <frame>
# inside <harmony>, and music21 WRITES one — but it drops the frame notes on
# the way back in, and every version in the workspace is written and read back,
# so a diagram would survive exactly one op and then vanish. The shorthand
# survives the round trip, and it is not a renderer's private encoding either:
# exported to any other program it reads as the line a player would write.

# The marker text, and the pattern that finds it again. Mirrored in
# render.py::CHORD_DIAGRAM_RE and ios/Scoranger/ScoreModel/ChordDiagrams.swift.
#
# Two groups, and the second is optional: [frets] is where the dots go, and
# (fingers) is which finger goes on each one. The fingering is written ONLY
# when it differs from the frets -- which for an open C it does not, so the
# marker for a C stays the [x,3,2,0,1,0] it always was.
CHORD_DIAGRAM_RE = re.compile(
    r"\[(?:[x\d]{1,2},){5}[x\d]{1,2}\](?:\((?:[x\d],){5}[x\d]\))?")
CHORD_FINGERING_RE = re.compile(r"\((?:[x\d],){5}[x\d]\)")

# Sounding pitches of the open strings, low to high. Only their pitch classes
# decide a shape; the octaves are here so "the root is the lowest string that
# sounds" is a comparison and not a convention.
GUITAR_TUNINGS = {
    "EADGBE": ("E2", "A2", "D3", "G3", "B3", "E4"),
    "DADGAD": ("D2", "A2", "D3", "G3", "A3", "D4"),
    "DADGBE": ("D2", "A2", "D3", "G3", "B3", "E4"),
}
TUNING_ALIASES = {"STANDARD": "EADGBE", "DROPD": "DADGBE", "DROP-D": "DADGBE"}

# One hand covers four consecutive frets; a chart that asks for five is asking
# for a stretch nobody plays.
GUITAR_FRET_SPAN = 3
# Above the twelfth fret a six-string chord stops being a chord chart.
GUITAR_MAX_FRET = 12
# Four strings is the fewest that reads as a chord rather than a fragment —
# open D (xx0232) is four, and it is the thinnest shape anyone teaches.
GUITAR_MIN_STRINGS = 4
# Five fingers, one of them holding the neck.
GUITAR_MAX_FINGERS = 4
# How many frets the grid shows, and the rule for the nut: a shape that fits
# inside the first five frets is drawn against the nut; anything higher is
# drawn as a window, labelled with the fret it starts at.
GUITAR_GRID_FRETS = 5

# The published chart. The search below can find a shape for anything, but it
# does not know that x32010 is *the* C — asked for the lowest playable voicing
# it offers whatever the arithmetic likes. These are the shapes a player
# already has in their hands, and they are a table for the same reason the
# whistle's fingerings are a table: they are published fact, not a derivation.
# Standard tuning only; everything else goes to the search, which is what makes
# `--tuning` real rather than decorative.
#
# The chart is consulted FIRST and the search only after, so a chord with a
# conventional shape gets it even when the arithmetic would have found
# something lower. That is not the same rule as "lowest position", and the two
# disagree about A7 and Dm7: both can be played open, and both are written and
# played as fifth-fret barres in the turnaround they live in. The conventional
# shape wins, and the open one is one `--shape "A7=x02020"` away.
CONVENTIONAL_SHAPES = {
    "C": "x32010", "C7": "x32310", "Cmaj7": "x32000", "C6": "x32210",
    "D": "xx0232", "D7": "xx0212", "Dmaj7": "xx0222", "Dm": "xx0231",
    "Dm7": "x57565", "D6": "xx0202",
    "E": "022100", "E7": "020100", "Em": "022000", "Em7": "020000",
    "Emaj7": "021100",
    "F": "133211", "Fmaj7": "xx3210", "Fm": "133111",
    "G": "320003", "G7": "320001", "Gmaj7": "320002", "G6": "320000",
    "A": "x02220", "A7": "575655", "Am": "x02210", "Am7": "x02010",
    "Amaj7": "x02120", "A6": "x02222",
    "B7": "x21202", "Bm": "x24432", "Bm7": "x20202",
}

# Which FINGER goes on each dot. A separate table from the shape above, and it
# has to be: a fingering is a convention, not an arithmetic. Frets and fingers
# coincide for a C -- x32010 both ways -- and part company for a G, where the
# frets are 320003 and the hand is 320004, ring and middle low, PINKY on the
# top E. Nothing in the six fret numbers says that.
#
# Keyed by the shape rather than by the chord, because a fingering belongs to
# the hand and not to the name: the same six numbers are fingered the same way
# whatever chord they are called. 0 is an open string, x a silent one, 1-4 the
# fingers from index to little.
#
# Only open-position shapes are listed. Every movable shape derives from one of
# them by the rule every guitar method teaches -- the index bars the fret the
# nut used to be, and each of the other fingers steps up one -- which is
# `derived_fingering` below, and is why F, Fm, Bm and every barre the search
# finds are absent here and still come out right.
OPEN_FINGERINGS = {
    "x32010": "x32010",   # C
    "x32310": "x32410",   # C7    pinky reaches the third fret on the G string
    "x32000": "x32000",   # Cmaj7
    "x32210": "x42310",   # C6
    "xx0232": "xx0132",   # D
    "xx0212": "xx0213",   # D7
    "xx0222": "xx0111",   # Dmaj7  one finger across three strings
    "xx0231": "xx0231",   # Dm
    "xx0211": "xx0211",   # Dm7 (open)
    "xx0202": "xx0102",   # D6
    "022100": "023100",   # E
    "020100": "020100",   # E7
    "022000": "023000",   # Em
    "020000": "020000",   # Em7
    "021100": "031200",   # Emaj7
    "xx3210": "xx3210",   # Fmaj7
    "320003": "320004",   # G     the pinky on the top E
    "320001": "320001",   # G7
    "320002": "320001",   # Gmaj7
    "320000": "320000",   # G6
    "x02220": "x01230",   # A
    "x02020": "x02030",   # A7 (open)
    "x02210": "x02310",   # Am
    "x02010": "x02010",   # Am7
    "x02120": "x02130",   # Amaj7
    "x02222": "x01111",   # A6
    "x21202": "x21304",   # B7
    "x20202": "x10203",   # Bm7
}


def guitar_tuning(name: str) -> tuple[str, ...]:
    """The open strings of a named tuning, low to high."""
    key = name.upper().replace(" ", "")
    key = TUNING_ALIASES.get(key, key)
    if key not in GUITAR_TUNINGS:
        raise ValueError(f"No chart for the tuning '{name}'. "
                         f"Have: {sorted(GUITAR_TUNINGS)} "
                         f"(aliases: {sorted(TUNING_ALIASES)})")
    return GUITAR_TUNINGS[key]


def chord_symbol_text(cs) -> str:
    """The chord symbol as a player writes it: 'C', 'Am7', 'B-7'.

    music21's own `figure` first, because it carries the extensions a rebuilt
    name loses -- a C13 read back from the kind alone is a C, and a report that
    says "no shape for C" about a chord nobody can play is a wrong report.
    """
    figure = (cs.figure or "").strip()
    if figure:
        return figure
    root = cs.root()
    quality = {v: k for k, v in QUALITY_KINDS.items()}.get(cs.chordKind or "major", "")
    return f"{root.name}{quality}" if root is not None else ""


def _shape_from_text(text: str) -> list[int | None]:
    """'x32010' or 'x,10,9,7,8,x' -> six frets, None for a silent string."""
    parts = text.split(",") if "," in text else list(text)
    return [None if p.strip().lower() == "x" else int(p) for p in parts]


def shape_text(frets: list[int | None],
               fingers: list[int | None] | None = None) -> str:
    """Six frets -> the marker a player can read, and the fingering after it.

    Always comma-separated: a tenth fret is two digits and 'x109780' means
    nothing to anyone. The fingering is appended in parentheses ONLY when it
    says something the frets do not -- a G is '[3,2,0,0,0,3](3,2,0,0,0,4)' and
    a C is just '[x,3,2,0,1,0]', because for a C the two are the same numbers.
    """
    def group(values, open_, close):
        return open_ + ",".join("x" if f is None else str(f) for f in values) + close

    text = group(frets, "[", "]")
    if fingers is not None and list(fingers) != list(frets):
        text += group(fingers, "(", ")")
    return text


def parse_shape(text: str) -> list[int | None] | None:
    """The inverse, tolerant of the surrounding words. None when it is not one."""
    match = CHORD_DIAGRAM_RE.search(text or "")
    if match is None:
        return None
    frets = _shape_from_text(match.group(0).split("]")[0][1:])
    return frets if len(frets) == 6 else None


def parse_fingering(text: str) -> list[int | None] | None:
    """The fingering a marker carries, or None when it carries none.

    None means "the frets are the fingering" -- which is what the renderers
    fall back to, and what a shape nobody has curated a hand for gets.
    """
    match = CHORD_DIAGRAM_RE.search(text or "")
    if match is None:
        return None
    found = CHORD_FINGERING_RE.search(match.group(0))
    if found is None:
        return None
    fingers = _shape_from_text(found.group(0)[1:-1])
    return fingers if len(fingers) == 6 else None


def derived_fingering(frets: list[int | None]) -> list[int | None] | None:
    """The fingering of a movable shape, from the open shape it is a barre of.

    The rule every guitar method teaches, and the whole reason F, Fm, Bm and
    the shapes the search finds up the neck need no table of their own: the
    index bars the fret the nut used to be, and every other finger steps up
    one. E is 0-2-3-1-0-0; F, the same shape at the first fret, is 1-3-4-2-1-1.

    None when the shape is not a barre of anything curated, or when stepping
    up would ask for a fifth finger.
    """
    stopped = [f for f in frets if f]
    if not stopped or any(f == 0 for f in frets):
        return None                      # an open string means it is not barred
    base = min(stopped)
    relative = [None if f is None else f - base for f in frets]
    open_fingers = OPEN_FINGERINGS.get(
        "".join("x" if f is None else str(f) for f in relative))
    if open_fingers is None:
        return None
    out: list[int | None] = []
    for fret, finger in zip(relative, _shape_from_text(open_fingers)):
        if fret is None:
            out.append(None)
        elif fret == 0:
            out.append(1)                # the index, lying across the neck
        elif finger is None or finger + 1 > GUITAR_MAX_FINGERS:
            return None
        else:
            out.append(finger + 1)
    return out


def chord_fingering(frets: list[int | None]) -> list[int | None] | None:
    """Which finger goes on each fret of a shape, or None when nobody knows.

    Curated first, derived from the open shape second, and None third -- at
    which point the renderers show the frets, which is honest: a fret number
    is a fact about the shape, and inventing a hand for it would not be.
    """
    key = "".join("x" if f is None else str(f) for f in frets)
    curated = OPEN_FINGERINGS.get(key)
    if curated is not None:
        return _shape_from_text(curated)
    return derived_fingering(frets)


def diagram_window(frets: list[int | None]) -> tuple[int, bool]:
    """(first fret drawn, is the top line the nut?).

    A shape inside the first five frets is drawn against the nut, which is the
    thick line; anything higher is a window on the neck, starting at its lowest
    stopped fret and labelled with it. This is the whole of what decides both
    the thick line and the "5 fr." label, so the two can never disagree.
    """
    stopped = [f for f in frets if f]
    if not stopped or max(stopped) <= GUITAR_GRID_FRETS:
        return 1, True
    return min(stopped), False


def diagram_barre(frets: list[int | None]) -> tuple[int, int, int] | None:
    """(fret, lowest string, highest string) of the barre, or None.

    One finger lies across several strings when the lowest stopped fret is
    stopped on more than one string AND something is stopped above it in
    between — otherwise those are just two fingers that happen to share a fret.
    Drawn as one bar rather than as separate dots, which is what tells a player
    it is one finger.
    """
    stopped = {i: f for i, f in enumerate(frets) if f}
    if not stopped:
        return None
    low = min(stopped.values())
    at_low = sorted(i for i, f in stopped.items() if f == low)
    if len(at_low) < 2:
        return None
    first, last = at_low[0], at_low[-1]
    if not any(f > low for i, f in stopped.items() if first < i < last):
        return None
    # A finger lying across the neck stops every string it crosses, so a shape
    # with an OPEN string inside the span is not a barre and is not playable
    # either: the search rejects it on the finger count for the same reason.
    if any(frets[i] == 0 for i in range(first, last + 1)):
        return None
    return low, first, last


def _fingers_needed(frets: list[int | None]) -> int:
    stopped = {i: f for i, f in enumerate(frets) if f}
    barre = diagram_barre(frets)
    if barre is None:
        return len(stopped)
    fret, first, last = barre
    return 1 + sum(1 for i, f in stopped.items()
                   if not (f == fret and first <= i <= last))


def guitar_shape(pitch_classes: set[int], root_pc: int,
                 open_pitches: tuple[str, ...]) -> list[int | None] | None:
    """The lowest playable voicing of a chord, or None when there is none.

    Lowest position first: the search walks up the neck a fret at a time and
    stops at the first window that yields anything, so a chord that can be
    played open is played open. Within a window it prefers the voicing that
    sounds the most strings, then the one that sits lowest.

    The constraints are the ones a hand imposes: every chord tone present, the
    root the lowest string sounding, no silent string trapped between two
    sounding ones, four frets of reach, four fingers.
    """
    import itertools

    opens = [m21pitch.Pitch(p).midi for p in open_pitches]
    for base in range(0, GUITAR_MAX_FRET + 1):
        window = list(range(base, base + GUITAR_FRET_SPAN + 1))
        if base > 0:
            window = [0] + window
        choices = []
        for open_midi in opens:
            options: list[int | None] = [None]
            options += [f for f in window if (open_midi + f) % 12 in pitch_classes]
            choices.append(options)
        best = None
        for combo in itertools.product(*choices):
            sounded = [i for i, f in enumerate(combo) if f is not None]
            if len(sounded) < max(GUITAR_MIN_STRINGS, len(pitch_classes)):
                continue
            if sounded != list(range(sounded[0], sounded[-1] + 1)):
                continue      # a silenced string trapped inside the chord
            if (opens[sounded[0]] + combo[sounded[0]]) % 12 != root_pc:
                continue
            if {(opens[i] + combo[i]) % 12 for i in sounded} != pitch_classes:
                continue
            shape = list(combo)
            fingers = _fingers_needed(shape)
            if fingers > GUITAR_MAX_FINGERS:
                continue
            # Most strings first, then the fewest fingers -- which is what
            # picks the barre a player would use over three separate fingers
            # holding the same fret -- then the lowest reach.
            rank = (-len(sounded), fingers,
                    max(f for f in shape if f is not None))
            if best is None or rank < best[0]:
                best = (rank, shape)
        if best is not None:
            return best[1]
    return None


def parse_shape_overrides(pairs: list[str] | None) -> dict[str, list[int | None]]:
    """`--shape "A7=x02020"` -> {"A7": [None,0,2,0,2,0]}.

    The reader's say over the chart. A conventional shape is the right default
    and it is still a default: an arranger who wants the open A7 rather than
    the fifth-fret barre says so once, and the op writes what they asked for.
    """
    out: dict[str, list[int | None]] = {}
    for pair in pairs or []:
        name, sep, text = pair.partition("=")
        if not sep or not name.strip():
            raise ValueError(f"A shape override reads 'A7=x02020', not {pair!r}")
        try:
            frets = _shape_from_text(text.strip())
        except ValueError as bad:
            raise ValueError(f"{pair!r} is not six frets: {bad}") from bad
        if len(frets) != 6:
            raise ValueError(f"{pair!r} names {len(frets)} strings, not 6")
        out[name.strip()] = frets
    return out


def chord_diagrams(score, part, tuning: str = "EADGBE", clear: bool = False,
                   shapes: dict[str, list[int | None]] | None = None) -> dict:
    """Engrave a guitar chord diagram over every chord symbol on a part.

    The diagram is written as the shape shorthand at the symbol's own offset,
    and the fingering after it when the fingering says something the frets do
    not; the grid, the nut, the dots, the barre and the position label are
    drawn from those by the renderers. A chord nobody can play in the tuning
    asked for is REPORTED, with its measure and its symbol, and left without a
    diagram — the same way `check-range` reports what an instrument cannot
    reach.

    `shapes` pins named chords to shapes of the reader's choosing, ahead of the
    chart and the search both.
    """
    from music21 import expressions as m21expressions
    from music21 import harmony as m21harmony

    def markers(measure):
        return [e for e in measure.getElementsByClass(m21expressions.TextExpression)
                if parse_shape(e.content) is not None]

    measures = list(part.getElementsByClass(stream.Measure))
    if clear:
        cleared = 0
        for measure in measures:
            for old in markers(measure):
                measure.remove(old)
                cleared += 1
        return {"part": part_label(part), "cleared": cleared}

    # Nothing to hang a diagram on is a REFUSAL, not a successful no-op.
    #
    # This op draws over the chord symbols a part ALREADY carries -- set-chords
    # writes them, chart_style places them, and a second notion of where a
    # chord sits would fall out of step with the first the moment either moved.
    # Asked for a part with no symbols it therefore had nothing to do, and used
    # to return {"diagrams": 0} as a success WITH a new version. The agent
    # relays a successful op, the reader is told diagrams were added, and the
    # page is unchanged -- which is exactly what Ali reported in 0.6.10.
    #
    # The message names the parts that do carry symbols, because "this score
    # has no chord symbols at all" and "you asked for the wrong staff" are the
    # two ways to get here and they need different next steps.
    if not any(measure.getElementsByClass(m21harmony.ChordSymbol)
               for measure in measures):
        charted = [part_label(other)
                   for other in score.parts
                   if any(m.getElementsByClass(m21harmony.ChordSymbol)
                          for m in other.getElementsByClass(stream.Measure))]
        here = part_label(part)
        if charted:
            raise ValueError(
                f"'{here}' carries no chord symbols, so there is nothing to "
                f"draw a diagram over. These parts do: {charted}. Either pass "
                f"one of them, or give '{here}' symbols first with set-chords.")
        raise ValueError(
            f"'{here}' carries no chord symbols, and neither does any other "
            "part, so there is nothing to draw a diagram over. Run analyze to "
            "get per-bar harmony candidates, then set-chords to write them.")

    opens = guitar_tuning(tuning)
    drawn: list[dict] = []
    unplayable: list[dict] = []
    for measure in measures:
        for old in markers(measure):
            measure.remove(old)
        for symbol in measure.getElementsByClass(m21harmony.ChordSymbol):
            name = chord_symbol_text(symbol)
            pcs = {p.pitchClass for p in symbol.pitches}
            root = symbol.root()
            pinned = (shapes or {}).get(name)
            standard = guitar_tuning(tuning) == GUITAR_TUNINGS["EADGBE"]
            curated = CONVENTIONAL_SHAPES.get(name) if standard else None
            if pinned is not None:
                frets = list(pinned)
            elif curated:
                frets = _shape_from_text(curated)
            else:
                frets = (guitar_shape(pcs, root.pitchClass, opens)
                         if root is not None else None)
            if frets is None:
                unplayable.append({
                    "measure": measure.number, "symbol": name,
                    "why": f"no shape for {name} in {tuning.upper()} within "
                           f"{GUITAR_MAX_FRET} frets"})
                continue
            fingers = chord_fingering(frets)
            text = shape_text(frets, fingers)
            marker = m21expressions.TextExpression(text)
            marker.placement = "above"
            measure.insert(symbol.offset, marker)
            base, nut = diagram_window(frets)
            drawn.append({"measure": measure.number, "symbol": name,
                          "shape": shape_text(frets), "first_fret": base,
                          "nut": nut, "barre": diagram_barre(frets) is not None,
                          "fingering": (shape_text(fingers)[1:-1]
                                        if fingers is not None else None),
                          "from_chart": bool(curated) and pinned is None,
                          "pinned": pinned is not None})
    return {
        "part": part_label(part),
        "tuning": tuning.upper(),
        "diagrams": len(drawn),
        "shapes": drawn[:40],
        "unplayable": unplayable[:20],
        "unplayable_count": len(unplayable),
    }


# ------------------------------------------------------- guitar tablature
#
# Tab is the other half of what a guitarist reads, and it is a different
# question from the chord diagrams above: WHERE ON THE NECK this note is
# played, note by note, rather than what shape a chord is. The two are separate
# ops for that reason -- a lead sheet wants grids and no tab, a line being
# learned wants tab and no grids, and an arranger wants both on one staff.
#
# It is engraved the way the whistle's fingerings are, and for the same
# reasons: six lyric verses under the part, one per string, so the notation
# itself carries the tab. It sits under the right notehead, exports with the
# score, prints, and survives every later op -- none of which is true of
# anything drawn over the page.
#
# Verse 1 is the HIGHEST string, because that is how a tab staff is written:
# the top line is the string nearest the floor.
#
# What is stored is the fret number as text, and a dash for a string that is
# not played. The renderers draw the six lines of the tab staff through the
# dashes and leave the numbers standing in the gaps -- the dash is the
# meaning, the line is the drawing, exactly the arrangement the whistle's
# letters and circles have.

TAB_LYRIC_TAG = "gt"


def tab_label(size: float | None = None, dx: float | None = None,
              dy: float | None = None) -> str:
    """The lyric name a tab verse carries: the tag, and any adjustment.

    `gt`, `gt@1.5`, `gt@1.5,20,-30`. It looks like an encoding because it is
    one, and it is here rather than in three MusicXML attributes because
    Verovio carries a lyric's NAME through to the page (as @label, and as a
    <title> in the SVG) and drops its font-size and its offsets on the way.
    The offsets are written to the notation as well, in the fields MusicXML
    means for them, so an export to another program still carries the nudge --
    but the renderers read this, because this is what reaches them.
    """
    return _verse_label(TAB_LYRIC_TAG, size, dx, dy)


def parse_tab_label(label: str) -> tuple[float | None, float | None, float | None] | None:
    """(size ratio, dx, dy) from a tab verse's name, or None if it is not one."""
    return _parse_verse_label(TAB_LYRIC_TAG, label)


def _verse_label(tag: str, size: float | None, dx: float | None,
                 dy: float | None) -> str:
    """`gt`, `gt@1.5`, `ly@1.5,20,-30` -- one encoding, two tags."""
    if size is None and dx is None and dy is None:
        return tag
    parts = [f"{size:g}" if size is not None else ""]
    if dx is not None or dy is not None:
        parts += [f"{dx:g}" if dx is not None else "",
                  f"{dy:g}" if dy is not None else ""]
    return f"{tag}@" + ",".join(parts)


def _parse_verse_label(tag: str, label: str):
    """The numbers back out of a verse name, or None if it carries none."""
    if not label or not label.startswith(tag):
        return None
    rest = label[len(tag):]
    if not rest:
        return None, None, None
    if not rest.startswith("@"):
        return None
    fields = (rest[1:].split(",") + ["", ""])[:3]
    return tuple(float(f) if f else None for f in fields)


#: What a WORD's verse name says when it has been resized: `ly@1.5`.
#:
#: MusicXML has nowhere else to put it. `<lyric>` takes a position and a
#: placement but no font: the size belongs on the `<text>` inside it, which
#: music21 neither writes nor reads, so a size stored there would vanish the
#: next time any op rewrote the file. The NAME survives -- music21 round-trips
#: it as `Lyric.identifier` and Verovio carries it to the page -- which is the
#: same reason a tab column's size rides in `tab_label`. The verse NUMBER is
#: untouched, so which verse a syllable belongs to still comes from the
#: `number` attribute where it always did.
LYRIC_LABEL_TAG = "ly"


def lyric_label(size: float | None = None) -> str:
    """The verse name a resized word carries: `ly`, or `ly@1.5`."""
    return _verse_label(LYRIC_LABEL_TAG, size, None, None)


def parse_lyric_label(label: str) -> float | None:
    """The size ratio written on a word's verse name, or None if it has none."""
    parsed = _parse_verse_label(LYRIC_LABEL_TAG, str(label or ""))
    return None if parsed is None else parsed[0]


def word_verses(note) -> list:
    """The verses on a note that are WORDS -- not fingerings, not tab.

    A whistle's fingerings are verses 1-7 and a guitar tab's frets are verses
    1-6, written as lyrics because that is what puts them under the notehead.
    They are addressed by ops of their own, and a lyric op that swept them up
    would resize a tab column by being asked to resize the words.
    """
    return [ly for ly in note.lyrics
            if str(ly.identifier or "") != WHISTLE_LYRIC_TAG
            and parse_tab_label(str(ly.identifier or "")) is None]


def _free_verse(note) -> int:
    """The lowest verse number nothing on this note is already using."""
    taken = {int(ly.number) for ly in note.lyrics if ly.number}
    verse = 1
    while verse in taken:
        verse += 1
    return verse
# A string that is not played on this beat. It is a character every font has,
# unlike the box glyphs a tab staff would otherwise want.
TAB_REST = "-"
# Nobody reads a chord tab spread over more than a hand's width.
TAB_CHORD_SPAN = 4
# How far up the neck tab goes. Higher than a chord diagram's twelve, because
# a diagram past the twelfth fret is a curiosity and a melody up there is not:
# nineteen is where an acoustic's neck meets its body, and the last fret a
# player reaches without thinking about it.
TAB_MAX_FRET = 19


def _tab_string_frets(pitch_ps: float, opens: list[float], capo: int) -> list[int]:
    """Every string that can play this pitch, as (string index, fret) pairs,
    lowest fret first. A capo shortens every string by its own number of
    frets, and nothing below it can be played at all."""
    out = []
    for index, open_ps in enumerate(opens):
        fret = int(round(pitch_ps - open_ps))
        if capo <= fret <= TAB_MAX_FRET:
            out.append((index, fret - capo))
    return sorted(out, key=lambda pair: pair[1])


def _tab_layouts(pitches, opens: list[float], capo: int) -> list[tuple]:
    """Every way a hand could hold this note or chord, unranked.

    One string per note, in pitch order -- a guitar cannot play two notes on
    one string -- inside four frets. Unranked because the ranking is not a
    property of one note: which of these a player uses depends on where the
    hand already is, and that is `_tab_plan`'s question, not this one's.
    """
    import itertools

    options = [_tab_string_frets(p.ps, opens, capo) for p in pitches]
    if any(not o for o in options):
        return []
    out = []
    for combo in itertools.product(*options):
        strings = [s for s, _ in combo]
        if len(set(strings)) != len(strings) or strings != sorted(strings):
            continue
        frets = [f for _, f in combo]
        stopped = [f for f in frets if f > 0]
        if stopped and max(stopped) - min(stopped) >= TAB_CHORD_SPAN:
            continue
        out.append(combo)
    return out


# ---------------------------------------------------------- hand position
#
# A fret number on its own is not a tab. Every note has three or four frets
# that play it, one on each string that reaches it, and taking the lowest of
# them every time -- which is the one on the THINNEST string -- writes a melody
# as a single line climbing to the eighth and twelfth frets of the top string,
# on a neck where a player would have spread it over two strings and never left
# fifth position. That tab is arithmetically correct and nobody can read it.
#
# What a hand does instead is stay: it covers four frets, plays everything
# inside them, crosses strings freely, and SHIFTS only when the line leaves
# what it can reach. So the choice is made for the whole line at once, by the
# cheapest path through it -- which is a small dynamic program over (position,
# layout), one column per note.
#
# The costs below are a ranking, not a measurement. What they have to get right
# is the order: staying beats shifting, shifting a little beats shifting a lot,
# crossing a string is nearly free, and where nothing else decides it the line
# sits low on the neck and takes open strings when they are there.

# How many frets one hand covers without moving: index to little finger.
TAB_HAND_SPAN = 4
# And one more at either end, reached by stretching rather than by moving. This
# is not a refinement: Twinkle in C is played in first position with the pinky
# stretching to the fifth fret for the A, and a hand held to exactly four frets
# cannot play it there at all -- it has to shift, and shifting is worse.
TAB_STRETCH = 1
TAB_STRETCH_COST = 1.0
# What moving the hand costs. Most of it is FIXED, because most of what a shift
# costs is that it happens at all -- a hand that has to leave fifth position
# has left it whether it goes to the sixth fret or the fourteenth. A purely
# per-fret cost made a long shift so expensive that three notes at the nut
# were written at the fifteenth fret to avoid one.
TAB_SHIFT_COST = 2.0
TAB_SHIFT_PER_FRET = 0.2
# Crossing strings is what a hand in one position does all day.
TAB_CROSS_COST = 0.25
# What sitting up the neck costs, per note, and it is the SQUARE of the
# position -- the one number here that is not linear, and it has to be. A
# linear cost cannot hold both ends of the same rule: at the ratio that keeps
# a C scale in fifth position rather than shifting out of the nut to finish
# it, three notes at the nut get written at the fifteenth fret to save one
# shift up to a high note. Being fourteen frets up is not three and a half
# times worse than being four frets up. It is much worse, and squaring says
# so, which leaves both cases decided by a wide margin instead of a hair.
TAB_HEIGHT_COST = 0.015
# An open string rings, costs no finger and leaves the hand free, so where two
# layouts are otherwise equal the open one is the one a player takes -- at the
# nut. Up the neck the same open string is a reach back to a nut the hand left
# behind, and the second number takes the first one away again: an open E is
# worth having in first position and is an odd lone 0 in a line sitting at the
# eighth fret, which is where a flat bonus put one.
TAB_OPEN_BONUS = 0.1
TAB_OPEN_REACH = 0.05


def _tab_shift_cost(was: int, now: int) -> float:
    """What it costs the hand to move from one position to another."""
    if was == now:
        return 0.0
    return TAB_SHIFT_COST + TAB_SHIFT_PER_FRET * abs(now - was)


def _tab_hand_positions() -> range:
    """Every fret the index finger can sit at and still have a neck under it."""
    return range(1, TAB_MAX_FRET - TAB_HAND_SPAN + 2)


def _tab_height_cost(position: int) -> float:
    """What sitting the hand at this fret costs, per note. See TAB_HEIGHT_COST
    for why it is squared."""
    return TAB_HEIGHT_COST * position * position


def _tab_candidates(pitches, opens: list[float], capo: int) -> list[tuple]:
    """(position, layout, cost) for every hand that plays this note or chord.

    A layout with nothing stopped -- all open strings -- is offered at EVERY
    position, because an open string asks nothing of the hand: whatever
    position the line is in carries straight through it.

    It is not offered any cheaper, though. The cost of being at the eighth
    fret is the cost of being there, and it belongs to the position rather
    than to the notes that happen to be fretted: an open string that came for
    free had the hand leaving fifth position to reach across for an open E it
    could have played on the B string under its own finger.
    """
    out = []
    for layout in _tab_layouts(pitches, opens, capo):
        stopped = [f for _, f in layout if f > 0]
        rung = sum(1 for _, f in layout if f == 0)

        def open_value(position: int, rung: int = rung) -> float:
            return rung * (TAB_OPEN_BONUS - TAB_OPEN_REACH * (position - 1))

        if not stopped:
            out += [(p, layout, _tab_height_cost(p) - open_value(p))
                    for p in _tab_hand_positions()]
            continue
        low, high = min(stopped), max(stopped)
        if high - low > TAB_HAND_SPAN - 1 + 2 * TAB_STRETCH:
            continue
        for position in _tab_hand_positions():
            reach = [f - position for f in stopped]
            if min(reach) < -TAB_STRETCH or max(reach) > TAB_HAND_SPAN - 1 + TAB_STRETCH:
                continue
            stretched = sum(1 for r in reach
                            if r < 0 or r > TAB_HAND_SPAN - 1)
            out.append((position, layout, _tab_height_cost(position)
                        + TAB_STRETCH_COST * stretched - open_value(position)))
    return out


def _tab_plan(events: list, opens: list[float], capo: int,
              start: int | None = None) -> list[tuple | None]:
    """The layout for each event, chosen for the whole line rather than one
    note at a time. None where nothing plays it.

    A shortest path: each column is the hands that could play that note, each
    edge is what it costs to get there from the hand before it, and the answer
    is the cheapest way through. Events nothing can play are holes -- the line
    joins across them, because a note the guitar cannot reach does not move the
    hand anywhere.

    `start` PINS the first hand rather than nudging it: an arranger who asks
    for the line in seventh position is not making a suggestion. It is dropped
    only where nothing at all can be played there, since refusing to write a
    tab is worse than writing one somewhere else and saying so.
    """
    columns: list[list[tuple]] = []
    costs: list[list[float]] = []
    backs: list[list[int]] = []
    previous = -1                       # index of the last column with any hand

    for pitches in events:
        states = _tab_candidates(pitches, opens, capo) if pitches else []
        if start is not None and previous < 0 and states:
            pinned = [s for s in states if s[0] == start]
            states = pinned or states
        columns.append(states)
        if not states:
            costs.append([])
            backs.append([])
            continue
        here_costs, here_backs = [], []
        for position, layout, own in states:
            string = min(s for s, _ in layout)
            if previous < 0:
                here_costs.append(own)
                here_backs.append(-1)
                continue
            best, best_back = None, -1
            for j, (was, was_layout, _) in enumerate(columns[previous]):
                total = (costs[previous][j]
                         + _tab_shift_cost(was, position)
                         + TAB_CROSS_COST
                         * abs(string - min(s for s, _ in was_layout)))
                if best is None or total < best:
                    best, best_back = total, j
            here_costs.append(own + best)
            here_backs.append(best_back)
        costs.append(here_costs)
        backs.append(here_backs)
        previous = len(columns) - 1

    chosen: list[tuple | None] = [None] * len(events)
    if previous < 0:
        return chosen
    index = min(range(len(costs[previous])), key=lambda i: costs[previous][i])
    while previous >= 0:
        chosen[previous] = columns[previous][index]
        index = backs[previous][index]
        if index < 0:
            break
        previous = max((i for i in range(previous) if columns[i]), default=-1)
    return chosen


def guitar_tab(score, part, tuning: str = "EADGBE", capo: int = 0,
               clear: bool = False, position: int | None = None) -> dict:
    """Write guitar tablature under a part, as six stacked lyric verses.

    Chosen for the LINE, not for one note at a time: the hand covers four
    frets, plays what is inside them across the strings, and shifts only where
    the music leaves its reach. Every shift is in the report, with the bar it
    happens in, because a shift is the one thing a player has to see coming.

    `position` pins the fret the hand starts at, for an arranger who wants the
    line read in a particular position; left alone, the tab settles as low on
    the neck as the music allows.

    A chord is laid out as a whole -- one string per note, inside four frets --
    so it can force a position higher than any of its notes would have taken
    alone, and the report says so, bar by bar.

    Notes the tuning cannot play are reported and left without a fret. Nothing
    is transposed to make it fit: a note an octave below the bottom string is
    the arrangement's problem to solve, not the tab's to hide.
    """
    from music21 import harmony as m21harmony

    def playable_notes(container):
        """The notes a guitarist plays.

        `recurse().notes` includes the chord SYMBOLS: a ChordSymbol is a Chord
        in music21, so a part carrying a chart would have had tab written onto
        its symbols as well as its notes -- six verses hung on an element that
        is not on the staff at all.
        """
        return [n for n in container.recurse().notes
                if not isinstance(n, m21harmony.Harmony)]

    if clear:
        cleared = 0
        for n in playable_notes(part):
            kept = [ly for ly in n.lyrics
                    if parse_tab_label(str(ly.identifier or "")) is None]
            if len(kept) != len(n.lyrics):
                n.lyrics = kept
                cleared += 1
        return {"part": part_label(part), "cleared": cleared}

    opens = [m21pitch.Pitch(p).ps for p in guitar_tuning(tuning)]
    if capo < 0 or capo > TAB_MAX_FRET:
        raise ValueError(f"A capo goes on frets 0-{TAB_MAX_FRET}, not {capo}")
    if position is not None and position not in _tab_hand_positions():
        raise ValueError(f"A hand sits at frets {_tab_hand_positions()[0]}-"
                         f"{_tab_hand_positions()[-1]}, not {position}")

    notes = list(playable_notes(part))
    # A tab's frets are verses 1-6 and a whistle's fingerings are verses 1-7,
    # so one note cannot carry both -- and music21's `addLyric` writes the TEXT
    # of the verse at that number and leaves its NAME alone, which put fret
    # numbers under a `wf` label and drew "3" as a row of circles. This op runs
    # last, so it takes those verses outright and the report says how many
    # notes it took them from.
    displaced = sum(1 for n in notes
                    if any(str(ly.identifier or "") == WHISTLE_LYRIC_TAG
                           for ly in n.lyrics))
    for n in notes:
        # verses 1-6, and the whistle's seventh: the overblown mark would
        # otherwise be left hanging under a tab that has no octave to mark
        n.lyrics = [ly for ly in n.lyrics
                    if (ly.number or 0) > len(opens)
                    and str(ly.identifier or "") != WHISTLE_LYRIC_TAG]
    voiced = [sorted(n.pitches, key=lambda p: p.ps) for n in notes]
    # more notes than strings is not a hand the planner should be asked about
    events = [pitches if len(pitches) <= len(opens) else [] for pitches in voiced]
    plan = _tab_plan(events, opens, capo, start=position)

    written = 0
    unplayable: list[dict] = []
    raised: list[dict] = []
    shifts: list[dict] = []
    at: int | None = position
    for n, pitches, state in zip(notes, voiced, plan):
        if state is None:
            if len(pitches) > len(opens):
                why = f"{len(pitches)} notes on {len(opens)} strings"
            else:
                reasons = []
                for p in pitches:
                    if not _tab_string_frets(p.ps, opens, capo):
                        low = min(opens) + capo
                        if p.ps >= low:
                            reason = f"above the {TAB_MAX_FRET}th fret"
                        elif capo:
                            reason = f"below the capo at fret {capo}"
                        else:
                            reason = "below the lowest string"
                        reasons.append(f"{p.nameWithOctave} is {reason}")
                why = "; ".join(reasons) or "no hand shape inside four frets"
            unplayable.append({
                "bar": bar_label(n),
                "pitch": ", ".join(p.nameWithOctave for p in pitches),
                "why": why})
            continue
        where, layout, _ = state
        # A shift is the one thing a player has to see coming, so every one of
        # them is in the report with the bar it lands in. Nothing is reported
        # for a note played entirely on open strings: the hand did not move,
        # it was not asked for.
        if any(f for _, f in layout) and at is not None and where != at:
            shifts.append({"bar": bar_label(n), "from": at, "to": where})
        if any(f for _, f in layout):
            at = where
        elif at is None:
            at = where
        # what a CHORD's notes would have cost one at a time, so a chord that
        # pushed the hand up on its own account can say so
        if len(pitches) > 1:
            alone = max(_tab_string_frets(p.ps, opens, capo)[0][1] for p in pitches)
            highest = max(f for _, f in layout)
            if highest > alone:
                raised.append({"bar": bar_label(n), "to_fret": highest,
                               "lowest_alone": alone})
        frets = {string: fret for string, fret in layout}
        # verse 1 is the HIGHEST string: a tab staff's top line is the string
        # nearest the floor
        for verse, string in enumerate(reversed(range(len(opens))), start=1):
            text = str(frets[string]) if string in frets else TAB_REST
            # applyRaw, or music21 reads the dash as a hyphenated syllable and
            # keeps the syllabic rather than the text
            n.addLyric(text, lyricNumber=verse, applyRaw=True,
                       lyricIdentifier=tab_label())
        written += 1

    played = [s for s in plan if s is not None and any(f for _, f in s[1])]
    return {
        "part": part_label(part),
        "tuning": tuning.upper(),
        "capo": capo,
        "notes_tabbed": written,
        "whistle_fingerings_replaced": displaced,
        "position": played[0][0] if played else None,
        "highest_fret": max((f for s in plan if s is not None
                             for _, f in s[1]), default=0),
        "shifts": shifts[:20],
        "shift_count": len(shifts),
        "positions_raised": raised[:20],
        "positions_raised_count": len(raised),
        "unplayable": unplayable[:20],
        "unplayable_count": len(unplayable),
    }


def clear_stale_diagrams(score, names: list[str] | None = None) -> int:
    """Drop chord diagrams whose chords have moved out from under them.

    A shape is six frets, and six frets are one chord: transpose the music and
    every diagram on it describes the chord that used to be there. The symbols
    themselves move -- music21 transposes a ChordSymbol -- so the page would
    show a C grid over a D, which is worse than showing nothing.

    Removing them and saying so in the report is the honest half of that: the
    shapes are one `chord-diagrams` away, and a stale diagram is a lie a player
    would act on.
    """
    from music21 import expressions as m21expressions

    parts = find_parts(score, names) if names else list(score.parts)
    removed = 0
    for part in parts:
        for measure in part.getElementsByClass(stream.Measure):
            for marker in [e for e in measure.getElementsByClass(
                    m21expressions.TextExpression)
                    if parse_shape(e.content) is not None]:
                measure.remove(marker)
                removed += 1
    return removed


# What `adjust-element` can move and resize. A chord DIAGRAM is addressed the
# same way its chord symbol is, and nudged through the same three MusicXML
# fields, because the alternative -- a second mechanism for a second kind of
# added element -- is how two things that look alike start behaving
# differently. Every kind below is there for the same reason.
# The point size an added element draws at when nobody has adjusted it. It is
# the unit a RELATIVE size is measured in: see `adjust_element`. Mirrored by
# render.DEFAULT_DIAGRAM_POINTS and ChordDiagrams.defaultPoints.
DEFAULT_ELEMENT_POINTS = 12.0


class ElementKind(NamedTuple):
    """How one class of added element is found, attached and edited."""

    #: what to call it in a message a person reads
    noun: str
    #: "offset" -- it sits in its measure at an offset of its own, so it moves
    #:             by being re-inserted at another measure and offset;
    #: "note"   -- it hangs off a note and has no offset of its own, so it
    #:             moves by being detached from one note and attached to
    #:             another;
    #: "lyric"  -- it IS a note, adjusted through the whole COLUMN of verses
    #:             written onto it (a tab column, a whistle fingering).
    #:             Nothing about it can be moved without moving the music.
    #:             A single sung WORD is not this: one verse of one note is a
    #:             thing of its own, so `lyric` is anchored "note" and moves
    #:             by re-attaching, like a fermata.
    anchor: str
    movable: bool


ELEMENT_KINDS: dict[str, ElementKind] = {
    "harm": ElementKind("chord symbol", "offset", True),
    "diagram": ElementKind("chord diagram", "offset", True),
    "dynamic": ElementKind("dynamic", "offset", True),
    "text": ElementKind("text mark", "offset", True),
    "fermata": ElementKind("fermata", "note", True),
    "articulation": ElementKind("articulation", "note", True),
    # An ORNAMENT is a note-attached mark like a fermata, and it is a
    # SEPARATE kind from one rather than a value of it: music21 keeps
    # ornaments in `expressions` beside the Fermata but under their own base
    # class, `expressions.Ornament`, which Fermata is not a subclass of. The
    # two finders below therefore never see each other's marks, and a reader
    # who says "take the roll off bar 12" does not also lose the fermata
    # there. ABC's decorations are where most of these arrive: see
    # `enrich.DECORATIONS`.
    "ornament": ElementKind("ornament", "note", True),
    # A WORD. It hangs off a note like a fermata does, so it moves the way a
    # fermata moves -- off one note and onto another -- and that is the only
    # motion a syllable has: a verse is drawn under the notehead it belongs
    # to, and a word that slid sideways from its note would be a word under
    # a different note, spelt as a lie about where it is. See `adjust_element`
    # for why it refuses an offset and takes a size.
    "lyric": ElementKind("lyric", "note", True),
    "tab": ElementKind("tabbed note", "lyric", False),
}

ADJUSTABLE_KINDS = set(ELEMENT_KINDS)
MOVABLE_KINDS = {name for name, spec in ELEMENT_KINDS.items() if spec.movable}

# Three kinds are already CREATED by an op of their own, and `add-element` must
# not become a second door to any of them. A chord symbol placed by a second
# mechanism would fall out of step with `chart_style`'s placement the moment
# either moved; a diagram is derived from the symbol it sits over; a tab column
# is six verses on a note that `guitar-tab` chooses as a line, not one at a
# time. Naming the op that owns each is more use than a bare refusal.
CREATED_BY = {"harm": "set-chords", "diagram": "chord-diagrams",
              "tab": "guitar-tab"}
ADDABLE_KINDS = set(ELEMENT_KINDS) - set(CREATED_BY)

# What `add-element --kind dynamic --value` will take. music21 will build a
# Dynamic out of any string at all and silently give an unknown one a default
# loudness, which would then be PLAYED -- so the list is checked here.
DYNAMIC_MARKS = ("pppppp", "ppppp", "pppp", "ppp", "pp", "p", "mp", "mf",
                 "f", "ff", "fff", "ffff", "fffff", "ffffff",
                 "fp", "sf", "sfz", "sffz", "fz", "rf", "rfz", "sfp")

# The articulations a person asks for by name, in MusicXML's own spelling.
# Curated rather than derived from music21's module: `dir(articulations)`
# holds forty-odd classes, most of them instrument techniques nobody is
# reaching for from a chat line, and several that are not articulations at all.
ARTICULATION_MARKS = {
    "accent": "Accent", "strong-accent": "StrongAccent", "marcato": "StrongAccent",
    "staccato": "Staccato", "staccatissimo": "Staccatissimo", "tenuto": "Tenuto",
    "detached-legato": "DetachedLegato", "spiccato": "Spiccato",
    "up-bow": "UpBow", "down-bow": "DownBow", "harmonic": "Harmonic",
    "stopped": "Stopped", "open-string": "OpenString", "doit": "Doit",
    "falloff": "Falloff", "plop": "Plop", "scoop": "Scoop",
    "breath-mark": "BreathMark", "caesura": "Caesura",
}

# The ornaments a person asks for by name -> the music21 class. Curated, like
# ARTICULATION_MARKS above and for the same reason: `expressions.Ornament` has
# subclasses nobody is reaching for from a chat line.
#
# `roll` is here because it is what Irish players call the figure, and it is
# the same object as `turn` -- see `enrich.DECORATIONS` for why an Irish roll
# is engraved as a turn and what that costs. Asking for either draws the ∾.
#
# TREMOLO IS DELIBERATELY ABSENT, and this is where someone would add it.
# music21 WRITES a `<tremolo>` with its font-size and relative-x/y and then
# reads it back WITHOUT them. Every op in this engine writes a version and
# reads it back, so a resized tremolo would lose its size at the next op --
# an adjustment that appears to work and quietly expires. The same is true of
# `<fermata>`, which is a pre-existing gap in `adjust-element --kind fermata`
# and not this table's to fix. The six below all round-trip all three fields.
ORNAMENT_MARKS = {
    "roll": "Turn", "turn": "Turn", "inverted-turn": "InvertedTurn",
    "trill": "Trill",
    "mordent": "Mordent", "lower-mordent": "Mordent",
    "inverted-mordent": "InvertedMordent",
    "upper-mordent": "InvertedMordent", "pralltriller": "InvertedMordent",
    "slide": "Schleifer", "schleifer": "Schleifer",
}

#: the music21 classes `_elements_in_measure` will call an ornament. Named
#: rather than `isinstance(e, expressions.Ornament)`, so the set a reader can
#: FIND is the same set they can ADD, resize and move -- a Tremolo that could
#: be selected but not durably adjusted is the silent half-failure the table
#: above exists to avoid.
ORNAMENT_CLASSES = tuple(sorted(set(ORNAMENT_MARKS.values())))

# A fermata's shape, as MusicXML spells it and music21 stores it.
FERMATA_SHAPES = ("normal", "angled", "square")

# SPANNERS ARE OUT OF SCOPE, and this is where someone would add them.
#
# A slur, a hairpin, an 8va bracket and a pedal line each name TWO anchors. A
# destination in this app names ONE bar and one offset inside it, so it states
# where one end goes and says nothing about the other. The moment the
# destination's rhythm differs from the source's there is no rule that picks
# the far anchor: the nearest note, the same beat, and the same note index all
# disagree, and each of the three is wrong on some real score. There is no
# deterministic answer, so the op refuses by name instead of guessing one --
# and a guess here silently re-phrases the music, which is worse than a
# refusal the reader can act on by redrawing the spanner.
SPANNER_KINDS = {"slur", "hairpin", "crescendo", "diminuendo", "wedge",
                 "ottava", "octave-shift", "bracket", "pedal", "glissando",
                 "trill-extension", "line"}


def _element_kind(kind: str, verb: str, allowed: set[str]) -> ElementKind:
    """The spec for an element kind, or a refusal naming what is allowed."""
    if kind in SPANNER_KINDS:
        # The reason depends on the verb. For everything that names a
        # DESTINATION it is that a spanner has two anchors and a destination
        # names one bar. A removal names no destination, so that reason would
        # be false: what is true there is that this family finds marks
        # attached to notes and bars, and a spanner is attached to neither.
        why = ("this family addresses marks that sit in a bar or hang off a "
               "note, and a spanner is a score-level object attached to "
               "neither, so it is not among the elements this op can see"
               if verb == "remove" else
               "a spanner names two anchors and a destination names one bar, "
               "so where its far end lands is undefined as soon as the "
               "destination's rhythm differs from the source's")
        raise ValueError(
            f"'{kind}' is a spanner, and this op does not {verb} spanners: "
            f"{why}. Redraw it instead.")
    if kind not in allowed:
        raise ValueError(
            f"Cannot {verb} '{kind}'. Can {verb}: {sorted(allowed)}")
    return ELEMENT_KINDS[kind]


def _elements_in_measure(measure, kind: str) -> list[tuple]:
    """Every element of one kind in one measure, in document order.

    Returns (holder, element) pairs: the holder is the stream an
    offset-anchored element sits in, or the note a note-attached one hangs
    off. Ordinals index THIS list, so `adjust_element`, `move_element` and the
    app's ScoreAddress all name the same thing by the same numbers -- which is
    the reason it is one function and not one per op.
    """
    from music21 import articulations as m21articulations
    from music21 import dynamics as m21dynamics
    from music21 import expressions as m21expressions
    from music21 import harmony as m21harmony

    if kind == "harm":
        return [(measure, e)
                for e in measure.getElementsByClass(m21harmony.ChordSymbol)]
    if kind == "diagram":
        return [(measure, e)
                for e in measure.getElementsByClass(m21expressions.TextExpression)
                if parse_shape(e.content) is not None]
    if kind == "text":
        # Text another op owns is excluded by that op's own marker: a rehearsal
        # mark belongs to `set-rehearsal` and a six-fret shape to
        # `chord-diagrams`. What is left is text a person put there.
        return [(measure, e)
                for e in measure.getElementsByClass(m21expressions.TextExpression)
                if not isinstance(e, m21expressions.RehearsalMark)
                and parse_shape(e.content) is None]
    if kind == "dynamic":
        return [(measure, e)
                for e in measure.getElementsByClass(m21dynamics.Dynamic)]
    if kind in ("fermata", "articulation", "ornament", "tab", "lyric"):
        # A chord SYMBOL is a Chord to music21, so it comes back from
        # `.notes` and is not on the staff at all -- the same trap
        # `whistle_fingerings` and `guitar_tab` were both written around.
        notes = [n for n in measure.recurse().notes
                 if not isinstance(n, m21harmony.Harmony)]
        if kind == "tab":
            # the NOTE is the element: its six verses are one column, and they
            # move and resize together or the column comes apart
            return [(n, n) for n in notes
                    if any(parse_tab_label(str(ly.identifier or "")) is not None
                           for ly in n.lyrics)]
        if kind == "lyric":
            # In verse order within each note, so ordinal 0 of a bar is the
            # first syllable of the first verse -- what a reader counting
            # words along the line would point at.
            return [(n, ly) for n in notes
                    for ly in sorted(word_verses(n), key=lambda l: l.number or 0)]
        if kind == "fermata":
            return [(n, e) for n in notes for e in n.expressions
                    if isinstance(e, m21expressions.Fermata)]
        if kind == "ornament":
            wanted = tuple(getattr(m21expressions, c) for c in ORNAMENT_CLASSES)
            return [(n, e) for n in notes for e in n.expressions
                    if isinstance(e, wanted)]
        return [(n, e) for n in notes for e in n.articulations
                if isinstance(e, m21articulations.Articulation)]
    raise ValueError(f"no finder for element kind {kind!r}")


def _attached_list(owner, kind: str) -> list:
    """The list on a note that a note-attached kind lives in."""
    if kind in ("fermata", "ornament"):
        return owner.expressions
    if kind == "articulation":
        return owner.articulations
    if kind == "lyric":
        return owner.lyrics
    raise ValueError(f"{kind!r} is not attached to a note")


def adjust_element(score, name: str, kind: str = "harm",
                   measure: int | None = None, ordinal: int = 0,
                   size: float | None = None, scale: float | None = None,
                   offset_x: float | None = None, offset_y: float | None = None,
                   reset: bool = False, all_elements: bool = False) -> dict:
    """Change how big an added element is, and where it sits.

    The adjustment lives in the notation -- MusicXML's `font-size`,
    `relative-x` and `relative-y` -- so it travels with the score, exports to
    any other program, and survives a change of device. music21 round-trips
    all three exactly; what neither it nor MusicXML can do is make Verovio
    honour them, which is the renderer's job (see render.py).

    SIZE IS RELATIVE TO THE ENGRAVED DEFAULT, not a point size. That is the
    decided question: a reader asking for a bigger chord symbol means bigger
    than the ones around it, and a page they later engrave at another scale
    must keep the same proportion. So `scale` is the interface -- 1.0 is the
    default, 1.5 is half again -- and it is multiplied by
    DEFAULT_ELEMENT_POINTS on the way into the file because MusicXML has no
    relative font size to write. Every reader divides by the same constant:
    render.py, ChordDiagrams.swift and the tab label all do.

    `size` remains for the callers that hold an absolute point value already
    (the app's adjust row, which reads one back out of the notation); pass one
    or the other, never both. The value is stored PER ELEMENT: a global text
    size moving under everyone is the bug this feature exists to make
    impossible.

    `measure` + `ordinal` addresses one element the way the app's ScoreAddress
    does, so the UI passes exactly what the user selected. `all_elements`
    reaches every one in the part, for "make all the chord names bigger".
    """
    spec = _element_kind(kind, "adjust", ADJUSTABLE_KINDS)

    if kind == "lyric" and (offset_x is not None or offset_y is not None):
        # Refused by name rather than written and ignored. A verse is laid out
        # under its own notehead, in a line whose spacing the engraver owns;
        # Verovio takes no offset on one, and MusicXML's relative-x/y on a
        # <lyric> would ride in the file, change nothing on any page this app
        # draws, and read back as an adjustment that had been made.
        raise ValueError(
            "A lyric cannot be nudged: the word sits under the note it "
            "belongs to, and nothing this app renders honours an offset on "
            "one. To put a word somewhere else, move it to the note it "
            "belongs under (`move-element --kind lyric`); to change how it "
            "looks, pass a size.")

    if size is not None and scale is not None:
        raise ValueError("Pass a scale or a size, not both")
    if scale is not None:
        if scale <= 0:
            raise ValueError(f"A scale must be greater than 0 (got {scale})")
        size = float(scale) * DEFAULT_ELEMENT_POINTS
    if not reset and size is None and offset_x is None and offset_y is None:
        raise ValueError("Nothing to change: pass a size, a scale, an offset, "
                         "or --reset")

    part = find_parts(score, [name])[0]
    measures = {m.number: m for m in part.getElementsByClass(stream.Measure)}

    if all_elements:
        targets = [e for m in measures.values()
                   for _holder, e in _elements_in_measure(m, kind)]
        if not targets:
            raise ValueError(f"No {spec.noun}s in part '{part_label(part)}'")
    else:
        if measure is None:
            raise ValueError("Which one? Pass a measure, or --all for the whole part")
        m = measures.get(measure)
        found = _elements_in_measure(m, kind) if m is not None else []
        if not 0 <= ordinal < len(found):
            raise ValueError(
                f"No {spec.noun} #{ordinal} in measure {measure} of "
                f"'{part_label(part)}' (it has {len(found)})")
        targets = [found[ordinal][1]]

    for element in targets:
        if kind == "lyric":
            # The size rides in the verse NAME (see LYRIC_LABEL_TAG); a reset
            # puts the plain verse number back, which is what the name said
            # before anybody resized anything.
            element.identifier = (str(element.number or 1) if reset
                                  else lyric_label(size / DEFAULT_ELEMENT_POINTS))
            continue
        if spec.anchor == "lyric":
            # A tab column's size and offset ride in the lyric NAME as well as
            # in the style: Verovio carries the name to the page and drops the
            # rest, so that is the copy the renderers can see. One place writes
            # both, so they cannot say different things.
            for lyric in element.lyrics:
                if not (lyric.identifier
                        and str(lyric.identifier).startswith(TAB_LYRIC_TAG)):
                    continue
                if reset:
                    lyric.identifier = TAB_LYRIC_TAG
                    lyric.style.relativeX = None
                    lyric.style.relativeY = None
                    continue
                had = parse_tab_label(str(lyric.identifier)) or (None, None, None)
                ratio = (size / DEFAULT_ELEMENT_POINTS) if size is not None else had[0]
                dx = offset_x if offset_x is not None else had[1]
                dy = offset_y if offset_y is not None else had[2]
                lyric.identifier = tab_label(ratio, dx, dy)
                if dx is not None:
                    lyric.style.relativeX = dx
                if dy is not None:
                    lyric.style.relativeY = dy
            continue
        if reset:
            element.style.fontSize = None
            element.style.relativeX = None
            element.style.relativeY = None
            continue
        if size is not None:
            element.style.fontSize = size
        if offset_x is not None:
            element.style.relativeX = offset_x
        if offset_y is not None:
            element.style.relativeY = offset_y

    return {"part": part_label(part), "kind": kind, "adjusted": len(targets),
            "reset": reset,
            "size": None if reset else size,
            "scale": None if (reset or size is None)
            else size / DEFAULT_ELEMENT_POINTS,
            "offset": None if reset else [offset_x, offset_y]}


def _make_element(kind: str, value: str | None, placement: str | None):
    """The music21 object for one added element, or a refusal naming the choices."""
    from music21 import articulations as m21articulations
    from music21 import dynamics as m21dynamics
    from music21 import expressions as m21expressions

    if kind == "dynamic":
        mark = (value or "").strip()
        if mark not in DYNAMIC_MARKS:
            raise ValueError(
                f"'{mark}' is not a dynamic. Choices: {list(DYNAMIC_MARKS)}")
        element = m21dynamics.Dynamic(mark)
    elif kind == "text":
        words = (value or "").strip()
        if not words:
            raise ValueError("A text mark needs words: pass --value \"dolce\"")
        if parse_shape(words) is not None:
            raise ValueError(
                f"'{words}' reads as a chord-diagram shape, which is how "
                "`chord-diagrams` marks its own text. Pick other words, or "
                "use `chord-diagrams` if a diagram is what you meant.")
        element = m21expressions.TextExpression(words)
    elif kind == "fermata":
        shape = (value or "normal").strip()
        if shape not in FERMATA_SHAPES:
            raise ValueError(
                f"'{shape}' is not a fermata shape. Choices: {list(FERMATA_SHAPES)}")
        element = m21expressions.Fermata()
        element.shape = shape
        # music21 defaults a Fermata to `inverted`, which MusicXML draws
        # UNDER the note. A fermata asked for with no side goes above.
        element.type = "upright" if placement != "below" else "inverted"
    elif kind == "articulation":
        mark = (value or "").strip().lower()
        if mark not in ARTICULATION_MARKS:
            raise ValueError(
                f"'{mark}' is not an articulation. Choices: "
                f"{sorted(ARTICULATION_MARKS)}")
        element = getattr(m21articulations, ARTICULATION_MARKS[mark])()
    elif kind == "ornament":
        mark = (value or "").strip().lower()
        if mark not in ORNAMENT_MARKS:
            raise ValueError(
                f"'{mark}' is not an ornament. Choices: "
                f"{sorted(ORNAMENT_MARKS)}")
        element = getattr(m21expressions, ORNAMENT_MARKS[mark])()
    elif kind == "lyric":
        from music21 import note as m21note

        word = (value or "").strip()
        if not word:
            raise ValueError('A lyric needs a word: pass --value "la"')
        if placement is not None:
            # Same refusal as the offset in `adjust_element`, for the same
            # reason: MusicXML takes a placement on a <lyric> and every
            # renderer here draws verses below the staff regardless.
            raise ValueError(
                "A lyric takes no placement: verses are drawn below the "
                "staff, and asking for 'above' would be written down and "
                "ignored. (Whistle fingerings are the exception, and the "
                "renderer moves those itself.)")
        # The verse it lands in is decided when it is attached, by the note
        # it is attached TO -- see `add_element`.
        element = m21note.Lyric(text=word, applyRaw=True)
        return element
    else:
        raise ValueError(f"no constructor for element kind {kind!r}")

    if placement is not None:
        if placement not in ("above", "below"):
            raise ValueError(
                f"placement is 'above' or 'below' (got '{placement}')")
        element.placement = placement
    return element


def add_element(score, name: str, kind: str, measure: int,
                value: str | None = None, offset: float = 0.0,
                placement: str | None = None) -> dict:
    """Put a dynamic, a text mark, a fermata or an articulation on the page.

    The op the toolset was missing. `adjust_element` could size and place an
    added mark, and `move_element` could move one, but nothing in the app or
    the engine could ADD one -- so every one of them had to already be in the
    file the score was imported from.

    THE DESTINATION IS THE SAME ONE A MOVE TAKES: a bar plus an offset inside
    it, in quarter notes from the barline, because this app has no drag. And
    the two element classes land by the same two mechanics `move_element`
    uses, for the same reason -- an offset-anchored mark is inserted at the
    offset, a note-attached one is attached to the note that STARTS there, and
    if nothing does the op refuses and lists the onsets rather than guessing.

    SPANNERS are refused by name, as they are everywhere else in this family.
    So are the three kinds that already have a creating op of their own
    (CREATED_BY): a second way to make a chord symbol is how two things that
    look alike start behaving differently.

    The report carries the ORDINAL the new element landed at, so the caller
    can address it with `adjust-element` or `move-element` without guessing
    where in the bar's document order it went.
    """
    if kind in CREATED_BY:
        spec = ELEMENT_KINDS[kind]
        raise ValueError(
            f"A {spec.noun} is added by `{CREATED_BY[kind]}`, not by this op. "
            f"Can add: {sorted(ADDABLE_KINDS)}")
    spec = _element_kind(kind, "add", ADDABLE_KINDS)
    if kind == "text" and is_chord_symbol_text(value):
        # Ali, 0.17.0: asked for "E minor in the second half of bar 8", the
        # chat wrote the word "Em" as a TEXT mark -- engraved lower than the
        # chart and in italics, because that is what a text mark is. A chord
        # name is a chord symbol, and set-chords places one mid-bar by offset.
        raise ValueError(
            f"'{value}' is a chord symbol, not words: add it with set-chords, "
            f"which places it at an offset inside the bar like the rest of the "
            f"chart ({{\"measure\": {measure}, \"symbol\": \"{str(value).strip()}\", "
            f"\"offset\": {float(offset)}}}). A text mark is engraved in "
            f"italics, under the chart.")

    part = find_parts(score, [name])[0]
    measures = {m.number: m for m in part.getElementsByClass(stream.Measure)}
    destination = measures.get(measure)
    if destination is None:
        raise ValueError(
            f"'{part_label(part)}' has no measure {measure} "
            f"(it has {min(measures) if measures else 0}-"
            f"{max(measures) if measures else 0})")

    bar = float(destination.barDuration.quarterLength)
    where = float(offset)
    if not 0.0 <= where < bar:
        raise ValueError(
            f"offset {where} is not inside measure {measure}, which is "
            f"{bar} quarter notes long")

    element = _make_element(kind, value, placement)

    if spec.anchor == "offset":
        destination.insert(where, element)
    else:
        target = _note_starting_at(destination, where)
        if target is None:
            raise ValueError(
                f"No note starts at offset {where} of measure {measure} in "
                f"'{part_label(part)}'. {spec.noun.capitalize()}s hang off a "
                f"note, so that is what the destination has to be; that bar "
                f"starts notes at {_onsets(destination)}")
        if kind == "lyric":
            # A note carries one syllable per verse, so the new word takes the
            # lowest verse nothing is using -- verse 1 on a note with no words
            # under it, verse 2 on a note that already sings one.
            element.number = _free_verse(target)
        _attached_list(target, kind).append(element)

    landed = [e for _holder, e in _elements_in_measure(destination, kind)]
    ordinal = next((i for i, e in enumerate(landed) if e is element), None)
    return {"part": part_label(part), "kind": kind, "op": "add",
            "anchor": spec.anchor,
            "value": value, "placement": placement,
            "at": {"measure": measure, "offset": where},
            "ordinal": ordinal,
            "in_measure": len(landed)}


def move_element(score, name: str, kind: str, measure: int, ordinal: int = 0,
                 to_measure: int | None = None, to_offset: float = 0.0,
                 duplicate: bool = False) -> dict:
    """Move an added element to another bar, or leave a copy of it there.

    THE DESTINATION IS A BAR PLUS AN OFFSET INSIDE IT, because this app has no
    drag: the reader taps the bar and steps the offset. The offset is in
    quarter notes from the barline, so 0 is the downbeat and 1.5 is the second
    half of beat two in 4/4.

    The two element classes are moved by different mechanics, which is why
    `ElementKind.anchor` exists:

      offset-anchored (chord symbols, dynamics, text, chord diagrams) are
        copied into the destination measure at the destination offset. Nothing
        about the music changes -- the element has an offset of its own and it
        is the only thing that moves.
      note-attached (fermatas, articulations) have no offset of their own.
        They are detached from the source note and attached to the note that
        STARTS at the destination offset. There has to be such a note; landing
        one on a bar position that nothing begins at would be inventing a
        placement MusicXML cannot express, so it is refused and the onsets
        that do exist are listed.

    SPANNERS are refused by name -- see SPANNER_KINDS for why there is no
    honest answer.

    A move never edits pitch, rhythm or any note: only where a mark sits.
    """
    verb = "duplicate" if duplicate else "move"
    spec = _element_kind(kind, verb, MOVABLE_KINDS)

    part = find_parts(score, [name])[0]
    measures = {m.number: m for m in part.getElementsByClass(stream.Measure)}

    source = measures.get(measure)
    found = _elements_in_measure(source, kind) if source is not None else []
    if not 0 <= ordinal < len(found):
        raise ValueError(
            f"No {spec.noun} #{ordinal} in measure {measure} of "
            f"'{part_label(part)}' (it has {len(found)})")
    holder, element = found[ordinal]

    destination_number = measure if to_measure is None else int(to_measure)
    destination = measures.get(destination_number)
    if destination is None:
        raise ValueError(
            f"'{part_label(part)}' has no measure {destination_number} "
            f"(it has {min(measures) if measures else 0}-"
            f"{max(measures) if measures else 0})")

    bar = float(destination.barDuration.quarterLength)
    offset = float(to_offset)
    if not 0.0 <= offset < bar:
        raise ValueError(
            f"offset {offset} is not inside measure {destination_number}, "
            f"which is {bar} quarter notes long")

    if spec.anchor == "offset":
        landed = copy.deepcopy(element)
        destination.insert(offset, landed)
        if not duplicate:
            holder.remove(element)
    else:
        target = _note_starting_at(destination, offset)
        if target is None:
            raise ValueError(
                f"No note starts at offset {offset} of measure "
                f"{destination_number} in '{part_label(part)}'. "
                f"{spec.noun.capitalize()}s hang off a note, so the "
                f"destination has to be one; that bar starts notes at "
                f"{_onsets(destination)}")
        landed = copy.deepcopy(element)
        if kind == "lyric":
            # One syllable per verse per note. Landing a word on a note that
            # already sings that verse would draw two words on top of each
            # other; landing it in the next free verse instead would silently
            # start a second line of text under the staff. Neither is what
            # anybody asked for, so the word goes where it was asked to go if
            # the verse is free and the op says so plainly if it is not.
            taken = {int(ly.number) for ly in word_verses(target)
                     if ly.number and ly is not element}
            wanted = int(landed.number or 1)
            if wanted in taken:
                sung = next(ly.text for ly in word_verses(target)
                            if ly.number and int(ly.number) == wanted)
                raise ValueError(
                    f"The note at offset {offset} of measure "
                    f"{destination_number} already sings '{sung}' in verse "
                    f"{wanted}. Move that one first, or pick another note.")
        _attached_list(target, kind).append(landed)
        if not duplicate:
            source_list = _attached_list(holder, kind)
            # by identity: two fermatas on one note compare equal, and
            # list.remove would drop whichever came first
            source_list[:] = [e for e in source_list if e is not element]

    return {"part": part_label(part), "kind": kind, "op": verb,
            "anchor": spec.anchor,
            "from": {"measure": measure, "ordinal": ordinal},
            "to": {"measure": destination_number, "offset": offset}}


def remove_element(score, name: str, kind: str, measure: int | None = None,
                   ordinal: int = 0, all_elements: bool = False) -> dict:
    """Take an added mark off the page.

    The verb the family was missing. `add_element` could put a mark on,
    `move_element` could move it and `adjust_element` could resize it, and
    nothing could take one off -- so "take the ornament off bar 12" had no op
    behind it and the only way back from an added mark was to undo to the
    version before it, losing everything done since.

    Addressed exactly as every other verb in the family addresses one: a
    measure plus an ordinal in that bar's document order, or `all_elements`
    for every one of that kind in the part. The two anchors are removed by
    the two mechanics `move_element` already uses -- an offset-anchored mark
    comes out of the stream it sits in, a note-attached one out of the list on
    its note, BY IDENTITY, because two fermatas on one note compare equal and
    `list.remove` would drop whichever came first.

    A TAB COLUMN IS REFUSED BY NAME. Its anchor is "lyric": the element IS
    the note, and its six verses are what `guitar-tab --clear` exists to take
    off. Removing it here would mean removing the note, which is not what
    anybody asking to remove a tab column means.

    A WORD IS REMOVED, AND HAS NO BRANCH OF ITS OWN ON PURPOSE. `lyric` is
    anchored "note", so it comes out through the same two lines every
    note-attached kind comes out through: `_attached_list` hands back
    `note.lyrics` and the verse is dropped from it by identity. That is the
    whole meaning of removing a word, so a branch here would only be a second
    spelling of it. Two things make the generic path correct rather than
    merely quiet, and both are asserted in `check_adjust.py`:
      - `_elements_in_measure` finds words through `word_verses`, which
        excludes a whistle's fingerings and a tab's frets. `--all` on a part
        that also carries fingerings takes the SUNG words and leaves the
        fingerings, and an empty bar refuses with a count rather than
        reporting a removal it did not make.
      - THE REMAINING VERSES ARE NOT RENUMBERED. Take verse 1 off a note
        singing two and verse 2 stays verse 2, sitting on the second line of
        text. Closing the gap would pull this note's word up into the first
        line while every other note in the phrase kept theirs there -- one
        word out of step with its own line, which is worse than a hole.
    """
    spec = _element_kind(kind, "remove", ADJUSTABLE_KINDS)
    if spec.anchor == "lyric":
        raise ValueError(
            f"A {spec.noun} is not a mark ON a note, it IS the note -- its "
            f"verses are taken off with `guitar-tab --clear`, which is what "
            f"removing one means. This op removes marks; it will not remove "
            f"music.")

    part = find_parts(score, [name])[0]
    measures = {m.number: m for m in part.getElementsByClass(stream.Measure)}

    if all_elements:
        found = [(m.number, holder, element) for m in measures.values()
                 for holder, element in _elements_in_measure(m, kind)]
        if not found:
            raise ValueError(f"No {spec.noun}s in part '{part_label(part)}'")
    else:
        if measure is None:
            raise ValueError(
                "Which one? Pass a measure, or --all for the whole part")
        m = measures.get(measure)
        in_bar = _elements_in_measure(m, kind) if m is not None else []
        if not 0 <= ordinal < len(in_bar):
            raise ValueError(
                f"No {spec.noun} #{ordinal} in measure {measure} of "
                f"'{part_label(part)}' (it has {len(in_bar)})")
        found = [(measure, *in_bar[ordinal])]

    removed = []
    for number, holder, element in found:
        if spec.anchor == "offset":
            holder.remove(element)
        else:
            attached = _attached_list(holder, kind)
            # by identity: two identical marks on one note compare equal
            attached[:] = [e for e in attached if e is not element]
        removed.append(number)

    return {"part": part_label(part), "kind": kind, "op": "remove",
            "anchor": spec.anchor, "removed": len(removed),
            "measures": sorted(set(removed))}


def duplicate_element(score, name: str, kind: str, measure: int,
                      ordinal: int = 0, to_measure: int | None = None,
                      to_offset: float = 0.0) -> dict:
    """Leave a copy of an added element in another bar, keeping the original.

    The same addressing and the same destination as `move_element`, which does
    the work: a duplicate that placed things by different rules from a move
    would be two features to learn instead of one.
    """
    return move_element(score, name, kind, measure, ordinal=ordinal,
                        to_measure=to_measure, to_offset=to_offset,
                        duplicate=True)


def _sounding_notes(measure) -> list:
    """The notes in a measure, chord symbols excluded, voices included."""
    from music21 import harmony as m21harmony

    return [n for n in measure.recurse().notes
            if not isinstance(n, m21harmony.Harmony)]


def _note_starting_at(measure, offset: float):
    """The first note beginning exactly at `offset` in a measure, or None."""
    wanted = round(float(offset), 6)
    for n in _sounding_notes(measure):
        if round(float(n.getOffsetInHierarchy(measure)), 6) == wanted:
            return n
    return None


def _onsets(measure) -> list[float]:
    """Every offset a note begins at in a measure, for an error to name."""
    return sorted({round(float(n.getOffsetInHierarchy(measure)), 6)
                   for n in _sounding_notes(measure)})


_CHORD_TEXT_RE = re.compile(r"([A-G])(b|#)?(.*)")


def is_chord_symbol_text(value) -> bool:
    """Is this text a chord name set-chords would write -- "Em", "F#m7", "Bb"?"""
    match = _CHORD_TEXT_RE.fullmatch(str(value or "").strip())
    return bool(match) and match.group(3) in QUALITY_KINDS


def set_chord_symbols(score, name: str, chords: list[dict]) -> dict:
    """Write chord symbols (MusicXML <harmony>) onto a part at given measures.

    chords: [{"measure": 1, "symbol": "Fm", "offset": 0.0}, ...]
    Symbols use lead-sheet spelling: F, Fm, F7, Fmaj7, Fm7, Fm7b5, Fdim, Fdim7, Faug
    (roots may carry b/#). Replaces any existing symbol at the same spot.
    """
    import re as _re

    from music21 import harmony as m21harmony
    part = find_parts(score, [name])[0]
    measures = {m.number: m for m in part.getElementsByClass(stream.Measure)}
    added = 0
    for spec in chords:
        mnum, sym = spec["measure"], spec["symbol"].strip()
        m = measures.get(mnum)
        if m is None:
            raise ValueError(f"No measure {mnum} in part '{part_label(part)}'")
        match = _re.fullmatch(r"([A-G])(b|#)?(.*)", sym)
        if not match or match.group(3) not in QUALITY_KINDS:
            raise ValueError(f"Bad chord symbol '{sym}'. Qualities: {sorted(QUALITY_KINDS)}")
        root = match.group(1) + {"b": "-", "#": "#", None: ""}[match.group(2)]
        cs = m21harmony.ChordSymbol(root=root, kind=QUALITY_KINDS[match.group(3)])
        off = float(spec.get("offset", 0.0))
        for old in list(m.getElementsByClass(m21harmony.ChordSymbol)):
            if abs(old.offset - off) < 1e-3:
                m.remove(old)
        m.insert(off, cs)
        added += 1
    return {"part": part_label(part), "symbols_added": added}


# ---------------------------------------------------------------- metadata
#
# There are two title fields in a music21 score and MusicXML carries both:
# <work-title> (md.title) and <movement-title> (md.movementName). Verovio
# engraves the *movement* title when it is present, so that -- not md.title --
# is what a reader sees at the top of the page. Worse, music21 seeds
# movementName with the source file's name, extension included, whenever the
# file itself carries no title: that is why an imported score engraved
# "sous-le-ciel-quartet.mxl". These helpers keep the two fields to one value.


def engraved_title(score) -> str | None:
    """The title that actually prints at the top of the page."""
    md = getattr(score, "metadata", None)
    if md is None:
        return None
    return md.movementName or md.title


def _contributor(score, role: str) -> str | None:
    md = getattr(score, "metadata", None)
    if md is None:
        return None
    names = [str(c) for c in md.getContributorsByRole(role)]
    # music21 stamps itself as the composer on every write when none is set
    names = [n for n in names if n and n != "Music21"]
    return names[0] if names else None


def score_metadata(score) -> dict:
    """Every editable metadata field, as it stands in the notation."""
    return {
        "title": engraved_title(score),
        "composer": _contributor(score, "composer"),
        "arranger": _contributor(score, "arranger"),
    }


def set_metadata(score, title: str | None = None, composer: str | None = None,
                 arranger: str | None = None) -> dict:
    """Write the score's own metadata. Only the fields passed are touched.

    An empty string clears a field; None leaves it alone. The title is written
    to both MusicXML title fields so there is exactly one title to see and
    exactly one to edit.
    """
    from music21 import metadata as m21metadata

    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    md = score.metadata
    if title is not None:
        title = title.strip()
        if not title:
            raise ValueError("A title is required")
        md.title = title
        md.movementName = title
    # the property setters replace the existing contributor, and None removes it
    for role, value in (("composer", composer), ("arranger", arranger)):
        if value is None:
            continue
        setattr(md, role, value.strip() or None)
    return score_metadata(score)


def clean_imported_metadata(score, fallback_title: str,
                            source_stem: str | None = None) -> dict:
    """Give a freshly imported score one sane title.

    Drops music21's filename-derived movement title (it is a file name, not a
    title, and it is what would engrave) and falls back to the name the score
    was imported under.
    """
    from music21 import metadata as m21metadata

    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    md = score.metadata
    candidates = [md.title, md.movementName]
    title = next((c for c in candidates
                  if c and not _is_junk_title(c, source_stem)), None)
    # The fallback is the name the caller imported under, and that can be a
    # file stem too -- a score dropped in as "sous-le-ciel-quartet.musicxml"
    # has nothing else to offer. Rather than engrave a slug, spell it: the same
    # words, spaced and sentence-cased. Nothing is invented.
    return set_metadata(score, title=title or humanise_title(fallback_title))


def is_internal_artifact_name(name: str | None) -> bool:
    """Is this the workspace's own file name for a version, rather than a name?

    Versions are stored as `vNNN.<ext>` -- v001.mxl, v002.musicxml -- and that
    string is never anybody's music. It is distinct from a file stem that still
    carries the title ("under-paris-skies"), which is worth tidying rather than
    discarding.

    Public because the repair reads it too: `title_repair` has to recognise a
    title poisoned before the guard existed, and the app mirrors this judgement
    in ScoreTitle.isInternalArtifactName so a poisoned title is never SHOWN
    either.
    """
    if not name:
        return False
    stem = str(name).strip()
    stem = stem.rsplit(".", 1)[0] if "." in stem else stem
    return bool(re.fullmatch(r"[vV]\d{2,}", stem))


#: The name kept for the callers written before it was public.
_is_internal_artifact_name = is_internal_artifact_name


def title_repair(stored: str | None, name: str | None,
                 piece: str | None = None) -> str | None:
    """The title an ALREADY STORED arrangement should carry, or None if it is fine.

    `title_for_added_version` guards the way in, and it only ever protected
    versions written after it existed. A library OMR'd before that carries the
    damage baked into the notation of versions already on disk, and nothing
    re-runs the title logic over a file that has been written -- so the reader
    still sees "v001.mxl" engraved at the top of music he imported months ago.

    This is the other half: given what a score document holds now, what is the
    title worth writing in a NEW version. Nothing is invented -- the
    replacement is the arrangement's own name, or failing that the piece's,
    spelled out the way an import spells a file stem. When neither can say
    anything, this returns None and the arrangement is reported rather than
    given a title someone would have to undo.
    """
    if stored and not _is_junk_title(stored) and not is_internal_artifact_name(stored):
        return None
    for candidate in (name, piece):
        if not candidate or is_internal_artifact_name(candidate):
            continue
        spelled = humanise_title(candidate)
        if spelled and not is_internal_artifact_name(spelled):
            return None if spelled == (stored or "").strip() else spelled
    return None


def title_for_sharing(stored: str | None, name: str | None,
                      piece: str | None, slug: str | None) -> str | None:
    """The name a SHARED SETLIST ENTRY carries for an arrangement.

    The ladder `title_repair` walks -- the stored title, then the
    arrangement's own name, then its piece's -- with one rung added and a
    different ending, both because of what a share IS.

    THE EXTRA RUNG IS THE SLUG. `title_repair` stops before it and reports,
    and is right to: it writes a NEW VERSION, so a guessed title gets engraved
    at the top of the page and somebody has to undo it. A share names a row in
    someone else's set list. The slug was derived from a real name once, so
    spelling it out is the worst HONEST answer available, and it is a great
    deal better than the alternative that shipped -- `share_payload` returned
    `title or name`, both were empty for one arrangement, and the app turned
    the resulting null into the literal string "Untitled" and uploaded it.
    Echo opened Ali's set list and found a piece called Untitled where
    Morrison's Jig should have been.

    Returns None only when NOTHING here can name the arrangement, and then the
    share refuses rather than inventing -- which is the same answer
    `title_repair` gives, for the same reason.
    """
    for candidate in (stored, name, piece, slug):
        if not candidate or is_internal_artifact_name(candidate):
            continue
        spelled = humanise_title(candidate)
        if not spelled or is_internal_artifact_name(spelled):
            continue
        # "Untitled" and "Music21 Fragment" are placeholders, not names, and a
        # slug survives humanising as words -- so this rejects the first and
        # keeps the second.
        if _is_junk_title(spelled):
            continue
        return spelled
    return None


def title_for_added_version(existing: str | None, incoming: str | None,
                            source_stem: str | None = None) -> str | None:
    """Which title a version built FROM A FILE should carry.

    Adding a version is not a rename. The arrangement already has a title --
    the one the reader imported the PDF under -- and OMR handing back a file
    called v001.mxl must not become the name of their music. It did: music21
    seeds the movement title from the source file name, `_write_version`
    projects the notation's metadata onto the score document, and Verovio
    engraves the movement title. So "v001.mxl" appeared in the library and at
    the top of the page.

    The arrangement's own title wins. The incoming file's title is used only
    when the arrangement has none worth keeping -- and a file name is never
    a title in either position.
    """
    if existing and not _is_junk_title(existing):
        return existing
    if incoming and not _is_junk_title(incoming, source_stem):
        return incoming
    # Both were rejected, and a rejected name does not improve by being
    # tidied: humanising `existing` here turned the v001.mxl this function
    # exists to stop into "V001" and engraved that instead. A file name that
    # has been de-hyphenated is still a file name.
    #
    # So nothing is returned, and the caller clears the title. An empty title
    # engraves nothing, which is honest; the library still shows the
    # arrangement's own name beside it.
    # A file stem still carrying the music's name -- "under-paris-skies" --
    # improves by being tidied, and that is worth doing. An INTERNAL ARTIFACT
    # name does not: "v001.mxl" is the workspace's own filename for a version
    # and means nothing to a reader. Humanising it here is what engraved
    # "V001" on the page after the first attempt at this fix, which is the very
    # bug the function exists to stop, wearing different capitals.
    if _is_internal_artifact_name(existing):
        return None
    return humanise_title(existing or "") or None


def carry_title_into_version(score, existing: str | None,
                             source_stem: str | None = None) -> dict:
    """Put `title_for_added_version` into the notation, which is what engraves."""
    from music21 import metadata as m21metadata

    incoming = engraved_title(score)
    title = title_for_added_version(existing, incoming, source_stem)
    if title:
        return set_metadata(score, title=title)
    # Nothing anywhere is usable. Leave no file name behind: an empty title
    # engraves nothing, and a file name engraves a file name.
    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    score.metadata.title = None
    score.metadata.movementName = None
    return score_metadata(score)


def humanise_title(text: str) -> str:
    """A slug spelled out. "sous-le-ciel-quartet" -> "Sous le ciel quartet"."""
    value = (text or "").strip()
    if not value or not _is_junk_title(value):
        return value
    value = re.sub(r"\.(musicxml|xml|mxl|mid|midi|pdf)$", "", value, flags=re.I)
    spaced = re.sub(r"[-_]+", " ", value).strip()
    spaced = re.sub(r"\s+", " ", spaced)
    if not spaced:
        return value
    return spaced[0].upper() + spaced[1:]


# Titles that are not titles: what music21 leaves behind when a file carries
# none of its own. Whatever is here ENGRAVES at the top of the page, which is
# how Ali got a file name as the name of his music.
_PLACEHOLDER_TITLES = {"music21 fragment", "untitled", "untitled score",
                       "score", "no title"}


def _is_junk_title(text: str, source_stem: str | None = None) -> bool:
    """Is this a file name or a placeholder wearing a title's clothes?

    Four ways, because catching only the first let a slug engrave at the top of
    Ali's score -- "sous-le-ciel-quartet" reached the page and the top bar, and
    the app showed it twice:

      - it carries an extension: "my-score.mxl"
      - it IS the file it came from, stem for stem
      - it is slug-shaped: no spaces, and words joined by - or _
      - it is a placeholder music21 wrote itself: "Music21 Fragment"

    A one-word title is NOT slug-shaped. "Nocturne" is a title; a real title
    with a hyphen ("Jean-Pierre Rampal suite") has spaces around the rest of it.
    """
    value = text.strip()
    if not value:
        return False
    if value.casefold() in _PLACEHOLDER_TITLES:
        return True
    if re.search(r"\.(musicxml|xml|mxl|mid|midi|pdf)$", value, re.I):
        return True
    if source_stem and value.casefold() == source_stem.strip().casefold():
        return True
    return not re.search(r"\s", value) and bool(re.search(r"[-_]", value))



# ------------------------------------------------------- structural markings
#
# Repeats and the navigation marks that go with them. Chat could not touch any
# of this before: the agent may only change notation through an op, and there
# was no op, so every phrasing of "put a repeat on bar 16" failed.
#
# Every kind below was checked against Verovio before it was offered — a mark
# the engine writes but nothing engraves is worse than saying no.

# kind -> the music21 class that expresses it
NAVIGATION_MARKS = {
    "segno": "Segno",
    "coda": "Coda",
    "fine": "Fine",
    "da-capo": "DaCapo",
    "da-capo-al-fine": "DaCapoAlFine",
    "da-capo-al-coda": "DaCapoAlCoda",
    "dal-segno": "DalSegno",
    "dal-segno-al-fine": "DalSegnoAlFine",
    "dal-segno-al-coda": "DalSegnoAlCoda",
}
REPEAT_BARLINES = {"repeat-start", "repeat-end", "repeat-both"}
STRUCTURE_KINDS = sorted(set(NAVIGATION_MARKS) | REPEAT_BARLINES | {"volta"})


def _measure_or_raise(part, number: int):
    measure = part.measure(number)
    if measure is None:
        numbers = [m.number for m in part.getElementsByClass(stream.Measure)]
        raise ValueError(f"No measure {number}. This part has "
                         f"{numbers[0] if numbers else '?'}–{numbers[-1] if numbers else '?'}.")
    return measure


def rehearsal_letter(index: int) -> str:
    """0 -> A, 25 -> Z, 26 -> AA, 27 -> BB.

    Doubling the letter rather than counting in base 26 (which would give AA,
    AB, AC): a rehearsal letter is called out loud across a room -- "from
    double-B" -- and AB and BB are the same two syllables in a noisy hall.
    """
    if index < 0:
        raise ValueError("a rehearsal letter has no index below zero")
    letter = chr(ord("A") + index % 26)
    return letter * (index // 26 + 1)


def _rehearsal_marks(part) -> list:
    """(measure, mark) for every rehearsal mark in a part, in bar order."""
    from music21 import expressions
    out = []
    for measure in part.getElementsByClass(stream.Measure):
        for mark in measure.getElementsByClass(expressions.RehearsalMark):
            out.append((measure, mark))
    return out


def set_rehearsal(score, measure: int | None = None, mark: str | None = None,
                  remove: bool = False, move_to: int | None = None,
                  reletter: bool = False) -> dict:
    """Add, remove, move or re-letter rehearsal marks.

    On EVERY part, which is the decision worth stating. This app's workflow is
    parts-first: a player reads an extracted part, and a mark written only to
    the top staff of the full score is absent from every part but the first --
    missing from precisely the page it is needed on. The cost is that Verovio
    renders a direction from each part and anchors them all to staff 1 of a
    COMBINED score, where they would stack on each other; the render dedupes
    them there (`render.mei_with_deduped_rehearsals`) so the mark is drawn
    once. Writing to the top staff alone would have been simpler and would
    have lost the marks from the parts.

    With no `mark`, the next free letter is used: A-Z then AA, BB, CC.
    `reletter` re-labels every existing mark in bar order, which is what you
    want after inserting one in the middle.

    How big the mark is and where it sits are `adjust-element`'s business, the
    same as any other added element.
    """
    from music21 import expressions

    parts = list(score.parts) or [score]

    if reletter:
        # bar order across the score, not per part: every part must agree
        bars = sorted({m.number for p in parts for m, _ in _rehearsal_marks(p)})
        for index, number in enumerate(bars):
            letter = rehearsal_letter(index)
            for part in parts:
                for m, existing in _rehearsal_marks(part):
                    if m.number == number:
                        existing.content = letter
        return {"relettered": [rehearsal_letter(i) for i in range(len(bars))],
                "measures": bars, "marks": len(bars)}

    if move_to is not None:
        # remove-then-add, so it cannot half-happen (set_structure's shape)
        moving = None
        for m, existing in _rehearsal_marks(parts[0]):
            if m.number == measure:
                moving = str(existing.content)
        set_rehearsal(score, measure=measure, remove=True)
        return set_rehearsal(score, measure=move_to, mark=mark or moving)

    if measure is None:
        raise ValueError("say which measure the rehearsal mark is in")

    if remove:
        taken = 0
        for part in parts:
            for m, existing in _rehearsal_marks(part):
                if m.number == measure:
                    m.remove(existing)
                    taken += 1
        if taken == 0:
            raise ValueError(f"no rehearsal mark in measure {measure}")
        return {"removed": measure, "parts": taken}

    if mark is None:
        used = {str(existing.content) for p in parts for _, existing in _rehearsal_marks(p)}
        index = 0
        while rehearsal_letter(index) in used:
            index += 1
        mark = rehearsal_letter(index)

    placed = 0
    for part in parts:
        target = _measure_or_raise(part, measure)
        for m, existing in _rehearsal_marks(part):
            if m.number == measure:
                m.remove(existing)          # one mark per bar, not a stack
        target.insert(0.0, expressions.RehearsalMark(mark))
        placed += 1
    return {"mark": mark, "measure": measure, "parts": placed}


def set_structure(score, kind: str, measure: int | None = None,
                  to_measure: int | None = None, number: int | None = None,
                  times: int | None = None, remove: bool = False,
                  move_to: int | None = None) -> dict:
    """Add, remove or move a repeat, a volta, or a navigation mark.

    One op rather than a dozen: the chat tool list is sent with every request,
    so each extra tool costs on every turn. `kind` says which mark.

    Repeat barlines go on EVERY part, because a repeat is a property of the
    system and a barline drawn on one staff of a piano score is just wrong.
    Voltas go on the top part and on every staff joined to it (see
    `_joined_staves`); navigation marks go on the top part, where they are
    read from.
    """
    from music21 import bar as m21bar
    from music21 import repeat as m21repeat
    from music21 import spanner as m21spanner

    if kind not in STRUCTURE_KINDS:
        raise ValueError(f"Unknown structural mark '{kind}'. "
                         f"Have: {', '.join(STRUCTURE_KINDS)}")
    parts = list(score.parts) or [score]
    top = parts[0]

    # a move is a remove followed by an add, so it cannot half-happen
    if move_to is not None:
        set_structure(score, kind, measure=measure, to_measure=to_measure,
                      number=number, remove=True)
        span = None if to_measure is None or measure is None else to_measure - measure
        return set_structure(score, kind, measure=move_to, number=number, times=times,
                             to_measure=None if span is None else move_to + span)

    if kind == "volta":
        return _volta(_joined_staves(score, parts), measure, to_measure, number, remove)
    if kind in REPEAT_BARLINES:
        return _repeat_barline(parts, kind, measure, times, remove)
    return _navigation_mark(top, kind, measure, remove)


def _repeat_barline(parts, kind: str, measure: int | None,
                    times: int | None, remove: bool) -> dict:
    from music21 import bar as m21bar

    if measure is None:
        raise ValueError("Which measure? A repeat barline needs one.")
    touched = []
    for part in parts:
        m = _measure_or_raise(part, measure)
        if remove:
            for side in ("leftBarline", "rightBarline"):
                existing = getattr(m, side, None)
                if isinstance(existing, m21bar.Repeat):
                    setattr(m, side, None)
        else:
            if kind in ("repeat-start", "repeat-both"):
                m.leftBarline = m21bar.Repeat(direction="start")
            if kind in ("repeat-end", "repeat-both"):
                end = m21bar.Repeat(direction="end")
                if times and times > 1:
                    end.times = times
                m.rightBarline = end
        touched.append(part_label(part))
    return {"kind": kind, "measure": measure, "removed": remove,
            "times": times, "parts": touched}


def _joined_staves(score, parts: list) -> list:
    """The top part, plus the staves MusicXML export merges into it.

    A grand staff (accordion, piano) parses as two `PartStaff`s in a
    `StaffGroup`, and music21 writes them out as ONE `<part>` with two staves.
    In that merge, a barline from the second staff replaces the first staff's
    barline at the same position — and a volta lives inside a barline as
    `<ending>`, so a bracket written to the top staff alone silently vanished
    from the exported file. Writing it to every joined staff survives the
    merge and still produces exactly one `<ending>` per barline.

    A score of separate instruments has no such group; there the volta stays
    on the top part, as it is engraved.
    """
    from music21 import layout as m21layout

    top = parts[0]
    for group in score.recurse().getElementsByClass(m21layout.StaffGroup):
        members = [p for p in parts if p in group.getSpannedElements()]
        if top in members and len(members) > 1:
            return members
    return [top]


def _volta(parts: list, measure: int | None, to_measure: int | None,
           number: int | None, remove: bool) -> dict:
    from music21 import spanner as m21spanner

    if measure is None:
        raise ValueError("Which measures? A volta covers a range.")
    last = to_measure or measure

    dropped = 0
    for part in parts:
        covered = [_measure_or_raise(part, n) for n in range(measure, last + 1)]
        numbers = {m.number for m in covered}
        if remove:
            for bracket in list(part.getElementsByClass(m21spanner.RepeatBracket)):
                spanned = {m.number for m in bracket.getSpannedElements()}
                if spanned & numbers:
                    part.remove(bracket)
                    dropped += 1
        else:
            part.insert(0, m21spanner.RepeatBracket(covered, number=number or 1))

    if remove:
        return {"kind": "volta", "measures": [measure, last], "removed": True,
                "brackets_removed": dropped}
    return {"kind": "volta", "measures": [measure, last],
            "number": number or 1, "removed": False,
            "staves": len(parts)}


def _navigation_mark(part, kind: str, measure: int | None, remove: bool) -> dict:
    from music21 import repeat as m21repeat

    cls = getattr(m21repeat, NAVIGATION_MARKS[kind])
    if remove:
        dropped = 0
        scope = ([_measure_or_raise(part, measure)] if measure is not None
                 else list(part.getElementsByClass(stream.Measure)))
        for m in scope:
            for existing in list(m.getElementsByClass(cls)):
                m.remove(existing)
                dropped += 1
        return {"kind": kind, "measure": measure, "removed": True, "count": dropped}

    if measure is None:
        raise ValueError(f"Which measure should the {kind} go on?")
    m = _measure_or_raise(part, measure)
    # at the start of the bar for a segno or coda sign, at the end for the
    # instructions that send the player somewhere else
    offset = 0.0 if kind in ("segno", "coda") else max(0.0, m.duration.quarterLength - 0.01)
    m.insert(offset, cls())
    return {"kind": kind, "measure": measure, "removed": False,
            "part": part_label(part)}


def info(score) -> dict:
    parts = []
    for i, p in enumerate(score.parts):
        instr = p.getInstrument(returnDefault=False)
        pitches = [pp for n in p.recurse().notes if "Harmony" not in n.classes for pp in n.pitches]
        clefs = []
        for c in p.recurse().getElementsByClass(m21clef.Clef):
            label = type(c).__name__.replace("Clef", "").lower()
            if label not in clefs:
                clefs.append(label)
        parts.append({
            "index": i,
            "name": part_label(p),
            "abbreviation": p.partAbbreviation,
            "instrument": instr.instrumentName if instr else None,
            "clefs": clefs,
            "range": [min(pitches).nameWithOctave, max(pitches).nameWithOctave] if pitches else None,
            "measures": len(p.getElementsByClass(stream.Measure)),
            "notes": len(pitches),
        })
    first = score.parts.first()
    time_sigs = [ts.ratioString for ts in first.recurse().getElementsByClass("TimeSignature")] if first else []
    key_sigs = [str(ks) for ks in first.recurse().getElementsByClass("KeySignature")] if first else []
    meta = score_metadata(score)
    return {
        # the title as engraved, so `info` and the page agree
        "title": meta["title"],
        "composer": meta["composer"],
        "arranger": meta["arranger"],
        "parts": parts,
        "time_signatures": list(dict.fromkeys(time_sigs)),
        "key_signatures": list(dict.fromkeys(key_sigs)),
    }


# --------------------------------------------------------------- selections
#
# An element address is what the iPad's lasso produces:
#
#     s1/m15/l1/note#3   staff 1, measure 15, layer 1, the 4th note
#
# The numbers come from the MEI Verovio engraves, so resolving one against
# music21 is a JOIN between two models of the same document, and a join that is
# subtly wrong edits the wrong note -- which is worse than the bug it fixes
# (an op that hits the whole bar is at least visible). So the mapping is stated
# here and PROVEN in engine/scripts/check_addresses.py, which engraves fixtures
# with Verovio, reads the addresses out of the MEI exactly as the app's parser
# does, resolves each one here, and asserts the pitches agree.
#
# The mapping, and the two places it is not the obvious one:
#
#   staff N   -> score.parts[N-1], parts in score order (a PartStaff is its own
#                part in music21 and its own staff in MEI, so grand staves line
#                up without special-casing)
#   measure M -> the measure whose NUMBER is M, not the Mth measure: pickups and
#                OMR output both number measures in ways that are not positions
#   layer L   -> the voice with id str(L); a measure with no voices at all is
#                layer 1, which is what Verovio writes for it
#   note#K    -> the K-th <note> IN DOCUMENT ORDER, counting notes inside
#                chords individually. music21 holds a chord as ONE element with
#                several pitches, so resolving by stream position skips notes
#                and lands on the wrong pitch from the first chord onwards.

_ADDRESS_RE = re.compile(
    r"^s(?P<staff>\d+)/m(?P<measure>-?\d+)/l(?P<layer>\d+)/(?P<kind>[a-zA-Z]+)#(?P<ordinal>\d+)$")


class AddressError(ValueError):
    """An address that does not parse, or names something not in this score."""


def parse_address(text: str) -> dict:
    m = _ADDRESS_RE.match(str(text).strip())
    if not m:
        raise AddressError(
            f"not an element address: {text!r} (expected e.g. 's1/m15/l1/note#3')")
    return {"staff": int(m["staff"]), "measure": int(m["measure"]),
            "layer": int(m["layer"]), "kind": m["kind"].lower(),
            "ordinal": int(m["ordinal"])}


def _layer_stream(measure, layer: int):
    """The voice an address names, or the measure itself when it has none."""
    voices = list(measure.voices)
    if not voices:
        return measure
    for v in voices:
        if str(v.id) == str(layer):
            return v
    # Verovio numbers layers 1..n in order; a voice whose id is not a plain
    # number (music21 accepts any hashable) still has a position.
    if 1 <= layer <= len(voices):
        return voices[layer - 1]
    raise AddressError(f"measure {measure.number} has no layer {layer}")


def _notes_in_document_order(container) -> list:
    """Every sounding note, chords flattened into their own notes.

    Returns (owner, pitch_index) pairs: `owner` is the music21 object to edit
    and `pitch_index` says which of its pitches this address names -- None for a
    plain Note, an index into `.pitches` for one note of a chord. Editing has to
    go through the owner, because a chord's pitch is not an independent object
    in the stream.
    """
    out = []
    for el in container.getElementsByClass([m21note.Note, m21chord.Chord,
                                            m21note.Rest]):
        if isinstance(el, m21chord.Chord):
            for i in range(len(el.pitches)):
                out.append((el, i))
        else:
            out.append((el, None))
    return out


def resolve_address(score, address: str | dict) -> tuple:
    """One address -> (owner, pitch_index, kind). Raises AddressError."""
    a = parse_address(address) if isinstance(address, str) else dict(address)
    parts = list(score.parts)
    if not 1 <= a["staff"] <= len(parts):
        raise AddressError(
            f"staff {a['staff']} does not exist (the score has {len(parts)})")
    part = parts[a["staff"] - 1]
    measure = None
    for m in part.getElementsByClass(stream.Measure):
        if m.number == a["measure"]:
            measure = m
            break
    if measure is None:
        raise AddressError(f"staff {a['staff']} has no measure {a['measure']}")
    container = _layer_stream(measure, a["layer"])

    kind = a["kind"]
    if kind in ("note", "chord", "rest"):
        entries = _notes_in_document_order(container)
        if kind == "rest":
            entries = [(o, i) for o, i in entries if isinstance(o, m21note.Rest)]
        elif kind == "chord":
            # a chord address names the chord itself, once, not its notes
            seen, chords = set(), []
            for o, _ in entries:
                if isinstance(o, m21chord.Chord) and id(o) not in seen:
                    seen.add(id(o))
                    chords.append((o, None))
            entries = chords
        else:
            entries = [(o, i) for o, i in entries if not isinstance(o, m21note.Rest)]
        if not 0 <= a["ordinal"] < len(entries):
            raise AddressError(
                f"{kind}#{a['ordinal']} is not in s{a['staff']}/m{a['measure']}"
                f"/l{a['layer']} (it holds {len(entries)})")
        owner, pitch_index = entries[a["ordinal"]]
        return owner, pitch_index, kind
    raise AddressError(f"addresses of kind {kind!r} cannot be operated on yet")


def resolve_elements(score, addresses: list) -> dict:
    """Resolve many addresses, keeping the ones that landed and reporting the
    rest rather than failing the whole operation.

    A selection outlives the version it was made on -- that is the point of
    addressing by staff/measure/layer rather than by a rendered id -- so some
    addresses legitimately no longer exist after an edit. The caller says how
    many were dropped; it never silently operates on a different set than the
    user chose.
    """
    resolved, missing = [], []
    for text in addresses:
        try:
            resolved.append((str(text),) + resolve_address(score, text))
        except AddressError as e:
            missing.append({"address": str(text), "why": str(e)})
    return {"resolved": resolved, "missing": missing}


ACCIDENTAL_NAMES = {
    "sharp": 1, "flat": -1, "natural": 0,
    "double-sharp": 2, "double-flat": -2,
}


def set_accidental(score, addresses: list, show: bool | None = None,
                   add: str | None = None, remove: bool = False,
                   color: str | None = None) -> dict:
    """Add, remove, show, hide or colour the accidentals on named elements.

    The manual counterpart to `normalize_accidentals`. Normalisation is what
    keeps a transformation from engraving accidentals the key already implies;
    this is for when the reader wants something other than the standard rule --
    a courtesy sharp kept in, a cancellation taken out, a note marked in
    colour while it is being worked on.

    Two of these change the MUSIC and three change only its DISPLAY, and the
    report says which happened to every element:

      add / remove    the note's actual accidental, so its PITCH changes
      show / hide     whether the glyph is drawn; the pitch is untouched
      color           what colour the glyph is drawn in; display only

    After a pitch change the affected parts are normalised, so an added
    accidental prints by the same key-signature-aware rule as everything else;
    an explicit --show or --hide is then applied on top and wins.

    Colour reaches the page: MusicXML `<accidental color=…>` becomes MEI
    `@color` and Verovio draws the glyph in it. `--color none` clears it.
    """
    if add is not None and add not in ACCIDENTAL_NAMES:
        raise ValueError(f"accidental must be one of {sorted(ACCIDENTAL_NAMES)}, not {add!r}")
    if add is not None and remove:
        raise ValueError("--add and --remove ask for opposite things")

    found = resolve_elements(score, addresses)
    if not found["resolved"]:
        raise AddressError(
            "none of those elements are in this score: "
            + "; ".join(m["why"] for m in found["missing"][:3]))

    changed, touched_parts = [], []
    for text, owner, pitch_index, _kind in found["resolved"]:
        if isinstance(owner, m21note.Rest):
            changed.append({"address": text, "skipped": "a rest has no accidental"})
            continue
        pitches = list(owner.pitches)
        index = 0 if pitch_index is None else pitch_index
        pitch = pitches[index]
        was = pitch.nameWithOctave

        if add is not None or remove:
            pitch.accidental = None if remove else m21pitch.Accidental(add)
            # a chord holds its pitches as a tuple; reassign or the edit is lost
            if pitch_index is not None:
                pitches[index] = pitch
                owner.pitches = tuple(pitches)
            holder = owner.getContextByClass(stream.Part)
            if holder is not None and not any(holder is p for p in touched_parts):
                touched_parts.append(holder)

        changed.append({"address": text, "pitch_before": was,
                        "pitch_now": pitch.nameWithOctave,
                        "pitch_changed": was != pitch.nameWithOctave})

    # the standard rule first, so an added accidental is engraved the way the
    # key says it should be...
    for part in touched_parts:
        _normalize_part(part)

    # ...and the explicit override second, so it wins
    for text, owner, pitch_index, _kind in found["resolved"]:
        if isinstance(owner, m21note.Rest):
            continue
        pitch = list(owner.pitches)[0 if pitch_index is None else pitch_index]
        if pitch.accidental is None:
            continue
        if show is not None:
            pitch.accidental.displayStatus = show
            # displayType would otherwise veto the status on export
            pitch.accidental.displayType = "always" if show else "never"
        if color is not None:
            pitch.accidental.style.color = None if color == "none" else color

    return {"elements": changed,
            "requested": len(addresses),
            "resolved": len(found["resolved"]),
            "pitch_changes": sum(1 for c in changed if c.get("pitch_changed")),
            "display": ({"shown": show} if show is not None else {}),
            "color": color,
            "missing": found["missing"]}


def transpose_elements(score, interval_str: str, addresses: list) -> dict:
    """Transpose ONLY the named elements.

    The operation selection exists for: Ali lassoed a chord, asked to move
    those notes up, and the whole bar moved -- because the selection was
    degraded to a measure range before the op ever saw it.
    """
    s = str(interval_str).strip()
    itv = (m21interval.Interval(int(s)) if re.fullmatch(r"-?\d+", s)
           else m21interval.Interval(s))
    found = resolve_elements(score, addresses)
    if not found["resolved"]:
        raise AddressError(
            "none of those elements are in this score: "
            + "; ".join(m["why"] for m in found["missing"][:3]))

    # Group by owner so a chord with two selected notes is transposed once per
    # pitch and never twice over the same pitch.
    moved = 0
    # the parts a selection actually landed in: only those get their
    # accidentals recomputed, so a lasso in one staff cannot restyle another
    touched_parts = []
    for _text, owner, pitch_index, kind in found["resolved"]:
        if isinstance(owner, m21note.Rest):
            continue
        holder = owner.getContextByClass(stream.Part)
        if holder is not None and not any(holder is p for p in touched_parts):
            touched_parts.append(holder)
        if pitch_index is None:
            owner.transpose(itv, inPlace=True)
        else:
            pitches = list(owner.pitches)
            pitches[pitch_index] = pitches[pitch_index].transpose(itv)
            owner.pitches = tuple(pitches)
        moved += 1
    hidden = sum(_normalize_part(p).get("hidden", 0) for p in touched_parts)
    return {"interval": itv.niceName,
            "direction": itv.direction.name.lower(),
            "elements_transposed": moved,
            "elements_requested": len(addresses),
            "redundant_accidentals_hidden": hidden,
            "missing": found["missing"]}


# ------------------------------------------------------------------ playback
#
# Playback reads the score twice and the two readings must not disagree: the
# MIDI a synthesiser plays, and the map saying which engraved bar each beat of
# it belongs to. So both come out of ONE object -- the performed score built
# here -- rather than being derived apart and hoped into agreement.
#
# Three things make the performed score differ from the engraved one. Each was
# measured against music21 10.5 before this was written:
#
#   - **Repeats are played out.** The MIDI writer expands them, so a four-bar
#     score whose first two bars repeat writes six bars of audio. The beat->bar
#     map is therefore one-to-MANY: bar 1 owns beats 0-3 AND beats 8-11.
#     Expanding here, explicitly, is what makes the map describe the audio.
#     Expanding an already-expanded stream is a no-op, so the writer's own pass
#     cannot double it.
#   - **Written pitch is not sounding pitch.** The writer emits what is on the
#     page, so a B-flat clarinet plays a whole tone sharp against everything
#     else. The fix belongs here and not in the app: the app cannot know a
#     part's transposition without re-reading the notation.
#   - **A bar is not four beats.** A pickup is a short bar whose clicks land at
#     the END of the grid, and 6/8 has two of them, not six. The click
#     positions are emitted rather than the rule for finding them, so nothing
#     downstream has to know any of that.

def _performed(score):
    """The score as it is PLAYED: repeats played out, written pitch made real.

    The two passes are attempted separately, because either can fail on
    material that arrived from optical recognition -- and neither failure is a
    reason to refuse playback. A score with a repeat music21 cannot resolve
    still plays; it plays straight through.
    """
    from music21 import harmony as m21harmony

    played = score
    # A REPEAT IS A FACT ABOUT THE BAR, NOT ABOUT ONE STAFF. Imate li vino, from
    # optical recognition, carried its repeat barline at bar 4 on the two piano
    # staves and not on the voice. music21 expands each part on its own, so the
    # piano came out 15 bars long and the voice 11: from the repeat onward the
    # voice's later bars sounded under the piano's repeated bars 1-4. Ali heard
    # "notes where there are no notes" and "the bottom voice misses the repeat",
    # and they were one fault. Every part gets the union of the repeat marks
    # before expansion, by measure position -- what `set-structure` already
    # does for marks this engine writes, applied to marks that arrived.
    played = _with_repeats_on_every_part(played)
    expanded = False
    try:
        candidate = played.expandRepeats()
        if candidate is not None and candidate.parts:
            if not _in_step(played, candidate):
                # Some mark one part carries and the others do not (a D.C., a
                # segno) sent the parts different ways. Out of step is the
                # one thing playback must never be, so the score plays
                # straight through rather than with one part a phrase behind.
                raise ValueError("the parts expanded to different lengths")
            played, expanded = candidate, True
    except Exception:
        # music21 could not resolve the repeats. Playing STRAIGHT THROUGH is the
        # promise made in this docstring, and it was not being kept: the
        # repeat barlines were left on the copy, and music21's MIDI writer
        # attempts the same expansion itself and raises the same
        # ExpanderException -- so a score with badly formed repeats refused to
        # play with a message about expansion, from a step that had "handled"
        # it. Reproduced with two repeat starts and one end, and with a
        # D.C. al Coda that has no coda. The marks are taken off the performed
        # copy so nothing downstream tries again; the page is untouched.
        played = _without_repeats(played)
    sounding = False
    try:
        candidate = played.toSoundingPitch()
        if candidate is not None and candidate.parts:
            played, sounding = candidate, True
    except Exception:
        pass
    # A CHORD SYMBOL IS A LABEL, NOT A NOTE, and until now playback did not
    # know that. `Fm` written over a staff is four letters on the page; a
    # ChordSymbol is a Chord in music21, so the MIDI writer sounded it.
    #
    # On Ali's own arrangement that is a whole phantom voice. `Acc. Chords` is
    # a names-only staff -- `strip-notes` empties a staff and keeps its chart
    # -- so it holds 0 notes and 135 symbols, and the MIDI came out with 485
    # note-ons in exactly the symbols' pitch range while the page shows no
    # notes at all on that staff. Turning it down changed something the reader
    # could not see, its activity lamp lit for music that is not written, and
    # "wrong instrument on the wrong staff" is a fair description of hearing
    # accordion chords from an empty staff.
    #
    # Removed from the PERFORMED copy only, which is a reading and not a
    # version, so the chart stays on the page and in every export. The same
    # trap `whistle_fingerings` and `guitar_tab` already guard against, now
    # guarded where it was loudest.
    symbols_silenced = 0
    for part in played.parts:
        for symbol in list(part.recurse().getElementsByClass(m21harmony.Harmony)):
            holder = symbol.activeSite
            if holder is not None:
                holder.remove(symbol)
                symbols_silenced += 1
    return played, {"repeats_expanded": expanded, "sounding_pitch": sounding,
                    "chord_symbols_silenced": symbols_silenced}


def _with_repeats_on_every_part(score):
    """Every part carries the union of the score's repeat barlines AND voltas,
    by bar.

    Works on a copy. Barlines are matched by measure INDEX within the part,
    not by number: OMR numbering is not trustworthy and the parts of one score
    are laid out bar for bar. A part shorter than the longest is left as it
    is beyond its own end.

    Voltas too, for the same reason and with a worse failure: a first and
    second ending written on the top staff alone (which is how optical
    recognition delivers them) makes music21 expand that part as 1-2-3-4,
    1-2-3-5 and every other part as 1-2-3-4, 1-2-3-4 -- one bar longer, and
    out of step with the melody from the second ending to the last note.
    """
    from music21 import bar as m21bar
    from music21 import spanner as m21spanner

    copy = _deep(score)
    parts = list(copy.parts)
    if len(parts) < 2:
        return copy
    per_part = [list(p.getElementsByClass(stream.Measure)) for p in parts]
    length = max(len(ms) for ms in per_part)
    for index in range(length):
        left = right = None
        for ms in per_part:
            if index < len(ms):
                if left is None and isinstance(ms[index].leftBarline, m21bar.Repeat):
                    left = ms[index].leftBarline
                if right is None and isinstance(ms[index].rightBarline, m21bar.Repeat):
                    right = ms[index].rightBarline
        for ms in per_part:
            if index < len(ms):
                if left is not None and not isinstance(ms[index].leftBarline, m21bar.Repeat):
                    ms[index].leftBarline = m21bar.Repeat(direction="start")
                if right is not None and not isinstance(ms[index].rightBarline, m21bar.Repeat):
                    ms[index].rightBarline = m21bar.Repeat(direction="end", times=right.times)
    # A volta is a bracket over a run of bars; carry each one, as INDICES, to
    # every part that has no bracket touching those bars.
    brackets = []
    for part, ms in zip(parts, per_part):
        position = {id(m): k for k, m in enumerate(ms)}
        for bracket in part.getElementsByClass(m21spanner.RepeatBracket):
            covered = [position[id(m)] for m in bracket.getSpannedElements() if id(m) in position]
            if covered:
                brackets.append((covered, bracket.number))
    for part, ms in zip(parts, per_part):
        taken = set()
        position = {id(m): k for k, m in enumerate(ms)}
        for bracket in part.getElementsByClass(m21spanner.RepeatBracket):
            taken.update(position[id(m)] for m in bracket.getSpannedElements() if id(m) in position)
        for covered, number in brackets:
            if taken & set(covered) or max(covered) >= len(ms):
                continue
            part.insert(0, m21spanner.RepeatBracket([ms[k] for k in covered], number=number))
            taken.update(covered)
    return copy


def _on_one_grid(played) -> list:
    """Every part's k-th bar starts on the same beat. Returns the grid: the
    length, in quarter notes, of each performed bar.

    music21 lays a part's bars out end to end by what each bar HOLDS, and a
    bar optical recognition filled past its meter -- six quarters in 3/4 --
    pushes every later bar of that one part late. Ali's own arrangement has
    fifteen such bars in the accordion's right hand and five in its bass, so
    at the last bar the right hand sounded twelve bars behind the violin and
    the bass four, while the map, read from the violin, agreed with neither.
    Measured: the sequencer's clock keeps pace with the audio device to
    0.05%; this was the whole of the play head's drift.

    The page already answers what to do. Verovio draws one barline through
    all the staves, so an overfull bar is a wide bar for EVERY part, with the
    shorter parts' notes in its left portion. The grid is that: each bar as
    long as the longest part's reading of it, every part's bar k placed at
    the same start, nothing cut and nothing overlapped.
    """
    per_part = [list(p.getElementsByClass(stream.Measure)) for p in played.parts]
    if not per_part:
        return []
    length = max(len(ms) for ms in per_part)
    grid = [max(float(ms[k].duration.quarterLength) for ms in per_part if k < len(ms))
            for k in range(length)]
    starts, at = [], 0.0
    for span in grid:
        starts.append(at)
        at += span
    for part, ms in zip(played.parts, per_part):
        for k, measure in enumerate(ms):
            if abs(float(measure.offset) - starts[k]) > 1e-9:
                part.setElementOffset(measure, starts[k])
    return grid


def _in_step(before, after) -> bool:
    """Did every part that had the same bar count before expansion keep the
    same bar count as each other after it?"""
    counts_before = [len(p.getElementsByClass(stream.Measure)) for p in before.parts]
    counts_after = [len(p.getElementsByClass(stream.Measure)) for p in after.parts]
    if len(counts_before) != len(counts_after):
        return False
    for i in range(len(counts_before)):
        for j in range(i + 1, len(counts_before)):
            if counts_before[i] == counts_before[j] and counts_after[i] != counts_after[j]:
                return False
    return True


def _without_repeats(score):
    """The score with every repeat barline made plain and every repeat
    expression (D.C., D.S., segno, coda, fine) removed -- so it plays straight
    through and nothing downstream attempts an expansion that has already
    failed. Works on a copy; the notation on the page is not touched."""
    from music21 import bar as m21bar
    from music21 import repeat as m21repeat

    copy = _deep(score)
    for part in copy.parts:
        for measure in part.getElementsByClass(stream.Measure):
            if isinstance(measure.leftBarline, m21bar.Repeat):
                measure.leftBarline = None
            if isinstance(measure.rightBarline, m21bar.Repeat):
                measure.rightBarline = m21bar.Barline("regular")
        for mark in list(part.recurse().getElementsByClass(m21repeat.RepeatMark)):
            holder = mark.activeSite
            if holder is not None:
                holder.remove(mark)
    return copy


def _deep(score):
    import copy as _copy
    return _copy.deepcopy(score)


def _timeline_spine(played):
    """The part the bar map is read from: the one with the most bars.

    Not simply the first. A part can be shorter than the score -- an instrument
    that enters late, a staff optical recognition cut short -- and a map read
    from it ends the score early, which on screen is a play head that stops
    following partway through.
    """
    parts = list(played.parts)
    return max(parts, key=lambda p: len(p.getElementsByClass(stream.Measure))) if parts else None


def _first_clef_name(part) -> str | None:
    """What clef this staff opens in, as a word ("treble", "bass"), or None.

    The first one only: a staff that changes clef mid-piece is still "the bass
    staff" to the reader who is looking for it in a mixer.
    """
    for clef in part.recurse().getElementsByClass(m21clef.Clef):
        # The same spelling `info` uses, so the two describe one staff the
        # same way: the class name with "Clef" taken off it.
        name = type(clef).__name__.replace("Clef", "").lower()
        if name:
            return name
    return None


def _sounding_intervals(part, epsilon: float = 1e-6) -> list:
    """When this staff is making a noise, as MERGED intervals in quarter notes.

    For the mixer's activity LED, which asks one question twenty times a second:
    is this staff sounding right now. Per-NOTE data would answer it too, and a
    136-bar quartet is thousands of entries -- so contiguous notes are merged
    and a part playing continuously through eight bars costs ONE pair rather
    than thirty. A rest breaks the interval, which is exactly the moment the
    LED should go dark.

    Offsets are taken in the PERFORMED score's hierarchy, so a repeat that
    sounds twice produces intervals covering both passes -- the same timebase
    the bar map and the MIDI use.
    """
    spans = []
    for element in part.recurse().notes:
        start = float(element.getOffsetInHierarchy(part))
        length = float(element.duration.quarterLength)
        if length <= 0:
            continue
        spans.append((start, start + length))
    if not spans:
        return []
    spans.sort()
    merged = [list(spans[0])]
    for start, end in spans[1:]:
        # Touching counts as continuous: a crotchet followed straight by
        # another is one sound to a reader watching a lamp, not two.
        if start <= merged[-1][1] + epsilon:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    return [[round(a, 6), round(b, 6)] for a, b in merged]


def playback_timeline(score) -> tuple:
    """The performed score, and the map from its beats back to the page.

    Beats are QUARTER NOTES, which is the unit an iOS `AVAudioSequencer`
    reports its play head in, so nothing has to convert between the two.
    """
    from music21 import meter as m21meter
    from music21 import tempo as m21tempo

    played, flags = _performed(score)
    widths = _on_one_grid(played)
    spine = _timeline_spine(played)

    bars, clicks = [], []
    signature = None
    if spine is not None:
        for k, measure in enumerate(spine.getElementsByClass(stream.Measure)):
            signature = measure.timeSignature or signature or m21meter.TimeSignature("4/4")
            start = float(measure.offset)
            # The bar's length on the shared grid, not this part's reading of
            # it: see _on_one_grid.
            span = widths[k] if k < len(widths) else float(measure.duration.quarterLength)
            unit = float(signature.beatDuration.quarterLength) or 1.0
            pad = float(measure.paddingLeft or 0)
            bars.append({"measure": int(measure.number), "start": start,
                         "end": start + span, "meter": signature.ratioString,
                         "pickup": pad > 0})
            # The grid belongs to the WHOLE bar and a short bar takes the tail
            # of it, which is why a pickup's click is not a downbeat.
            grid = pad
            while grid < pad + span - 1e-6:
                clicks.append({"beat": start + (grid - pad), "down": grid < 1e-6})
                grid += unit

    marks = list(played.recurse().getElementsByClass(m21tempo.MetronomeMark))
    tempos = [{"beat": float(m.getOffsetInHierarchy(played)),
               "bpm": float(m.getQuarterBPM() or 120.0)} for m in marks]
    # music21 writes 120 when a score names no tempo. Said out loud rather than
    # left implicit: "120 (default)" is a different thing for a reader to see
    # than a tempo the arranger chose.
    if not tempos:
        tempos = [{"beat": 0.0, "bpm": 120.0}]

    parts = []
    for index, part in enumerate(played.parts):
        found = part.getInstrument(returnDefault=False)
        # EXACTLY what the staff is called on the page, duplicates and all.
        # Optical recognition labels every unlabeled staff "Voice", so a
        # scanned quartet really is four parts called "Voice" -- and the mixer
        # says so, because a strip that called itself something the page does
        # not is a strip the reader cannot match to a staff. The fix for
        # duplicate names is renaming the parts with the tools that already
        # exist. A channel is keyed on its INDEX, which is why duplicate
        # labels are harmless here.
        parts.append({
            "index": index,
            "name": part_label(part),
            "instrument": getattr(found, "instrumentName", None),
            # None where the part names no instrument, which is every staff
            # optical recognition labels "Voice". Honest beats a wrong guess:
            # the player falls back to its own documented default.
            "program": getattr(found, "midiProgram", None),
            # The clef this staff is written in, so a repeated NAME can still
            # be told apart by what the reader sees on the page. A grand staff
            # is ONE MusicXML part and music21 splits it into two PartStaffs
            # that both answer "Piano", so the mixer showed Piano and Piano --
            # correct per staff, and unnameable. The name stays exact, as
            # above; this is what lets the label say which of them is which.
            "clef": _first_clef_name(part),
            "sounding": _sounding_intervals(part),
        })

    return played, {
        "parts": parts,
        "bars": bars,
        "clicks": clicks,
        "tempos": tempos,
        "tempo_from_score": bool(marks),
        "beats": bars[-1]["end"] if bars else 0.0,
        "written_bars": (len(score.parts[0].getElementsByClass(stream.Measure))
                         if score.parts else 0),
        "performed_bars": len(bars),
        **flags,
    }


# -- pagination --------------------------------------------------------------
#
# WHERE THE SYSTEMS BREAK, written into the notation as MusicXML
# `<print new-system="yes"/>` (music21's `layout.SystemLayout(isNew=True)`) so
# it travels with the score like everything else here.
#
# THE ONE THING TO KNOW ABOUT VEROVIO HERE, measured rather than assumed
# (engine/scripts/check_pagination.py keeps the measurement):
#
#     breaks=auto      lays the music out itself and IGNORES encoded breaks
#     breaks=encoded   breaks ONLY where the notation says, and nowhere else
#     breaks=smart     honours some and re-flows the rest
#
# `encoded` is what a reader who asked for four bars a line means -- and ONLY
# for a score the reader paginated. It was asked for unconditionally first, and
# the release gate caught what that did: a MusicXML file from MuseScore,
# Finale, Sibelius or Audiveris carries its SOURCE EDITION's breaks, and the
# string-quartet fixture went from Verovio's 8 pages to its publisher's 4, at
# eight and a half bars a line. Those breaks were made for another engraver's
# page and staff size; after `keep-parts` a four-staff layout's page breaks
# would strand one staff on mostly empty pages. So the reader's pagination is
# MARKED (PAGINATION_FIELD) and the renderers ask for `encoded` only on a
# marked score -- render.breaks_for and EngravingOptions.breaks. Every other
# score lays out exactly as it always has.
#
# The trap is the other half. Because `encoded` breaks ONLY where told, ONE
# break on a sixty-bar piece does not mean "and lay the rest out sensibly" --
# it means one short system and then fifty-odd bars crushed into a single line,
# which Verovio reports as "Justification is highly compressed" and a reader
# sees as a garbled page. So THIS OP ALWAYS WRITES A COMPLETE PAGINATION:
# every system's start, from the first bar to the last. There is no way to ask
# it for a lone break, because there is no way to draw one.
#: How many notes a line of the page holds comfortably, for choosing a line
#: length when nobody said one. Read off Verovio's own layout at this app's
#: page and scale: a reel (eight quavers a bar) comes out four bars to a line,
#: a jig six or seven -- about thirty-two notes a line either way. This is an
#: ESTIMATE from note counts, not a measurement of the page, and the report
#: says what it chose so the reader can ask for another.
NOTES_PER_LINE = 32

#: Line lengths a musician reads as phrases. Tunes are built of 4- and 8-bar
#: phrases, so a choice prefers these over the largest number that would fit:
#: a jig that would fit seven bars a line is laid out at four.
_PHRASE_LENGTHS = (8, 4, 3, 2, 1)


def _notes_per_bar(score) -> list[int]:
    """Distinct attacks per bar in the busiest part -- what a line's width
    is mostly made of."""
    from music21 import harmony as m21harmony

    per_bar: dict[int, int] = {}
    for part in score.parts:
        for m in part.getElementsByClass(stream.Measure):
            # a chord symbol is a Chord in music21, and is not a note anyone plays
            onsets = {round(float(n.offset), 4) for n in m.recurse().notesAndRests
                      if not isinstance(n, m21harmony.Harmony)}
            per_bar[m.number] = max(per_bar.get(m.number, 0), len(onsets))
    return list(per_bar.values())


def natural_measures_per_line(score) -> int:
    """A reasonable number of bars to a line, chosen from how busy they are.

    The most bars that fit `NOTES_PER_LINE`, rounded DOWN to a phrase length
    (8, 4, 3, 2) -- never fewer than one.
    """
    counts = [c for c in _notes_per_bar(score) if c > 0]
    mean = (sum(counts) / len(counts)) if counts else 4.0
    fits = max(1, int(NOTES_PER_LINE // max(mean, 1.0)))
    return next(n for n in _PHRASE_LENGTHS if n <= fits)


#: The mark a reader's own pagination carries, as
#: <miscellaneous-field name="scoranger-pagination">reader</miscellaneous-field>.
#: Its presence -- and nothing else -- tells both renderers to honour the breaks.
PAGINATION_FIELD = "scoranger-pagination"


def reader_paginated(score) -> bool:
    """Has the READER laid this score out, as opposed to its source edition?"""
    md = score.metadata
    return bool(md is not None and md.getCustom(PAGINATION_FIELD))


def _mark_reader_pagination(score, on: bool) -> None:
    from music21 import metadata as m21metadata
    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    score.metadata.setCustom(PAGINATION_FIELD, "reader" if on else [])


def _measure_numbers(part) -> list[int]:
    return [m.number for m in part.getElementsByClass(stream.Measure)]


def system_break_bars(score) -> list[int]:
    """The bars that START a system, as the notation currently says.

    Read from the FIRST part: a system break is a property of the system, so
    the op writes one to every staff and they agree by construction.
    """
    if not score.parts:
        return []
    bars = []
    for m in score.parts[0].getElementsByClass(stream.Measure):
        if any(sl.isNew for sl in m.getElementsByClass(m21layout.SystemLayout)):
            bars.append(m.number)
    return sorted(bars)


def _fill_runs(starts: set[int], numbers: list[int], per_line: int,
               forced: frozenset[int] = frozenset(),
               joins: frozenset[int] = frozenset(),
               pickup: int | None = None) -> set[int]:
    """Break any stretch longer than `per_line` until none is.

    The forced breaks are kept exactly where they were asked for; only the
    stretches BETWEEN them are subdivided, so "a new line at bar 17" keeps bar
    17 at the head of a line however the rest falls out.

    A stretch that ENDS at a forced break is evened out rather than filled
    from the left: ending a line at bar 10 of a four-bars-a-line tune gives
    4, 3, 3 rather than 4, 4 and a stranded 2. The last stretch, which ends
    with the music, is filled from the left at `per_line`, so only the final
    line is short.

    A last line of a single bar is evened out the same way, because a bar
    stranded alone is not a layout anyone would choose.

    `joins` are bars the reader said must NOT start a line; a break that would
    land on one moves to the next bar that may take it.

    `pickup` is an upbeat bar, which rides in front of the first line without
    counting toward it -- an engraver sets a four-bar line as the pickup plus
    bars 1-4, so the lines start on the phrases.
    """
    out = set(starts)
    ordered = [n for n in numbers if n in out] or [numbers[0]]
    for index, start in enumerate(ordered):
        end = ordered[index + 1] if index + 1 < len(ordered) else None
        run = [n for n in numbers
               if n >= start and (end is None or n < end)]
        lead = 1 if pickup is not None and run and run[0] == pickup else 0
        if len(run) - lead <= per_line:
            continue
        counted = len(run) - lead
        stranded = end is None and counted % per_line == 1 and per_line >= 3
        if (end is not None and end in forced) or stranded:
            lines = -(-counted // per_line)
            base, extra = divmod(counted, lines)
            cuts, at = [], lead
            for line in range(lines - 1):
                at += base + (1 if line < extra else 0)
                cuts.append(at)
        else:
            cuts = list(range(per_line + lead, len(run), per_line))
        last = 0
        for cut in cuts:
            cut = max(cut, last + 1)
            while cut < len(run) and run[cut] in joins:
                cut += 1
            if cut < len(run):
                out.add(run[cut])
                last = cut
    return out


#: What the reader ASKED for, kept beside the breaks it produced:
#: <miscellaneous-field name="scoranger-pagination-forced">per=4;starts=11;joins=9
#: -- the line length, the bars that must start a line, and the bars that must
#: not. Without it every break on the page looks alike, and ending a line at
#: bar 10 of a four-bars-a-line tune kept the old breaks at 5, 9 and 13 around
#: the new one at 11: lines of 4, 4, 2, 2, 4. With it, the filled-in breaks are
#: derived again around what was asked for, every time.
PAGINATION_FORCED_FIELD = "scoranger-pagination-forced"


def number_bars_from_one(score) -> int:
    """Number the first full bar 1, as every page does. Returns the shift (0 or 1).

    music21's ABC reader numbers a tune from 0 whether or not it opens with a
    pickup, and a MusicXML import is numbered from 1. So in an ABC tune with no
    upbeat the first FULL bar was bar 0 everywhere -- the chat counted it as
    "bar 1" and skipped it, and Ali's chords started a bar late: "when I say
    put chord measures, it should start at the first bar" (0.17.0). A bar 0
    that IS an upbeat (paddingLeft, as `bar_label` reads it) stays 0: it is
    "the pickup", and the bar after it is already 1.

    Every part moves together, and the reader's forced line breaks move with
    their bars.
    """
    if not score.parts:
        return 0
    first = next(iter(score.parts[0].getElementsByClass(stream.Measure)), None)
    if first is None or first.number != 0 or float(getattr(first, "paddingLeft", 0) or 0) > 0:
        return 0
    for part in score.parts:
        for m in part.getElementsByClass(stream.Measure):
            m.number += 1
    per, starts, joins = _read_forced(score)
    if per is not None:
        _write_forced(score, per, {n + 1 for n in starts}, {n + 1 for n in joins})
    return 1


def _pickup_bar(score) -> int | None:
    """The upbeat's number, if the music opens with one -- a short first bar,
    as `bar_label` recognises it."""
    measures = list(score.parts[0].getElementsByClass(stream.Measure)) if score.parts else []
    if measures and float(getattr(measures[0], "paddingLeft", 0) or 0) > 0:
        return measures[0].number
    return None


def _read_forced(score) -> tuple[int | None, set[int], set[int]]:
    md = score.metadata
    raw = md.getCustom(PAGINATION_FORCED_FIELD) if md is not None else []
    per, starts, joins = None, set(), set()
    for part in (str(raw[0]) if raw else "").split(";"):
        key, _, value = part.partition("=")
        numbers = [int(x) for x in value.split(",") if x.strip().lstrip("-").isdigit()]
        if key == "per" and numbers:
            per = numbers[0]
        elif key == "starts":
            starts = set(numbers)
        elif key == "joins":
            joins = set(numbers)
    return per, starts, joins


def _write_forced(score, per: int | None, starts: set[int], joins: set[int]) -> None:
    from music21 import metadata as m21metadata
    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    if per is None:
        score.metadata.setCustom(PAGINATION_FORCED_FIELD, [])
        return
    text = f"per={per}"
    if starts:
        text += ";starts=" + ",".join(str(n) for n in sorted(starts))
    if joins:
        text += ";joins=" + ",".join(str(n) for n in sorted(joins))
    score.metadata.setCustom(PAGINATION_FORCED_FIELD, text)


def paginate(score, measures_per_line: int | None = None,
             break_at: list[int] | None = None,
             remove_at: list[int] | None = None,
             clear: bool = False,
             end_at: list[int] | None = None) -> dict:
    """Lay the music out in lines, or hand it back to the engraver.

    `clear` takes every encoded break off, which is how a reader asks for the
    automatic layout back -- Verovio then breaks where it judges best, which is
    what an untouched score has always done.

    `measures_per_line` lays the whole score out at that length, forgetting
    any line the reader forced before (unless this call forces one too).
    `break_at` makes those bars START a line; `end_at` makes those bars END
    one -- "end the line at bar 12" is a new line at 13 -- which is how a
    reader says it. `remove_at` takes a break off: a forced one is forgotten,
    and one the op filled in becomes a bar that must not start a line.

    Forced breaks are remembered (PAGINATION_FORCED_FIELD) and every other
    break is derived again around them each time, at the score's line length:
    the one it remembers, or failing that the one its existing layout shows,
    or failing that one CHOSEN from how busy the bars are
    (`natural_measures_per_line`) -- and the report says when it chose.

    The first bar always starts a system and carries no break of its own: a
    `<print new-system="yes"/>` on the first measure is what tells Verovio to
    leave an empty system above the music.
    """
    if not score.parts:
        raise ValueError("this score has no parts to paginate")
    numbers = _measure_numbers(score.parts[0])
    if not numbers:
        raise ValueError("this score has no measures to paginate")
    first = numbers[0]

    # Only the READER's breaks are the score's own line length. A score that
    # arrived with its publisher's layout has breaks too, made for another
    # page, and paginating replaces them rather than inheriting their length.
    mine = reader_paginated(score)
    existing = system_break_bars(score) if mine else []
    remembered_per, remembered_starts, remembered_joins = (
        _read_forced(score) if mine else (None, set(), set()))
    if clear:
        _, removed = _write_system_breaks(score, set())
        _mark_reader_pagination(score, False)
        _write_forced(score, None, set(), set())
        return {"clear": True, "breaks_removed": removed,
                "layout": "automatic -- Verovio breaks where it judges best"}

    known = [n for n in numbers if n != first]
    ending: list[int] = []
    for bar in end_at or []:
        if bar not in numbers:
            raise ValueError(
                f"bar {bar} cannot end a line: this score has bars "
                f"{numbers[0]}-{numbers[-1]}")
        if bar != numbers[-1]:          # the last bar ends the last line anyway
            ending.append(numbers[numbers.index(bar) + 1])
    for bar in (break_at or []) + (remove_at or []):
        if bar not in known:
            raise ValueError(
                f"bar {bar} cannot start a line: this score has bars "
                f"{numbers[0]}-{numbers[-1]}" +
                (f", and bar {first} already starts the first one"
                 if bar == first else ""))

    per_line = measures_per_line
    chosen = False
    if per_line is None:
        per_line = remembered_per or _inferred_per_line(existing, numbers)
    if per_line is None:
        per_line = natural_measures_per_line(score)
        chosen = True
    if per_line < 1:
        raise ValueError("a line holds at least one bar")

    asked = set(break_at or []) | set(ending)
    if measures_per_line is not None:
        forced, joins = set(asked), set()
    else:
        forced, joins = remembered_starts | asked, set(remembered_joins)
    joins -= asked
    for bar in remove_at or []:
        if bar in forced:
            forced.discard(bar)
        else:
            joins.add(bar)
    forced.discard(first)

    starts = _fill_runs({first} | forced, numbers, per_line,
                        frozenset(forced), frozenset(joins), _pickup_bar(score))

    written, _ = _write_system_breaks(score, starts - {first})
    _mark_reader_pagination(score, True)
    _write_forced(score, per_line, forced, joins)
    heads = sorted(starts)
    lengths = [((heads[i + 1] if i + 1 < len(heads) else numbers[-1] + 1) - head)
               for i, head in enumerate(heads)]
    return {
        "measures_per_line": per_line,
        "systems": len(heads),
        "line_starts": heads,
        "bars_per_line": lengths,
        "breaks_written": written,
        "forced": sorted(set(break_at or [])),
        "lines_end_at": sorted(set(end_at or [])),
        "removed": sorted(set(remove_at or [])),
        # said, so a reader who wanted another length knows to ask for it
        "measures_per_line_chosen": chosen,
        # said so a caller knows the page now follows these lines, and how to
        # hand it back
        "note": ("marked as the reader's own layout, so the page follows these "
                 "lines; clear hands it back to the engraver"
                 + (f". Nobody had set a line length, so {per_line} bars a line "
                    "was chosen from how busy the bars are; ask for another "
                    "with measures_per_line" if chosen else "")),
    }


def _inferred_per_line(existing: list[int], numbers: list[int]) -> int | None:
    """The score's own line length, read off the pagination it already has."""
    if len(existing) < 1:
        return None
    heads = sorted({numbers[0]} | set(existing))
    gaps = [heads[i + 1] - heads[i] for i in range(len(heads) - 1)]
    if not gaps:
        return None
    return max(set(gaps), key=gaps.count)


def _write_system_breaks(score, starts: set[int]) -> tuple[int, int]:
    """Put a break at the head of each named bar on EVERY staff, and nowhere else.

    On every staff because a system break is a property of the SYSTEM: written
    to the top staff alone, music21's grand-staff merge drops it -- the same
    trap `set_structure` records for voltas.

    A source edition's PAGE breaks go too. Under `encoded` Verovio honours them,
    so a reader's four-bars-a-line would otherwise still turn the page wherever
    the publisher did. The reader's layout replaces the source's whole.
    """
    written = removed = 0
    for part in score.parts:
        for m in part.getElementsByClass(stream.Measure):
            for old in list(m.getElementsByClass(m21layout.SystemLayout)):
                if old.isNew:
                    m.remove(old)
                    removed += 1
            for old in list(m.getElementsByClass(m21layout.PageLayout)):
                if old.isNew:
                    m.remove(old)
                    removed += 1
            if m.number in starts:
                m.insert(0.0, m21layout.SystemLayout(isNew=True))
                written += 1
    return written, removed


# -- staff spacing -----------------------------------------------------------
#
# How much room the page gives between staves, between systems, and to a
# whistle's fingering column -- stored in the notation as
# <miscellaneous-field name="scoranger-spacing"> and read by both renderers
# (render.spacing_from_musicxml and ios/.../StaffSpacing.swift). The field is
# the only way this can travel with the score: music21 writes MusicXML's own
# <staff-layout>/<system-layout> correctly and Verovio ignores both, at every
# value.

def _measure_numbers_described(numbering: tuple[str, int]) -> str:
    mode, every = numbering
    if mode == "none":
        return "no measure numbers"
    if mode == "every":
        return "every bar" if every == 1 else f"every {every} bars (the bars whose number divides by {every})"
    return "the first bar of every line (the engraver's default)"


def measure_numbers(score, every: int | None = None, system: bool = False,
                    none: bool = False, reset: bool = False) -> dict:
    """Where the page numbers its bars. Exactly one of the four.

    `every` numbers every Nth bar -- 1 is every bar, 3 the bars whose number
    divides by three; `system` numbers the first bar of each line, which is
    what an untouched score does; `none` numbers nothing; `reset` is `system`.
    Stored in the notation (render.MEASURE_NUMBERS_FIELD) so it versions and
    travels; both renderers draw it. The default is not written at all.
    """
    from music21 import metadata as m21metadata

    from . import render

    asked = [name for name, on in (("every", every is not None), ("system", system),
                                   ("none", none), ("reset", reset)) if on]
    if len(asked) != 1:
        raise ValueError("say exactly one of: every N bars, the first bar of "
                         "each line (system), none, or reset"
                         + (f" -- got {', '.join(asked)}" if asked else ""))
    if every is not None:
        lo, hi = render.MEASURE_NUMBERS_EVERY_RANGE
        if not lo <= every <= hi:
            raise ValueError(f"every must be between {lo} and {hi}; {every} is not")
    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    current = score.metadata.getCustom(render.MEASURE_NUMBERS_FIELD)
    before = render.parse_measure_numbers(str(current[0]) if current else "")
    if every is not None:
        stored, after = f"every={every}", ("every", every)
    elif none:
        stored, after = "none", ("none", 0)
    else:
        stored, after = "", ("system", 0)
    score.metadata.setCustom(render.MEASURE_NUMBERS_FIELD, stored if stored else [])
    return {"measure_numbers": _measure_numbers_described(after),
            "was": _measure_numbers_described(before),
            "changed": after != before}


def staff_spacing(score, staff: int | None = None, system: int | None = None,
                  fingering_rows: int | None = None, reset: bool = False) -> dict:
    """Open or close the space on the page. Only the values given change.

    `staff` and `system` are the minimum space between staves and between
    systems, in MEI units (Verovio's own `spacingStaff` and `spacingSystem`).
    They are MINIMUMS: they open space up and cannot take back space the music
    itself claims -- a staff with a whistle column above it is as tall as its
    column. `fingering_rows` is that column's band: how many lyric rows are
    reserved for its six holes. Four is the tightest the drawn column fits
    inside (render.DEFAULT_FINGERING_ROWS says why); six is the layout every
    build before 0.13.0 drew.

    `reset` takes the score back to the defaults. A setting equal to its
    default is not written at all, so a score nobody has spaced carries no
    field.
    """
    from music21 import metadata as m21metadata

    from . import render

    ranges = {"staff": render.SPACING_RANGE, "system": render.SPACING_RANGE,
              "rows": render.FINGERING_ROWS_RANGE}
    asked = {"staff": staff, "system": system, "rows": fingering_rows}
    names = {"staff": "staff", "system": "system", "rows": "fingering_rows"}
    for key, value in asked.items():
        if value is None:
            continue
        lo, hi = ranges[key]
        if not lo <= value <= hi:
            raise ValueError(
                f"{names[key]} must be between {lo} and {hi}; {value} is not"
                + (" -- four rows is the tightest a whistle column fits "
                   "without reaching into the space above its staff"
                   if key == "rows" and value < lo else ""))

    defaults = render.parse_spacing_value("")
    if score.metadata is None:
        score.metadata = m21metadata.Metadata()
    current = score.metadata.getCustom(render.SPACING_FIELD)
    before = render.parse_spacing_value(str(current[0]) if current else "")
    after = dict(defaults) if reset else dict(before)
    for key, value in asked.items():
        if value is not None:
            after[key] = value

    stored = ";".join(f"{k}={after[k]}" for k in ("staff", "system", "rows")
                      if after[k] != defaults[k])
    score.metadata.setCustom(render.SPACING_FIELD, stored if stored else [])
    return {
        "staff": after["staff"],
        "system": after["system"],
        "fingering_rows": after["rows"],
        "changed": sorted(names[k] for k in after if after[k] != before[k]),
        "reset": reset,
        "defaults": {"staff": defaults["staff"], "system": defaults["system"],
                     "fingering_rows": defaults["rows"]},
        # said so a caller that asks for tighter staves and sees no change
        # knows why rather than asking again
        "note": ("staff and system are minimums: they open space up but "
                 "cannot close space the music itself needs"),
    }
